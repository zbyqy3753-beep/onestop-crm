import "server-only";

import { revalidatePath } from "next/cache";

/**
 * ריענון הקאש אחרי מוטציה.
 *
 * הפעולות רענו עד כה רק את המסך שממנו נקראו, אבל אותם נתונים מוצגים
 * בכמה מקומות: הדשבורד (`/`) סופר לידים לפי סטטוס וסוג ובונה את לוח
 * המובילים, ו-`/deals` נשען על עלויות הלידים לחישוב רווח. בלי הריענון
 * הרחב, שינוי סטטוס במסך הלידים הותיר את הדשבורד עם המספרים הישנים
 * עד לטעינה מחדש.
 *
 * שלושה נתיבים למוטציה זה זול בסדר הגודל הזה, והחלופה — לנחש איזה
 * מסך "כנראה לא הושפע" — היא בדיוק סוג ההנחה שיצרה את הבאג.
 */

/** כל מסך שמציג לידים או נגזרת שלהם. */
export function revalidateLeadSurfaces(): void {
  revalidatePath("/leads");
  revalidatePath("/");
  revalidatePath("/deals");
}

/**
 * שינוי במצבת המשתמשים. מלבד מסך הניהול, שמות העובדים מופיעים
 * בבוררי השיוך במסך הלידים ובלוח המובילים בדשבורד — עובד חדש שלא
 * הופיע ברשימת השיוך היה נראה כמו באג ביצירת המשתמש.
 */
export function revalidateUserSurfaces(): void {
  revalidatePath("/admin");
  revalidatePath("/leads");
  revalidatePath("/");
}
