/**
 * עלות התקנה שהרשומה מתנה ב**סוג הבית**, והמספר שבמפרט הוא צד אחד שלה בלבד.
 *
 * ⚠️ `installationCost` הוא שדה אחד, והפרוזה של הקטלוג הביתי מוכרת שני
 * מחירים: 21 מתוך 33 החבילות הביתיות אומרות "בבניין X / בית פרטי Y".
 * `installationCost === 0` תורגם ל-"ללא עלות" כעובדה גורפת — id 115
 * ("עלות התקנה : בבנין0 שח בית פרטי 499שח"), id 73 ("0 ש"ח לבניין לזמן
 * מוגבל , 125 ש"ח לבית פרטי") ו-id 3 ("התקנה ללא עלות בבניין בית פרטי
 * 499") כולן הדפיסו "התקנה: ללא עלות" מול תשלום חד-פעמי של מאות
 * שקלים. זה הפער הכספי הגדול ביותר שכרטיס בדף הזה יכול להסתיר, והוא
 * אותה מחלקת פגם שכבר נסגרה ב-`discountIsCapped` ו-`proseCapsAt`:
 * הפרוזה מתנה, והמפרט שכח את התנאי.
 *
 * ⚠️ המספר של הבית הפרטי נקרא בשני סדרים — "125 ש"ח **ל**בית פרטי"
 * (לפני) ו-"בית פרטי 499שח" (אחרי) — והצורה שלפני דורשת את ה-`ל`:
 * בלעדיו "בבנין0 שח בית פרטי" נקרא כ-0 לבית פרטי, כלומר השער היה
 * מדפיס את ההפוך מהרשומה. הצורה שאחרי דורשת סימן מטבע, מאותו טעם.
 */
function installationProse(pkg: Package): string {
  return [logicName(pkg), pkg.description, pkg.benefits].filter(Boolean).join(" ");
}

function privateHomeInstallation(pkg: Package): number | null {
  const prose = installationProse(pkg);
  const before = prose.match(/(\d[\d,]*(?:\.\d+)?)\s*(?:ש"ח|שח|₪)\s*לבית\s*פרטי/);
  if (before) return Number(before[1].replace(/,/g, ""));
  const after = prose.match(/בית\s*פרטי[^\d%]{0,40}?(\d[\d,]*(?:\.\d+)?)\s*(?:ש"ח|שח|₪)/);
  if (after) return Number(after[1].replace(/,/g, ""));
  return null;
}

/**
 * הרשומה מתנה את ההתקנה בסוג הבית — גם כשלא נקרא ממנה מספר.
 *
 * ⚠️ מיוצאת כי יש **צרכן רביעי** מחוץ לדף: `src/lib/posts/catalog.ts`
 * (סטודיו הפוסטים) פרסם `installationCost` גולמי, ולכן "0" הודפס
 * "התקנה: ללא עלות" על 15 רשומות שהפרוזה שלהן מוכרת 125/499 ש"ח לבית
 * פרטי. זה בדיוק הדפוס שחזר כאן שבע פעמים — שער שחובר לכרטיס ולא לשאר
 * המשטחים שמדפיסים את אותו שדה — ובפוסט הוא גרוע מבאתר: המספר מתפרסם
 * בשם של אלירן, והקובץ שמייצר אותו מצהיר בהערה שלו שמספר שאינו מה
 * שהגולש רואה הוא הסתירה שהפוסטים טוענים לחשוף.
 */
export function installationIsConditional(pkg: Package): boolean {
  const prose = installationProse(pkg);
  if (!/התקנ/.test(prose)) return false;
  return /בית\s*פרטי/.test(prose) || /\d\s*דירות/.test(prose);
}

/**
 * התנאי שהפרוזה תולה בו דווקא את **צד הבניין**, כלומר את המספר שבמפרט.
 *
 * ⚠️ `installationIsConditional` סגר את "0 ⇒ חינם גורף", אבל הצד השני
 * של אותו משפט נשאר מתפרסם כעובדה: ids 157, 92, 102, 107, 108, 109
 * אומרות "עלות התקנה מתחת ל 4 דירות **או בית פרטי** 499 ש"ח / **מעל 4
 * דירות** ללא עלות התקנה" — כלומר ה-0 שבמפרט הוא המחיר של בניין מעל
 * ארבע דירות בלבד, והתווית "בבניין" הבטיחה אותו לכל מי שאינו בבית
 * פרטי. גולש בבניין של שלוש דירות קרא "ללא עלות" מול 499 ש"ח, וזו
 * בדיוק הרשומה שהמחשבון מצטט בכל קלט במסלול הבית.
 *
 * ⚠️ ו-ids 73, 153, 154, 159 אומרות "0 ש"ח לבניין **לזמן מוגבל**" —
 * מבצע בתוקף, לא תכונה של החבילה. אותו כלל של `discountIsCapped`
 * ו-`proseCapsAt`: הפרוזה מתנה, והתווית מוותרת על התנאי.
 *
 * התנאי נלקח **מהטקסט עצמו** ולא מושלם: רשומה שאין בה אחת משתי
 * התבניות נשארת עם "בבניין" כשהיתה.
 */
function housingQualifiers(pkg: Package): { building: string; privateHome: string } {
  const prose = installationProse(pkg);
  const apartments = prose.match(/מעל\s*(\d+)\s*דירות[^.|]{0,24}?ללא\s*עלות/);
  if (apartments) {
    return {
      building: `בבניין מעל ${apartments[1]} דירות`,
      privateHome: `לבית פרטי או עד ${apartments[1]} דירות`,
    };
  }
  if (/לבניין\s*לזמן\s*מוגבל/.test(prose)) {
    return { building: "בבניין לזמן מוגבל", privateHome: "לבית פרטי" };
  }
  return { building: "בבניין", privateHome: "לבית פרטי" };
}

/**
 * ids 158, 104: "התקנה ללא עלות בבניין / בית פרטי **במידה ואין סיב
 * מותקן** עלות התקנה 499שח" — התנאי האמיתי הוא קיום סיב, והוא חל על
 * שתי צורות המגורים. הרגקס של הבית הפרטי חוטף את ה-499 ומייחס אותו
 * לבית פרטי בלבד, כלומר מבטיח חינם לבניין שאין בו סיב. כאן התנאי
 * מוחלף במה שהרשומה באמת אמרה, ולא במי שהוא חל עליו.
 */
function fiberConditionedInstallation(pkg: Package): boolean {
  return /במידה\s*ו?אין\s*סיב/.test(installationProse(pkg));
}

/**
 * שורת הפירוט: שני הצדדים, כל אחד עם מי שהוא חל עליו.
 *
 * ⚠️ כששני המספרים זהים, המפרט החזיק את מחיר הבית הפרטי ולא את זה של
 * הבניין (id 70: "עלות התקנה חד פעמי: , 125 ש"ח לבית פרטי" — המחלץ
 * איבד את הראשון). אין לנו מחיר לבניין, ולכן לא נאמר עליו דבר.
 *
 * ⚠️ וכשהמספר של הבית הפרטי לא נקרא (id 3 — "בית פרטי 499" בלי יחידה)
 * הרשומה נשארת מותנית בלי מספר. "לא יודעים — לא מבטיחים": עדיף לומר
 * על מה המחיר חל מאשר להדפיס אותו כאילו הוא חל על כולם.
 */
function installationDetail(pkg: Package, cost: number): string {
  const flat = cost === 0 ? "ללא עלות" : shekels(cost);
  if (!installationIsConditional(pkg)) return flat;
  const priv = privateHomeInstallation(pkg);
  if (fiberConditionedInstallation(pkg) && priv != null && priv !== cost) {
    return `${flat} כשיש סיב מותקן · ${shekels(priv)} כשאין`;
  }
  const qualifiers = housingQualifiers(pkg);
  const parts: string[] = [];
  if (priv !== cost) parts.push(`${flat} ${qualifiers.building}`);
  if (priv != null) parts.push(`${shekels(priv)} ${qualifiers.privateHome}`);
  return parts.join(" · ");
}

/**
 * מחיר הנתב כפי שהרשומה מסרה אותו, או `null` כשלא מסרה.
 *
 * ⚠️ אותו פגם שתוקן להתקנה, על השדה שלידה. `routerIncluded: false` הודפס
 * "אינו כלול במחיר" בשלוש הרשומות היחידות שמחזיקות אותו — ובכל שלושתן
 * הפרוזה **כן** מסרה את המחיר: id 81 אומרת "עלות נתב 0 ש"ח", כלומר
 * השלילה גבתה תוספת על נתב שהרשומה נותנת בחינם, ו-ids 158, 104 אומרות
 * "עלות נתב אינטרנט 20שח (יש הטבה על הנתב למשך שנה ללא עלות)" — תנאי
 * שהוצג בלי המספר ובלי התנאי, בזמן ששורת ההתקנה על אותו כרטיס מדפיסה
 * את שני הצדדים. "אינו כלול במחיר" נשאר רק כשאין מספר לקרוא.
 */
/*
 * ⚠️ שלוש צורות, ולא "עלות נתב" לבדה — ובכל שדות הפרוזה.
 *
 * זה אותו דפוס שהקובץ הזה מתעד שוב ושוב: שער שמכיר הצהרה בצורה אחת
 * ומפספס את השכנה. שתי רשומות חיות ומוצגות מסרו תוספת חודשית על הנתב
 * וקיבלו **אפס** שורות עליה:
 *   • id 85 (`Partner Fiber`, ₪100) — "נתב פייבר בהשכרה בתוספת 25 ₪
 *     לחודש": סדר מילים הפוך (`נתב … בתוספת`) במקום `עלות נתב`.
 *   • id 124 (`All in 1000/250 פרטנר TV`, ₪235) — "ראווטר בעלות 20 שח
 *     לחודש": איות אחר של "ראוטר", ו-"בעלות" במקום "עלות".
 *
 * ⚠️ והראיה שזו אסימטריה ולא החלטה: `ROUTER_PRICED_SEPARATELY`
 * ב-`savings.ts` **כן** קוראת את id 85 ופוסלת אותה מההשוואה — כלומר
 * המנוע יודע שהנתב נגבה בנפרד בדיוק באותו רגע שהכרטיס שותק על זה.
 * הכרטיס היה מאחורי המנוע על אותה רשומה.
 *
 * ⚠️ `ראווטר` חסרה גם מאוצר המילים של המנוע, ולכן id 124 אינה נפסלת
 * שם — היא אינה בבריכת ההשוואה הביתית ({3, 157}) ולכן אינה מתמחרת
 * שום כותרת היום, אבל זה החור שנותר.
 */
const ROUTER_WORD = String.raw`(?:נתב|ראוטר|ראווטר)`;
const ROUTER_MONEY = String.raw`(\d[\d,]*(?:\.\d+)?)\s*(?:ש"ח|ש״ח|שח|₪)`;
const ROUTER_COST = new RegExp(
  String.raw`(?:עלות|בעלות|בתוספת|בתשלום|דמי\s*שכירות(?:\s*של)?)\s*(?:ה)?${ROUTER_WORD}[^.|\n\d]{0,24}?${ROUTER_MONEY}` +
    "|" +
    String.raw`${ROUTER_WORD}[^.|\n\d]{0,30}?(?:עלות|בעלות|בתוספת|בתשלום|דמי\s*שכירות(?:\s*של)?)\s*(?:של\s*)?${ROUTER_MONEY}`,
);

/**
 * המחיר שהרשומה מסרה ל**אותה חבילה עם נתב**, כשהמחיר שליד אינו כולל אותו.
 *
 * ⚠️ הצורה השלילית — "199 ש״ח לא כולל נתב … 220 שח כולל נתב" — אינה
 * נוקבת באף אחת מהמילים ש-`ROUTER_COST` מחפש (עלות / בתוספת / דמי
 * שכירות); היא מוסרת את אותה עובדה בדיוק כהפרש בין שני מחירים.
 *
 * ⚠️ והמנוע **כבר יודע**: `ROUTER_PRICED_SEPARATELY` ב-`savings.ts` נושא
 * בדיוק את החלופה השלילית הזו, ו-`tools/savings.test.mjs` מקבע אותה על
 * id 114 בשם. כלומר המנוע פוסל את הרשומה מהמחשבון בגלל עלות
 * הנתב, והכרטיס לא הדפיס עליה ולו שורה אחת. זה אותו פער ש-
 * `includedRouterSurcharge` נכתב לו, רק בכיוון השני.
 *
 * המבקר שמשווה id 113 (₪179, "179ש״ח כולל נתב") מול id 114 (₪199) ראה
 * פער של ₪20 בלי שאף אחד מהכרטיסים אומר מילה על נתב — בזמן
 * שהפער האמיתי, כששניהם עם נתב, הוא ₪41 (179 מול 220).
 *
 * ⚠️ מוחזר המחיר שהרשומה מסרה, ולא ההפרש שחישבנו (₪21): זה אותו
 * כלל של `discountScope` ושל `promoNoteText` — מחזירים את מה שהרשומה
 * אמרה, בלי להמציא ממנו מספר שהיא לא מסרה.
 *
 * ⚠️ `[sS]` ולא מחלקת תו שפוסלת ירידת שורה — כמו ב-
 * `includedRouterSurcharge` ומאותו טעם: המחלץ שותל שורה ריקה בדיוק
 * בין שתי ההצהרות של id 114 ("לא כולל נתב

220 שח כולל נתב").
 */
const ROUTER_EXCLUDED_PRICE = new RegExp(
  String.raw`(?:לא|אינו|אינה|אינם)\s*כולל(?:ת|ים)?\s*(?:ה)?${ROUTER_WORD}` +
    String.raw`[\s\S]{0,40}?${ROUTER_MONEY}\s*כולל\s*(?:ה)?${ROUTER_WORD}`,
);

function routerDetail(pkg: Package): string | null {
  const prose = installationProse(pkg);
  const cost = prose.match(ROUTER_COST);
  // ⚠️ שתי קבוצות לוכדות — אחת לכל סדר מילים — והנתפסת היא זו שאינה
  // `undefined`. בלי הנפילה הזו הסדר ההפוך החזיר `Number(undefined)`,
  // כלומר `NaN`, והשער שמתחת היה מפיל את השורה בשקט דווקא על הצורה
  // שנוספה כאן.
  const raw = cost ? (cost[1] ?? cost[2]) : null;
  if (raw == null) {
    // ⚠️ הצורה השלילית רק אחרי ש-`ROUTER_COST` לא מצא: רשומה שמסרה
    // סכום מפורש לנתב הוא המדויק מבין השניים. ראה `ROUTER_EXCLUDED_PRICE`.
    const withRouter = prose.match(ROUTER_EXCLUDED_PRICE);
    if (!withRouter) return null;
    const total = Number(withRouter[1].replace(/,/g, ""));
    if (!Number.isFinite(total) || total <= 0) return null;
    return `המחיר אינו כולל נתב · ${shekels(total)} לחודש עם נתב`;
  }
  const amount = Number(raw.replace(/,/g, ""));
  if (!Number.isFinite(amount)) return null;
  const flat = amount === 0 ? "ללא עלות" : `${shekels(amount)} בתוספת למחיר`;
  const waived = prose.match(/הטבה\s*על\s*הנתב\s*למשך\s*(שנה|\d+\s*חודשים?)\s*ללא\s*עלות/);
  return waived ? `${flat} · ללא עלות למשך ${waived[1]}` : flat;
}

/**
 * התוספת החודשית שהרשומה תולה דווקא ב**הכללת** הנתב במחיר.
 *
 * ⚠️ הצד החיובי של אותו שדה, והוא נשאר פתוח אחרי `routerDetail`.
 * `routerIncluded: true` הודפס "כלול במחיר" כעובדה גורפת על חמש
 * רשומות שהפרוזה שלהן מתנה בדיוק את המצב הזה: ids 92, 102, 107, 108
 * ו-109 כותבות "בתוכניות שבהן הנתב כלול במחיר החבילה , תתווסף עלות
 * על הנתב על סך 4.9 ₪ לחודש בנוסף לעלות התוכנית". כלומר הרשומה
 * מוסרת **שני** דברים — הנתב בתוך המחיר, ותוספת חודשית עליו — והשורה
 * הדפיסה את הנדיב מהם לבדו.
 *
 * ⚠️ והמנוע כבר הכריע את המשפט הזה לכיוון ההפוך: `ROUTER_PRICED_SEPARATELY`
 * ב-`savings.ts` מונה אותו במפורש ("אותה הצהרה בדיוק, בניסוח שלא
 * 'בתוספת' ולא 'עלות נתב'") ו-`isComparable` פוסלת בגללו את חמשתן
 * מהמחשבון. כלומר הכרטיס הבטיח ציוד ללא עלות על אותן רשומות שהמנוע
 * מסרב להשוות **בגלל** אותה עלות — בדיוק הפער שההערה על `lineTiers`
 * מתארת, רק שכאן הכרטיס הוא הנדיב מהשניים.
 *
 * התנאי נקרא **מהטקסט עצמו** ולא מושלם, כמו ב-`housingQualifiers`
 * וב-`tierLines`: רשומה שאין בה את ההתניה נשארת עם "כלול במחיר"
 * כשהיתה. דרושה ספרה — "תתווסף עלות" בלי סכום אינו מספר שמותר להדפיס.
 *
 * ⚠️ `\n` **אינו** גבול, רק `.` ו-`•` — כמו ב-`ROUTER_PRICED_SEPARATELY`.
 * המחלץ שותל שורה ריקה בתוך המשפט ("תתווסף עלות\n\nעל הנתב על סך 4.9 ₪"),
 * ולכן מחלקת תו שפוסלת ירידת שורה לא תפסה אף אחת מחמש הרשומות — שער
 * שנראה עובד ואינו עובד גרוע משער שאינו קיים.
 */
function includedRouterSurcharge(pkg: Package): number | null {
  const m = installationProse(pkg).match(
    /שבהן\s*ה?נתב\s*כלול\s*במחיר[^.•]{0,40}?תתווסף\s*עלות[^.•\d]{0,30}?(\d[\d,]*(?:\.\d+)?)\s*(?:ש"ח|שח|₪)/,
  );
  if (!m) return null;
  const amount = Number(m[1].replace(/,/g, ""));
  return Number.isFinite(amount) && amount > 0 ? amount : null;
}

/**
 * מדרגות הכמות שהרשומה מסרה ושניתן להדפיס.
 *
 * ⚠️ פונקציה אחת לשני הקוראים — שורת הפירוט `מחיר לפי מספר קווים`
 * ו-`priceNote` — ולא עותק של אותו `filter`. ההיסטוריה של הקובץ היא
 * שכל שער שהוחזק בשני עותקים התיישן באחד מהם.
 */
export function usableLineTiers(pkg: Package): { lines: number; price: number }[] {
  const raw = specOf<Partial<CellularSpec>>(pkg).lineTiers;
  if (!Array.isArray(raw)) return [];
  return raw.filter(
    (t): t is { lines: number; price: number } =>
      Boolean(t) && isCount(t.lines) && Number.isInteger(t.lines) && t.lines >= 1 && isMoney(t.price),
  );
}

/**
 * הכמות שמדרגת הקווים חלה עליה, כפי שהרשומה ניסחה אותה.
 *
 * ⚠️ `lineTiers` מחזיק סקלר אחד למדרגה, והשורה הדפיסה אותו כשוויון —
 * בזמן שכל ארבע הרשומות שמחזיקות מדרגות מוסרות **טווח**. id 57 אומרת
 * "למצרפים 2-3 מנויים – 33 ₪, למצרפים 4 מנויים ויותר 30 ₪", והשורה
 * הכריזה "3 קווים ₪33 · 4 קווים ₪30": לקוח עם שני קווים הסיק שעליו חל
 * ₪39.9 בזמן שהרשומה מעניקה לו ₪33, ולקוח עם חמישה לא ידע ש-₪30 חל גם
 * עליו. אותו דבר ב-ids 36, 37 ("עד 2 מנויים כולל", "3 ומעלה") וב-68.
 *
 * התנאי נקרא **מהטקסט עצמו** ולא מושלם: מדרגה שאין בפרוזה שלה אחת
 * משלוש התבניות נשארת בשוויון שהיתה.
 */
function tierLines(pkg: Package, lines: number): string {
  const plain = lines === 1 ? "קו אחד" : `${lines} קווים`;
  const prose = [logicName(pkg), pkg.description, pkg.benefits].filter(Boolean).join(" ");
  // ⚠️ קו בודד נכתב בפרוזה גם במילים ("קו אחד ומעלה") ולא רק בספרה.
  const n = lines === 1 ? "(?:(?<!\\d)1(?!\\d)|קו\\s*אחד)" : `(?<!\\d)${lines}(?!\\d)`;
  const unit = "\\s*(?:מנויים|מנוי|קווים|קו)?\\s*";
  if (new RegExp(`${n}${unit}(?:ומעלה|ויותר)`).test(prose)) return `${plain} ומעלה`;
  const range = prose.match(
    new RegExp(`(?<!\\d)(\\d+)\\s*[-–]\\s*${lines}(?!\\d)\\s*(?:מנויים|מנוי|קווים|קו)`),
  );
  if (range) return `${range[1]}–${lines} קווים`;
  // ⚠️ אותה קריאה שהמנוע עושה, ממקום אחד. ראה `tierCapsAt`.
  if (tierCapsAt(pkg, lines)) return `עד ${plain}`;
  return plain;
}

/**
 * האם הרשומה מצהירה על המחיר הזה כעל **רצפה** ("מ-100 ₪ לחודש").
 *
 * ⚠️ המקבילה של `proseCapsAt` בכיוון ההפוך, וזו שחסרה דווקא לשדה
 * היחיד שהכרטיס מדפיס בגודל 3xl. id 85 (`Partner Fiber`) אומר
 * פעמיים "מ-69 ₪ לחודש לחודשיים ראשונים לאחר מכן **מ-100 ₪ לחודש**",
 * ו-`price` שלו הוא 100 — כלומר הכרטיס הדפיס "₪100 לחודש" כמחיר
 * אחיד בזמן שההערה **שעל אותו כרטיס** (`priceAfterPromoNote`) מצטטת
 * "מ-100 ₪". שתי אמירות על אותו מספר, זו מעל זו, והעליונה היא
 * הגורפת מהן. אותו כלל של `discountIsCapped`: לא יודעים — לא
 * מבטיחים.
 *
 * ⚠️ נדרשת התאמה **לאותו מספר** ולא עצם קיום התבנית, מאותו טעם שם:
 * כך השער מצמצם הבטחה ולא מרחיב אותה. `מ` חייבת לבוא אחרי גבול
 * ולא אחרי אות עברית, אחרת "**מ**חודש 4 99 ש"ח" (ids 73, 153, 159)
 * ייקרא כרצפה; ו-`ומעלה`/`ויותר` שאחרי הסכום נדחה, כי "מ-300 ₪
 * ומעלה" (id 135) הוא מדרגת **צריכה** ולא מחיר התוכנית.
 */
function proseFloorsAt(pkg: Package, value: number): boolean {
  const prose = [logicName(pkg), pkg.description, pkg.benefits].filter(Boolean).join(" ");
  for (const m of prose.matchAll(
    /(?<![א-ת])מ-?\s*(\d[\d,]*(?:\.\d+)?)\s*(?:₪|ש"ח|שח|ש''ח)\s*(ומעלה|ויותר)?/g,
  )) {
    if (m[2]) continue;
    if (Number(String(m[1]).replace(/,/g, "")) === value) return true;
  }
  return false;
}

/**
 * המספר הגדול שבכרטיס — מחיר חודשי או אחוז הנחה — כמחרוזת.
 *
 * ⚠️ `isMoney` ולא `!= null`, ובמקום אחד לשני הענפים. `PackageCard`
 * שאל `pkg.price != null` והזריק את `pkg.discountPercent` בלי שום
 * שער, ולכן `price: 0` (ids 18, 22 — הצורה שהמחלץ מייצר כשלא קרא
 * מחיר) הודפס "₪0 לחודש", כלומר **חבילה חינם**, ו-`discountPercent:
 * null` (id 144) הודפס "null% הנחה". שתיהן נעצרות היום ב-`isListable`
 * בלבד, שאינו על המסלול שמרנדר כרטיס; והשדה השלישי על אותו כרטיס
 * (`priceAfterPromo`) כבר גודר כך במפורש. "—" הוא אותו דרדור של
 * `shekels` על עמלה פגומה: עדיף להשמיט מספר מאשר להמציא אותו.
 */
export function headlineValue(pkg: Package): string {
  if (pkg.category === "electricity") {
    return isMoney(pkg.discountPercent) ? `${nf.format(pkg.discountPercent)}%` : "—";
  }
  return isMoney(pkg.price) ? shekels(pkg.price) : "—";
}

/**
 * מה שהרשומה מסרה על המחיר **אחרי** תום ההטבה — מספר, או נוסח מילולי,
 * או כלום.
 *
 * ⚠️ יושבת כאן ולא בכרטיס כדי שכל מי שמדפיס את השדה יקרא **אותו** שער.
 * שלושה מקומות בדף מדפיסים את `priceAfterPromo`, ושניים מהם גידרו אותו
 * ב-`isMoney` (`PackageCard` ב-`> 0`, `CompareTray` ב-`afterPriceKnown`
 * המקומי) — ואילו פס המחיר בהירו, ההצהרה הרמה ביותר בדף, שאל
 * `!= null` בלבד. `0` הוא הצורה שהמחלץ מייצר כשלא קרא מספר (ids 18, 22
 * מוכיחים את זה על `price` באותו קובץ), ולכן רענון שיכתוב
 * `priceAfterPromo: 0` לחבילת הסלולר הזולה היה מדפיס בהירו "ואחרי
 * ההטבה ₪0" — הבטחה שהחבילה נעשית **חינם** בתום המבצע — **ובמקביל
 * בולע** את `priceAfterPromoNote`, כלומר דווקא את ההצהרה שהרשומה כן
 * מסרה. הכרטיס שמתחתיו, על אותה חבילה, היה אומר את ההערה הנכונה.
 *
 * ⚠️ חשמל מוחזר `null`: `ElectricityPackage` מצהיר `priceAfterPromo:
 * null` ואין לו "מחיר חודשי" שיעלה.
 */
export type PromoRise =
  | { kind: "amount"; amount: number }
  | { kind: "note"; note: string }
  /**
   * הרשומה מצהירה בתיאור על תקופת מבצע ולא מסרה לא מספר ולא נוסח.
   *
   * ⚠️ 19 חבילות (ids 17, 24, 27, 31, 34, 45, 50, 54, 57, 64, 67, 71,
   * 72, 73, 98, 124, 125, 153, 159) נתפסות ב-`declaresRiseInText`
   * ולכן **נפסלות נכון** מהמחשבון — אבל `priceAfterPromo` ו-
   * `priceAfterPromoNote` ריקים אצל כולן, ולכן `promoRise` החזיר
   * `null`, הכרטיס לא הראה באנר, ושורת "אחרי ההטבה" בטבלת ההשוואה
   * הכריזה **"לא דווח שינוי"** — הכחשה של מה שהרשומה כן אמרה. על
   * id 17 התיאור שעל אותו כרטיס אומר "מהחודש ה-13 והלאה- 59.9 ₪".
   *
   * ⚠️ הענף הזה **אינו אומר שהמחיר עולה**, בכוונה: ב-10 מתוך 19
   * (ids 45, 67, 71, 72, 73, 98, 124, 125, 153, 159) ה-`price`
   * שבכרטיס הוא כבר מחיר הקבע וההצהרה היא על מבצע **זול** בהתחלה
   * ("חודש 1-3 79ש"ח מחודש 4 109ש"ח" כש-`price` 109). "המחיר עולה
   * בהמשך" היה שם מספר שגוי בכיוון ההפוך. אותו כלל של
   * `discountIsCapped`: אומרים מה שהרשומה אמרה — שיש תקופת מבצע —
   * ולא מה שלא מסרה.
   */
  | { kind: "period" };

export function promoRise(pkg: Package): PromoRise | null {
  if (pkg.category === "electricity") return null;
  if (isMoney(pkg.priceAfterPromo)) return { kind: "amount", amount: pkg.priceAfterPromo };
  /*
   * ⚠️ `typeof === "string"` ולא טרות'יניס. הנוסח הזה מודפס **מילה
   * במילה** בשלושה מקומות (הכרטיס, פס ההירו, שורת "אחרי ההטבה"), ללא
   * `shekels` ובלי `nf.format` שידרדרו ערך פגום — ולכן ערך שאינו
   * מחרוזת הודפס "בתום ההטבה: [object Object]" דווקא בשורה שהדף
   * מצהיר עליה כהבטחת המותג. כמו `hoursText`, זה שדה טקסט חופשי
   * שהקטלוג נכנס אליו בלי ולידציה בזמן ריצה.
   */
  if (typeof pkg.priceAfterPromoNote === "string" && pkg.priceAfterPromoNote) {
    return { kind: "note", note: pkg.priceAfterPromoNote };
  }
  return declaresRiseInText(pkg) ? { kind: "period" } : null;
}

