/**
 * השורה שפס המחיר בהירו מוסיף מתחת למחיר, או `null` כשאין מה לומר.
 *
 * ⚠️ הנוסח כאן ולא ב-`page.tsx`: הפסקה שמעל הפס מבטיחה במפורש
 * "ומציגים גם את המחיר שאחרי תקופת המבצע", ולכן השורה הזו היא חלק
 * מהבטחה — ומחרוזת שנבנית בתוך ה-JSX אינה ניתנת לבדיקה בלי לרנדר
 * דף שלם (`page.tsx` מייבא `lp.css`). ראה `promoRise`.
 */
export function heroRiseLine(pkg: Package): string | null {
  const rise = promoRise(pkg);
  if (!rise) return null;
  if (rise.kind === "amount") return `ואחרי ההטבה ${shekels(rise.amount)}`;
  // ⚠️ `promoNoteText` ולא `rise.note` ישירות — ראה את השער שם.
  if (rise.kind === "note") {
    return `${promoNoteLabel(pkg, rise.note)} ${promoNoteText(pkg, rise.note)}`;
  }
  return PROMO_PERIOD_TEXT;
}

/**
 * מה ההנחה של מסלול החשמל חלה עליו, כפי שהרשומה עצמה כותבת.
 *
 * ⚠️ 10 מתוך 19 מסלולי החשמל מצהירים במפורש שההנחה אינה על החשבון
 * אלא על **רכיב** אחד בתוכו ("ההנחה היא על רכיב התשלום המשתנה
 * לקוטש בלבד... בנוסף לתעריף המשתנה הלקוח יישא בתשלומים החודשיים
 * הקבועים (אספקה, חלוקה והספק KVA)"), והכרטיס הדפיס "20% הנחה"
 * בגודל 3xl בלי אות אחת מההסתייגות הזו. אלה בדיוק ארבעת המסלולים
 * שהדף מכריז עליהם כמובילים (20%, 18%, 15%) — מבקר שמשווה 20% מול
 * חשבון החשמל שלו קורא הבטחה על הסכום כולו.
 *
 * ⚠️ מוחזר **נוסח הרשומה** ולא ניסוח שלנו, ובלי מקדם כלשהו לחלקו
 * של הרכיב בחשבון: המקדם אינו בקטלוג, וכל ניחוש היה הופך את
 * ההסתייגות למספר שנראה מחושב. אותה כנות של `electricityRank`.
 */
const DISCOUNT_SCOPES: [RegExp, string][] = [
  [/רכיב\s+ה?תשלום\s+המשתנה/, "רכיב התשלום המשתנה"],
  [/רכיב\s+הצריכה/, "רכיב הצריכה"],
  [/רכיב\s+ה?ייצור/, "רכיב הייצור"],
];

export function discountScope(pkg: Package): string | null {
  if (pkg.category !== "electricity") return null;
  const prose = [logicName(pkg), pkg.description, pkg.benefits].filter(Boolean).join(" ");
  for (const [re, label] of DISCOUNT_SCOPES) if (re.test(prose)) return label;
  return null;
}

/**
 * ההסתייגות שהרשומה מסרה על המספר הגדול שבכרטיס — מחיר או אחוז הנחה.
 *
 * ⚠️ יושבת כאן ולא ב-`PackageCard` כדי ש**גם טבלת ההשוואה** תראה
 * אותה. שרשרת התנאים הזו נכתבה בכרטיס בלבד, ולכן הטבלה — שכל תפקידה
 * להשוות מחירים — הדפיסה את אותם ₪35 של id 110 בלי מילה על
 * "לרוכשים 2 מנויים ויותר", בעוד הכרטיס שמעליה כן אמר זאת. זו הפעם
 * הרביעית שהפער הזה מייצר באג (ראה `discountIsCapped`), ולכן
 * `compareRows` מוסיפה את השורה מכאן, מאותו מקור.
 *
 * ⚠️ `requiresMultipleLines` קודם: id 16 נושא את שתי ההצהרות, והמחמירה
 * מהן — מינימום חוזי ולא מחיר למנוי — היא זו שצריכה להיאמר.
 */
/**
 * המחיר שעל הכרטיס הוא המחיר שהרשומה ייחסה למנוי/קו **בודד**.
 *
 * ⚠️ נקרא מהטקסט עצמו ולא מושלם, כמו `tierLines` ו-`housingQualifiers`:
 * רשומה שלא מסרה מחיר לבודד מחזירה `false`, כלומר ההסתייגות
 * נשארת כשהיתה — "לא יודעים, לא מבטיחים", הכיוון של כל הקבוצה.
 */
function headlinePriceIsSingleUnit(pkg: Package): boolean {
  if (!isMoney(pkg.price)) return false;
  const m = installationProse(pkg).match(
    /(?:מנוי|קו)\s*בודד\s*[–—:-]?\s*(\d[\d,]*(?:\.\d+)?)/,
  );
  if (!m) return false;
  const single = Number(m[1].replace(/,/g, ""));
  return Number.isFinite(single) && Math.abs(single - pkg.price) < 0.005;
}
export interface PriceNote {
  label: string;
  value: string;
}

export function priceNote(pkg: Package): PriceNote | null {
  if (pkg.category === "electricity") {
    const scope = discountScope(pkg);
    return scope ? { label: "מה ההנחה כוללת", value: `הנחה על ${scope} בחשבון בלבד` } : null;
  }
  if (!isMoney(pkg.price)) return null;
  /*
   * ⚠️ ולא כשהרשומה מסרה שהמחיר המוצג הוא דווקא מחיר המנוי הבודד.
   *
   * זה אותו תיקון בדיוק שענף `familyPriceOnly` שמתחת כבר קיבל
   * (`usableLineTiers(pkg).length === 0`, שנוסד אחרי ש-id 36 קיבלה הסתייגות
   * שהמדרגות שלה סתרו) — והענף החמור משניהם, שרץ ראשון,
   * לא נבדק מול שום נתון כמותי.
   *
   * id 42 (`TOP 400 GB 2025`, `price: 39.9`) מוסרת במפורש "לרוכשים 3 מנויים
   * ואילך, עבור מנוי בודד 39.90 ₪" — כלומר ה-39.9 שעל הכרטיס הוא
   * המחיר של **מנוי אחד**, והמחיר המותנה בכמות הוא ₪30. הכרטיס
   * וטבלת ההשוואה הדפיסו עליו "המחיר מותנה בכמות המנויים",
   * הסתייגות על תנאי שאינו חל על המספר שלידו.
   *
   * id 110 (`price: 35`) מנסחת את אותו דבר ("עבור מנוי בודד 39.90 ₪")
   * ושם ההסתייגות **נכונה**, כי ₪35 הוא דווקא המחיר המותנה.
   * אותה הצהרה, שני מחירים — והשאלה היחידה שמבדילה היא איזה
   * מהם הוא `pkg.price`. גם id 68 נשאר מסוייג בצדק (הבודד שלו הוא
   * 49.90, ו-`price` הוא 39.9 — מחיר שלושה קווים ומעלה).
   *
   * ⚠️ השער הוא **תצוגה בלבד**. `requiresMultipleLines` ממשיך לפסול
   * את id 42 מבריכת ההשוואה ב-`isComparable` — שם הכיוון השמרני הוא
   * בריכה קטנה יותר, והרשומה אכן מתמחרת לפי כמות בחלק מהמדרגות.
   * בריכת ההשוואה אינה זזה מהתיקון הזה.
   */
  if (requiresMultipleLines(pkg) && !headlinePriceIsSingleUnit(pkg)) {
    return { label: "תנאי המחיר", value: "המחיר מותנה בכמות המנויים בחבילה" };
  }
  /*
   * ⚠️ בסלולר בלבד, כמו במנוע. `computeSaving` מחילה את השער הזה
   * מאחורי `track !== "cellular"` (`savings.ts:719`) כי "מסלול משפחתי"
   * הוא מחיר לקו מתוך כמה קווים — מושג שאין לו מקבילה בחבילת בית, שם
   * יש חיבור אחד. `FAMILY_ONLY` כולל `/family/i`, ולכן חבילת אינטרנט
   * שהמילה הזו מופיעה בשמה הייתה מקבלת כאן "משני מנויים ומעלה" —
   * הסתייגות שהרשומה לא מסרה. רדום בקטלוג של היום (אפס התאמות בבית),
   * ולכן זה שער לרענון הבא ולא תיקון של מספר מוצג.
   */
  /*
   * ⚠️ ורק כשהרשומה **לא** מסרה מדרגות כמות. `familyPriceOnly` נתפס
   * על המילה "משפחתי" שבשם, וההערה עליו ב-`savings.ts` מצהירה במפורש
   * שהבדיקה "תלוית-כמות ויושבת ב-`computeSaving` לצד
   * `priceUnknownAtLines`" — ואילו כאן היא הוחלה כהצהרה שטוחה, בלי
   * כמות. id 36 ("סלקום משפחתי פלוס", `lineTiers: [{2, 39.9}, {3, 34.9}]`)
   * קיבלה על אותו כרטיס שתי שורות שאומרות הפוך: "מחיר למנוי במסלול
   * משפחתי — משני מנויים ומעלה" לצד "מחיר לפי מספר קווים: עד 2 קווים
   * ₪39.9 · 3 קווים ומעלה ₪34.9" — כלומר קו **אחד** משלם 39.9 בדיוק
   * כמו שניים, וזה מה שהפרוזה אומרת ("עד 2 מנויים כולל - 39.9 ₪ למנוי").
   *
   * ⚠️ והראיה שזו השמטה ולא החלטה: id 37 ("סלקום 5G PRO") נושאת מבנה
   * מדרגות זהה לחלוטין ואינה מקבלת שום הסתייגות — כי בשמה אין את המילה
   * "משפחתי". אותה עובדה, שני ניסוחים, לפי מילה בשם ולא לפי הנתון.
   * id 117 (`wecomFamily 4G`), שבשבילה השער נכתב, נשארת מסויגת בצדק:
   * שם אין מדרגות ואין מחיר לקו בודד.
   */
  if (pkg.category === "cellular" && familyPriceOnly(pkg) && usableLineTiers(pkg).length === 0) {
    return { label: "תנאי המחיר", value: "מחיר למנוי במסלול משפחתי — משני מנויים ומעלה" };
  }
  if (proseFloorsAt(pkg, pkg.price)) {
    return { label: "תנאי המחיר", value: "המחיר הוא מחיר התחלתי ולא מחיר אחיד" };
  }
  return null;
}

