/**
 * האם הפרוזה של הרשומה מצהירה על **המספר הזה** כתקרה ("עד 600").
 *
 * ⚠️ המקבילה המדויקת של `discountIsCapped`, שחסרה למהירות ולנפח.
 * `discountIsCapped` נבנתה כדי שהכרטיס לא יבטיח שיעור קבוע כשהרשומה
 * אמרה "עד", ואותה הבטחה בדיוק נשארה פתוחה בצד השני של הכרטיס:
 * id 85 נקרא "Partner Fiber במהירות **עד** 600/100" והאריח הדפיס
 * "600/100Mbps" כעובדה; id 124 ("עד 1000Mb") הדפיס "1,000/250Mbps";
 * ids 26, 27 ו-69 מבטיחים "עד 500GB"/"עד 1500GB"/"עד 5,000 דקות"
 * והאריח הדפיס את המספר שטוח. הכרטיס הכריז יותר ממה שהחבילה מוכרת.
 *
 * ⚠️ אותם שני שערים של `discountIsCapped`, מאותם טעמים: `logicName`
 * ולא `displayName` (שקוטעת אחרי `[line]`), ו-`עד` כמילה ולא כתת-מחרוזת
 * (כדי ש-"ועד בית" לא ייקרא כתקרה). ובנוסף — התאמה **לאותו מספר**,
 * ולא לעצם קיום המילה, כדי שהשער יצמצם הבטחה ולא ירחיב אותה.
 *
 * ⚠️ היחידה מותרת **לפני** המספר. הקטלוג כותב את אותה תקרה
 * בשני הסדרים: id 69 אומר "עד 3000GB" ונתפס, ואילו ids 54,
 * 65 ו-66 אומרים "עד GB800" / "עד GB2500" — אותה הצהרה בדיוק,
 * והאריח הדפיס "800GB" שטוח על שלושתן. ההתנהגות לא רק
 * חסרה — היא הייתה **לא עקבית** בין שתי רשומות של אותו ספק.
 * רק אותיות לטיניות, כלומר יחידה (GB/MB/Mbps) ולא מילה בעברית.
 *
 * ⚠️ מספר שאחריו `%` או `:` נדחה. `%` הוא תחומה של `discountIsCapped`,
 * ו-`:` הוא שעה — "ההנחה חלה עד 7:00" אינה הצהרה על נפח או מהירות,
 * ובלי השער הזה כל שדה שערכו 7 היה נקרא ממנה כתקרה.
 *
 * ⚠️ ו' החיבור מותרת. ה-lookbehind נכתב כדי ש-"ועד בית" לא ייקרא
 * כתקרה, והוא חסם גם את "**ו**עד 1500GB" — ניסוח לגיטימי לגמרי.
 * id 27 אומר "ועד 1500GB גלישה לשלושת הקווים יחד" והאריח הדפיס
 * `1,500GB` כעובדה, כלומר בדיוק ההבטחה המנופחת שהשער נבנה למנוע.
 * "ועד בית" ממילא אינו נתפס: הדרישה למספר מיד אחרי המילה (בלבד
 * עם יחידה לטינית ביניהם) פוסלת כל "ועד" שאחריו מילה עברית.
 *
 * ⚠️ והתקרה נקשרת ל**שדה**, לא למספר לבדו. ההשוואה לפי מספר בלבד
 * אפשרה ל-"עד" של שדה אחד לזלוג לאריח של שדה אחר כשבמקרה מדובר
 * באותה כמות: id 27 מוסר "3000 דקות שיחה לקו, **עד** 3000 SMS לקו"
 * — ה-"עד" שייך ל-SMS, והאריח הדפיס "עד 3,000 דקות שיחה" על כמות
 * שהרשומה מסרה שטוחה. לכן נקראת היחידה שצמודה למספר (לפניו או
 * בחלון קצר אחריו) ומושווית למשפחה שנשאלה. יחידה שלא זוהתה —
 * המספר נקרא כתקרה כבעבר, כי שם אין ראיה לשדה אחר.
 */
type CapKind = "data" | "speed" | "minutes" | "sms" | "converters" | "channels";

/*
 * ⚠️ `speed` לפני `data`, ו-`data` בלי `MB`. "עד 1000Mb" הוא מהירות
 * ו-"עד 800GB" הוא נפח; השדה שמודפס כנפח הוא `dataGb`, ולכן `MB`
 * אינו שייך לו ואין בין השניים דו-משמעות.
 */
const CAP_UNITS: [CapKind, RegExp][] = [
  ["speed", /Mbps|Mb(?![a-z])|מהירות|הורדה|העלאה/i],
  ["data", /GB|ג['׳]?יגה|גלישה|נפח/i],
  ["sms", /SMS|הודעות|מסרונ/i],
  ["minutes", /דק/],
  ["converters", /ממיר/],
  /*
   * ⚠️ `ערוצ` כאן ולא רק כ-`CapKind`: בלי יחידה מזוהה כל "עד N" שבמקרה
   * נושא את מספר הערוצים היה נקרא כתקרה שלהם, וזה בדיוק מה שההערה על
   * `proseCapsAt` ("התקרה נקשרת ל**שדה**") נבנתה למנוע. עם היחידה
   * השער הדוק לשני הכיוונים: "עד 60 ערוצים" נתפס, ו-"עד 60 דקות" על
   * חבילה עם 60 ערוצים נדחה.
   */
  ["channels", /ערוצ/],
];

function proseCapsAt(pkg: Package, value: number, kind: CapKind): boolean {
  const prose = [logicName(pkg), pkg.description, pkg.benefits].filter(Boolean).join(" ");
  for (const m of prose.matchAll(
    // ⚠️ חלון היחידה ב-lookahead, אחרת הוא **נבלע**: כשהוא נצרך
    // כקבוצה רגילה, "עד 3000 SMS לקו ועד 1500GB" החזיר התאמה אחת —
    // 14 התווים שאחרי 3000 כללו את "ועד 15", והסריקה המשיכה אחריהם.
    /(?<![א-ת])ו?עד\s*(?:([A-Za-z]{1,5})\s*)?(\d[\d,]*(?:\.\d+)?)\s*(?=([\s\S]{0,14}))/g,
  )) {
    const window = m[3] ?? "";
    if (window.startsWith("%") || window.startsWith(":")) continue;
    if (Number(String(m[2]).replace(/,/g, "")) !== value) continue;
    const unit = CAP_UNITS.find(([, re]) => re.test(`${m[1] ?? ""} ${window}`));
    if (unit && unit[0] !== kind) continue;
    return true;
  }
  return false;
}

/** `"עד "` כשהרשומה מצהירה על המספר הזה כתקרה, אחרת מחרוזת ריקה. */
const upTo = (pkg: Package, kind: CapKind, ...values: (number | null | undefined)[]) =>
  values.some((v) => typeof v === "number" && proseCapsAt(pkg, v, kind)) ? "עד " : "";

/**
 * כמות שמותר להדפיס דרך `nf.format` — המקבילה של `isMoney` לשדות
 * ה**מונים** של ה-`spec`.
 *
 * ⚠️ `isMoney` גודר את המחירים ואת העמלות (`shekels` מדרדר ל-"—"), אבל
 * כל שדה שמודפס כמספר חשוף נשאר בלי שער: `dataGb`, `minutes`, `sms`,
 * `intlMinutes`, `channels`, `converters`, `downloadMbps`, `uploadMbps`.
 * שני חורים שונים, שתוצאתם זהה — `NaN` על המסך:
 *
 *   • `dataLabel` ו-`speedLabel` שאלו `== null` בלבד, ולכן **מחרוזת**
 *     עברה: `dataGb: "750GB"` הדפיס אריח "NaNGB", ו-`downloadMbps:
 *     "1000 Mb"` הדפיס "NaN/100Mbps" מתחת לכיתוב "מהירות גלישה".
 *   • האחרים שאלו `typeof === "number"`, ו-`NaN` **הוא** number: ערך
 *     `uploadMbps: NaN` הדפיס "1,000/NaNMbps".
 *
 * זה אותו תרחיש שההערה על `shekels` מתארת — הקטלוג נכנס דרך
 * `as unknown as Catalog`, כלומר אין ולידציה בזמן ריצה, ורשומה שתישאב
 * פעם אחת לא-מנורמלת מגיעה לכאן כמות שהיא. `isMoney` אינו מתאים כאן
 * כי `0` מפורש הוא **נתון** במונים (ראה ההערה ב-`cardStats`), ולכן
 * השער בודק סופיות בלבד. אריח שנשמט עדיף על אריח שמדפיס "NaN".
 */
const isCount = (value: unknown): value is number =>
  typeof value === "number" && Number.isFinite(value);

/**
 * ה-`spec` כאובייקט שאפשר לקרוא ממנו שדות — גם כשהרשומה לא מסרה אותו.
 *
 * ⚠️ `spec: null` **הפיל את רינדור השרת של `/lp` כולו**. `cardStats`,
 * `detailRows` ו-`compareRows` עשו `pkg.spec as HomeSpec` ואז ניגשו
 * מיד לשדה (`spec.unlimitedData` / `spec.downloadMbps` / `spec.allHours`
 * / `(p.spec as HomeSpec).uploadMbps`), ולכן `spec: null` זרק
 * `Cannot read properties of null` — כלומר **כל** הדף מחזיר 500 במקום
 * שכרטיס אחד יציג פחות. זו בדיוק הנפילה שההערה על `shekels` נכתבה
 * נגדה, ואותו שער בדיוק כבר נבנה רמה אחת מעל: `hasSpec`/`tierTable`
 * ב-`savings.ts` מסננים `spec` שאינו אובייקט לפני כל קריאה ממנו, ומה
 * שחסר כאן הוא השכבה שמדפיסה. `spec` שאינו אובייקט נקרא כ"לא נמסר
 * דבר": כל שערי ה-`isCount`/`typeof` שמתחת מפילים את האריחים
 * והשורות בשקט, כמו רשומה שכל שדות ה-`spec` שלה ריקים (ids 132, 100).
 *
 * ⚠️ מיוצאת מאותו טעם ש-`installationIsConditional` מיוצאת: סטודיו
 * הפוסטים קרא `p.spec.hoursText` ישירות, כלומר אותה נפילה בדיוק נשארה
 * פתוחה במשטח הרביעי. שער אחד לארבעת הצרכנים.
 */
export const specOf = <T>(pkg: Package): T =>
  (pkg.spec != null && typeof pkg.spec === "object" && !Array.isArray(pkg.spec)
    ? pkg.spec
    : {}) as T;

/**
 * Big buckets are sold as "unlimited" — say so instead of printing 10000GB.
 *
 * ⚠️ `pkg` ולא `spec` לבדו: ה-"עד" חי בפרוזה של הרשומה, לא במפרט.
 *
 * ⚠️ ה-`spec` מוצהר כבר-`null`, כמו `tierTable` ב-`savings.ts` ומאותו
 * טעם: `cardStats` כבר מגודר ב-`specOf`, אבל הפונקציה הזו מיוצאת
 * וקורא שני (`src/lib/posts/catalog.ts`, סטודיו הפוסטים) מעביר לה את
 * `p.spec` כמות שהוא. שם הנפילה הייתה מפילה את רינדור הסטודיו.
 */
export function dataLabel(pkg: Package, spec: CellularSpec | null | undefined): string | null {
  if (!spec) return null;
  if (spec.unlimitedData) return "גלישה חופשית";
  // ⚠️ `isCount` ולא `== null`: "750GB" הדפיס "NaNGB". ראה ההערה שם.
  if (!isCount(spec.dataGb) || spec.dataGb === 0) return null;
  return `${upTo(pkg, "data", spec.dataGb)}${nf.format(spec.dataGb)}GB`;
}

/*
 * ⚠️ שתי המהירויות באותה יחידה. ההורדה הומרה ל-Gb בעוד ההעלאה נשארה
 * ב-Mb **ובלי יחידה כלל**: `{5000, 500}` הוצג כ-"5Gb/500" מתחת לכיתוב
 * "מהירות גלישה" — הגולש קורא 5 מול 500 ואין לו שום דרך לדעת שמדובר
 * ב-5000 מול 500. היחידה נקבעת פעם אחת, ושתיהן מוצגות בה.
 *
 * ⚠️ היחידה נקבעת לפי **שתיהן**, לא לפי ההורדה בלבד. `{1000, 100}` —
 * החבילה הנפוצה ביותר בקטלוג הביתי (15 מתוך 33) — הוצג כ-"1/0.1Gb":
 * נכון אריתמטית, אבל "0.1" הוא דרך גרועה לומר 100, והמספר הגדול מבין
 * השניים נקרא כקטן משמעותית. יחידת Gb נבחרת רק כששתי המהירויות
 * נשארות שלמות בה; אחרת שתיהן ב-Mb.
 */
/*
 * ⚠️ "נשארות שלמות" נבדק כחלוקה ב-1000 ולא כ-`>= 1000`. התנאי הקודם
 * עצר את `{1000, 100}` אבל לא את `{1500, 1000}`, שהוצג כ-"1.5/1Gb" —
 * בדיוק הניסוח שההערה שמעל פוסלת, רק מהצד השני: המספר הגדול נכתב
 * כשבר. וגרוע מכך, `nf` מוגבל לשלוש ספרות אחרי הנקודה בברירת מחדל,
 * ולכן `{1000.5, 1000.5}` הודפס כ-"1.001/1.001Gb" — **אובדן דיוק**
 * בעקבות חלוקה, על מספר שהקטלוג מסר במדויק. יחידה שאינה מחלקת את שתי
 * המהירויות בשלמות נשארת Mb, שם שום חלוקה לא מתבצעת.
 */
export function speedLabel(pkg: Package, spec: HomeSpec | null | undefined): string | null {
  if (!spec) return null;
  /*
   * ⚠️ `isCount` ולא `== null`, בשני השדות. השער הקודם בדק היעדר ערך
   * ולא ערך שמיש: `downloadMbps: "1000 Mb"` עבר ו-`nf.format` החזיר
   * `NaN`, כך שהאריח הדפיס "NaN/100Mbps" **מתחת לכיתוב "מהירות
   * גלישה"** — מספר שהרשומה לא מסרה, בדיוק מה ש-`shekels` מדרדר
   * ל-"—" כבר היום. ו-`uploadMbps` גרוע מזה: הוא נבדק ב-`!= null`
   * בלבד ולכן `NaN` הדפיס "1,000/NaNMbps", כלומר חצי מספר אמיתי וחצי
   * חור — על שדה שהערך **שלו** פגום, בזמן שההורדה נמסרה כראוי.
   *
   * העלאה שאינה שמישה נקראת כ"לא נמסרה" ונופלת לצורת המהירות הבודדת,
   * בדיוק כמו ids 3, 81, 92 ו-104 שבאמת נושאים `uploadMbps: null` —
   * וכך גם התווית הזוגית ("מהירות (הורדה/העלאה)") אינה מובטחת על
   * נתון שאין.
   */
  if (!isCount(spec.downloadMbps)) return null;
  const upload = isCount(spec.uploadMbps) ? spec.uploadMbps : null;
  const whole = (mbps: number) => mbps >= 1000 && mbps % 1000 === 0;
  /*
   * ⚠️ יחידת Gb רק כששתי המהירויות נמסרו, ולא על מהירות בודדת.
   *
   * היחידה נבחרה לכל חבילה בנפרד, והכרטיסים יושבים זה ליד זה: ברצועת
   * ההיילייטס של הבית id 92 (`{1000, null}`) הודפס "1Gb" **בשורה
   * שמעל** id 73 (`{1000, 100}`) שהודפס "1,000/100Mb" — אותה מהירות
   * הורדה, אותו מחיר ₪109, ושני מספרים שנראים כמו 1 מול 1,000. זו
   * בדיוק הקריאה השגויה שההערות שמעל פוסלות, רק שהיא עברה מתוך ערך
   * בודד אל הפער בין שני ערכים.
   */
  const asGb = upload != null && whole(spec.downloadMbps) && whole(upload);
  /*
   * ⚠️ `Mbps`/`Gbps` ולא `Mb`/`Gb`. הנתון הוא `downloadMbps` — מגהביט
   * **לשנייה** — והאריח הדפיס "5,000/500Mb", כלומר יחידת נפח במקום
   * יחידת מהירות, על כל 23 החבילות הביתיות שמסרו מהירות. לא כותרת
   * האריח ("מהירות גלישה") ולא שורת הפירוט ("מהירות (הורדה/העלאה)")
   * משלימות את "לשנייה", ולכן המספר עצמו חייב לשאת אותה — על אותו
   * כרטיס יושב "100GB" של נפח גלישה, ושתי יחידות שנראות זהות על
   * שני דברים שונים הן בדיוק הקריאה השגויה שהקובץ הזה נלחם בה.
   */
  const unit = asGb ? "Gbps" : "Mbps";
  const value = (mbps: number) => nf.format(asGb ? mbps / 1000 : mbps);
  /*
   * ⚠️ תחילית אחת לזוג כולו, ולא "עד" לכל מהירות בנפרד: "עד 600/עד
   * 100" קורא כשתי עובדות ולא כזוג, ואין דרך לקשור תחילית אחת לחצי
   * אחד של "600/100".
   *
   * ⚠️ והנימוק שנכתב כאן קודם — "הרשומות שמצהירות על תקרה מצהירות
   * עליה על שתיהן (id 85)" — נכון ל-id 85 **בלבד**. בשמונה מתוך תשע
   * חבילות הבית שמסרו זוג (ids 73, 98, 99, 86, 124, 153, 154, 159)
   * ה-"עד" נאמר על ההורדה לבדה ("אינטרנט סיבים עד 1000/100"), ולכן
   * התחילית מסתייגת גם על מספר ההעלאה. זה הכיוון שמצמצם הבטחה
   * ולא מרחיב אותה, וזו הסיבה שהוא נשאר — לא העובדה שלא קיים.
   */
  const cap = upTo(pkg, "speed", spec.downloadMbps, upload);
  return upload != null
    ? `${cap}${value(spec.downloadMbps)}/${value(upload)}${unit}`
    : `${cap}${value(spec.downloadMbps)}${unit}`;
}

