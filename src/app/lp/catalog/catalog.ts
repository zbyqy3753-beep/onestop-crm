/**
 * מספר שאפשר להציג כמחיר (או כאחוז הנחה) — ולא מחרוזת שנראית כמו אחד,
 * לא `0` ולא ערך שלילי.
 *
 * ⚠️ אותה פונקציה בדיוק כמו `isMoney` ב-`savings.ts`, ומאותו טעם:
 * הקטלוג נכנס דרך `as unknown as Catalog`, כלומר אין ולידציה בזמן ריצה.
 * כאן היא מרוכזת כדי ששלושת השערים שמתחתיה (`isListable`, `afterPrice`
 * ו-`byPrice`) יקראו את אותה הגדרה של "מספר שמותר לדרג לפיו" — שתי
 * הגדרות שונות לאותו שדה הן בדיוק המלכודת שההערות כאן מתריעות עליה.
 *
 * ⚠️ מיוצאת כדי ש**גם הכרטיס** יקרא אותה הגדרה. `PackageCard` שאל
 * `pkg.price != null` על הכותרת בגודל 3xl, ולכן `price: 0` — הצורה
 * שהמחלץ מייצר כשלא קרא מחיר, וקיימת בפועל ב-ids 18 ו-22 — היה מודפס
 * "₪0 לחודש", כלומר חבילה חינם; ו-`discountPercent` הוזרק לכותרת בלי
 * שום שער, כך ש-id 144 (`discountPercent: null`) היה מדפיס "null%
 * הנחה". שתיהן נעצרות היום ב-`isListable` בלבד — שער אחד, במקום אחד,
 * שאם ייעקף (מסלול שמרנדר כרטיס בלי `listable`) מדפיס מספר שהרשומה
 * לא מסרה. השדה שהכרטיס עצמו גידר (`priceAfterPromo > 0`) הוא ההוכחה
 * שהאמת-מידה הזו כבר הוסכמה כאן — היא פשוט לא הוחלה על שני האחרים.
 */
export function isMoney(value: unknown): value is number {
  return typeof value === "number" && Number.isFinite(value) && value > 0;
}

/**
 * חבילה שאפשר להציג. חבילת חשמל נמדדת באחוז הנחה ולא במחיר, ולכן
 * לשתיהן תנאי משלהן.
 *
 * ⚠️ `editorial?.hidden` נשמר בבדיקה למרות שאין כאן שכבת עריכה: השדה
 * קיים בטיפוס, וקובץ קטלוג שיועתק בעתיד מגרסה שכן נשמרה איתו יכובד
 * מעצמו במקום להציג בשקט חבילה שהוסתרה.
 */
/**
 * ⚠️ `typeof === "number"` ולא `!= null`.
 *
 * הקטלוג נכנס לקוד דרך `as unknown as Catalog`, כלומר **אין ולידציה
 * בזמן ריצה** — הטיפוסים נבדקים על הקובץ שקיים היום, לא על הקובץ
 * שהרענון הבא יכתוב. הנתונים הנוכחיים נקיים (כל 90 המחירים מספריים),
 * אבל `"39.9" != null` הוא `true` וגם `"39.9" > 0` הוא `true`: מחיר
 * שיישאב פעם אחת כמחרוזת יעבור את השער הזה, יגיע ל-`shekels()` ול-
 * `perLinePrice`, ויוצג לגולש כ-`NaN`. השער הוא המקום היחיד שכל
 * החבילות עוברות בו, ולכן כאן נעצרת רשומה פגומה — בשקט ומראש.
 */
/*
 * ⚠️ `> 0` **בשני** הענפים.
 *
 * הענף החודשי דרש מחיר חיובי ("מחיר 0 מייצר חיסכון של מלוא החשבון"),
 * ואילו ענף החשמל הסתפק במספר סופי — כלומר `discountPercent: 0` עבר
 * את השער ועלה לדף כמסלול הנחה אמיתי, עם הכותרת "0% הנחה". גרוע
 * מזה: `afterPrice` ו-`byPrice` מדרגות חשמל כ-`-discountPercent`,
 * ולכן מסלול של 0% (או שלילי, שגם הוא עבר) מדורג כ**זול ביותר**
 * בקטגוריה ונכנס ל-`highlights` ול-`cheapest`. הקטלוג של היום נקי —
 * אין אף רשומה עם `discountPercent <= 0` — ולכן זה שער לרענון הבא,
 * בדיוק מאותו טעם שהענף החודשי נכתב כך.
 */
export function isListable(p: Package): boolean {
  if (p.editorial?.hidden) return false;
  return p.category === "electricity"
    ? isMoney(p.discountPercent)
    : isMoney(p.price);
}

export function listable(packages: Package[]): Package[] {
  return packages.filter(isListable);
}

/**
 * האם אחוז ההנחה שהרשומה מצהירה עליו הוא **תקרה** ולא שיעור קבוע.
 *
 * ⚠️ הכרטיס הדפיס "10% הנחה" במספר הגדול ביותר שלו על ids 135 ו-142,
 * שתיהן הנחה מדורגת לפי גובה החשבון (10% עד ₪149, ואז 8%/7%/6%/5%) —
 * כלומר לקוח בצריכה של ₪300 ומעלה מקבל חצי ממה שהכרטיס הכריז. ב-135
 * הכותרת שעל אותו כרטיס אומרת "עד 10% הנחה", כך ששתי אמירות סותרות
 * ישבו זו מעל זו. "לא יודעים — לא מבטיחים" הוא אותו כלל שחל בענף
 * החודשי על המחיר שאחרי ההטבה; לענף החשמל לא היה לו מקביל.
 *
 * ⚠️ נדרשת התאמה **לאותו מספר** שהרשומה מצהירה עליו, ולא עצם הימצאות
 * המילה "עד" בפרוזה: רק כך השער מצמצם הבטחה ולא מרחיב אותה.
 *
 * ⚠️ הפונקציה יושבת כאן ולא ב-`format.ts`, למרות שהצרכנים שלה הם
 * כרטיס וטבלה: `electricityRank` שמתחתיה חייבת אותה, `format.ts` כבר
 * מייבא מכאן (`logicName`), וייבוא בכיוון ההפוך היה סוגר מעגל.
 * `format.ts` מייצאת אותה מחדש, כך שאף צרכן לא ידע על ההעברה.
 */
export function discountIsCapped(p: Package): boolean {
  if (p.category !== "electricity" || typeof p.discountPercent !== "number") return false;
  /*
   * ⚠️ `logicName` ולא `p.name`. זו לוגיקה שמחפשת ראיה בתוך השם, ולכן
   * היא כפופה לאינווריאנט ב-`catalog.ts:51-58`. `displayName` **קוטעת
   * כל מה שאחרי `[line]`** (קורה בפועל ב-id 36), ולכן רשומת חשמל
   * שמשפט התקרה שלה נופל אחרי הסימן הייתה מפסיקה להיזהות כתקרה
   * והכרטיס היה מבטיח שיעור קבוע במקום "עד".
   */
  /*
   * ⚠️ וגם `priceAfterPromoNote` — השדה **הרביעי**, זה שקיים כדי להחזיק
   * את המשפט של הספק על מה שקורה להטבה. חמשת שערי הנוסח ב-`savings.ts`
   * קוראים את ארבעת השדות דרך `gateText`, והשער הזה נעצר על שלושה.
   * הקטלוג של היום משאיר את השדה ריק בכל 19 רשומות החשמל, ולכן אין כאן
   * שינוי במספר מוצג — אבל "עד 10% בהתאם לגובה החשבון" שייכתב דווקא
   * שם הוא תקרה שהכרטיס היה מבטיח כשיעור קבוע.
   */
  const prose = [logicName(p), p.description, p.benefits, p.priceAfterPromoNote]
    .filter(Boolean)
    .join(" ");
  /*
   * ⚠️ `עד` כמילה ולא כתת-מחרוזת: שתיים מ-19 רשומות החשמל הן מסלולי
   * **ועד בית** (142, 145), ו-"ועד 10%" אינו הצהרת תקרה.
   */
  for (const m of prose.matchAll(/(?<![א-ת])עד\s*(\d+(?:[.,]\d+)?)\s*%/g)) {
    if (Number(String(m[1]).replace(",", ".")) === p.discountPercent) return true;
  }
  return false;
}

/**
 * ⚠️ קבוע ולא מקדם. מסלול חלקי-שעות יורד **קבוצה שלמה**, ולא אחוז
 * מוכפל — ראה ההסבר ב-`electricityRank`. 1000 גדול מכל אחוז אפשרי
 * (0-100) ולכן אף אחוז אינו יכול להעלות מסלול חלקי מעל מסלול מלא.
 */
const PARTIAL_HOURS_GROUP = 1000;

/**
 * ערך הדירוג של מסלול חשמל — אחוז ההנחה **אחרי** מה שהוא לא מבטיח.
 *
 * ⚠️ עד כה דורג כל מסלול לפי `-discountPercent` בלבד, ושני שדות
 * שהרשומה כן מסרה לא השתתפו בדירוג: `spec.allHours` ו-`discountIsCapped`.
 * התוצאה הייתה ששלושת המסלולים שהדף הכריז עליהם כמובילים
 * (ids 150, 147, 137 — כולם 20%) הם מסלולי **שעות לילה בלבד**
 * ("23:00 עד 7:00"), בזמן שכל מסלול שההנחה שלו חלה על החשבון כולו
 * (5%-6%) דורג מתחת לשלושתם. 20% על צריכת לילה שווה לרוב משק בית
 * פחות מ-6% על החשבון כולו, ולכן הדף המליץ בדיוק על המסלולים
 * הפחות טובים עבור המבקר הטיפוסי.
 *
 * ⚠️ האחוז החלקי **אינו** מוכפל במקדם. חלקו של הלילה בחשבון אינו
 * בקטלוג, וכל מקדם היה הופך ניחוש למספר שנראה מחושב. במקום זאת
 * "כל השעות" מדורג לפני כל מסלול חלקי-שעות, והאחוז מכריע רק בתוך
 * הקבוצה — אותה כנות של "לא יודעים, לא מבטיחים". המסלולים החלקיים
 * נשארים גלויים בקטלוג, עם אריח השעות שלהם לידם.
 *
 * ⚠️ תקרה ("עד 10%") מדורגת אחרי שיעור קבוע באותו אחוז, מאותו טעם.
 */
export function electricityRank(p: Package): number {
  if (!isElectricity(p) || !isMoney(p.discountPercent)) return Infinity;
  /*
   * ⚠️ הקנס חל על מי ש**הצהיר** על שעות חלקיות, ולא על מי ששתק.
   * ל-`allHours` אין מצב "לא ידוע", וחמש רשומות נושאות `allHours: false`
   * **וגם** `hoursText: null` (ids 135, 139, 140, 141, 142) — כלומר אין
   * בהן שום הצהרה על שעות, ושתיים מהן אף אומרות את ההפוך בתיאור
   * ("קבלת הנחה קבועה לאורך כל שעות היממה" ב-142, "7% הנחה קבועה בכל
   * שעות היום" ב-139). הן ירדו קבוצה שלמה בלי סיבה שהגולש רואה:
   * `cardStats` — האחות שקוראת את אותם שני שדות — אינה מדפיסה להן
   * אריח שעות כלל, ולכן אין על המסך דבר שמסביר את ההורדה.
   *
   * התוצאה הייתה שתפריט המיון "הנחה: מהגבוהה לנמוכה" החזיר סדר שאינו
   * מונוטוני בכלל (6%, 6%, 6%, 5%, 20%, 20%, …) — התווית מבטיחה סדר
   * לפי האחוז, והסדר לא היה כזה. זו הטעות ההפוכה של הקנס הזה, לא
   * ה-regression שהוא נכתב למנוע.
   *
   * ⚠️ שתיקה נקראת כ"כל השעות" ולא כ"לא ידוע", בדיוק כמו ש-`afterPrice`
   * קוראת היעדר הצהרת עלייה כ"אותו מחיר" ולא שולחת אותה לסוף הרשימה.
   */
  /*
   * ⚠️ `hasSpec` לפני כל קריאה מתוך `spec`. הפונקציה הזו היא הערך
   * שלפיו `byPrice` ו-`afterPrice` מדרגות **כל** מסלול חשמל, כלומר היא
   * נקראת מתוך קומפרטור בכל מיון בעמוד — ו-`spec: null` אחד זרק כאן
   * `TypeError` שהפיל את רינדור השרת של `/lp` כולו (אומת: `cheapest`
   * על שתי רשומות או יותר, וכן `sortCatalog` בכל ארבעת המיונים).
   * רשומה בלי `spec` שמיש אינה מצהירה דבר על שעות, ולכן היא נקראת
   * כמי ש**שתק** — אותה קריאה בדיוק שההערה למעלה מנמקת.
   */
  /*
   * ⚠️ מחרוזת **לא ריקה**, ולא `!= null`. `cardStats` — האחות שההערה
   * למעלה מצטטת כהצדקה לקנס ("אינה מדפיסה להן אריח שעות כלל, ולכן אין
   * על המסך דבר שמסביר את ההורדה") — בודקת
   * `typeof spec.hoursText === "string" && spec.hoursText`, כלומר
   * `hoursText: ""` אינו מצייר אריח. השער כאן קרא `""` כהצהרה על שעות
   * חלקיות והוריד את המסלול **קבוצה שלמה** בלי שום דבר על המסך שמסביר
   * זאת — בדיוק ה-regression שההערה מעל השורה הזו מתעדת, עד לאותו
   * מיון "הנחה: מהגבוהה לנמוכה" שחוזר להיות לא-מונוטוני.
   *
   * ⚠️ ו-`allHours !== true` ולא `!p.spec.allHours`: `"false"` כמחרוזת
   * — הצורה שהמחלץ מייצר כשהוא קורא שדה טקסטואלי, והצורה ש-`=== true`
   * נכתב נגדה ב-`serviceCounts`, ב-`isRecommended` ובענף הבית של
   * `isComparable` — הוא **אמת** ב-JS, ולכן מסלול שהצהיר "23:00 עד
   * 7:00" חמק מהקנס וחזר לראש הדף עם 20% על צריכת לילה. ההצהרה שהקנס
   * נשען עליה היא `hoursText`; הדגל רק מבטל אותה, ולכן הוא מבטל רק
   * כשהוא בוליאן אמת ולא כשהוא ערך שאי אפשר לקרוא.
   */
  const partialHours =
    hasSpec(p) &&
    p.spec.allHours !== true &&
    typeof p.spec.hoursText === "string" &&
    p.spec.hoursText !== "";
  return (
    (partialHours ? PARTIAL_HOURS_GROUP : 0) - p.discountPercent + (discountIsCapped(p) ? 0.5 : 0)
  );
}

/**
 * ערך הדירוג של "כמה תשלמו כשההטבה נגמרת".
 *
 * ⚠️ משותף למיון ב-`CatalogBrowser` — פונקציה אחת. חשמל הוא אחוז הנחה
 * ולכן מדורג בשלילה (הנחה גדולה = "זול יותר"); חבילה שלא דיווחה על
 * עלייה שומרת על מחירה, כי הקריאה הכנה של "לא פורסמה עלייה" היא "אותו
 * מחיר" ולא "לא ידוע, לסוף הרשימה".
 */
export function afterPrice(p: Package): number {
  // ⚠️ `-Infinity` ולא `0`, כדי להסכים עם `byPrice`. שתי הפונקציות
  // מדרגות את אותו שדה, והשתיקה של `?? 0` הייתה ממקמת רשומה פגומה
  // כזולה ביותר בעמוד בעוד `byPrice` שולח אותה לסוף. אף אחת מהן אינה
  // ניתנת להגעה היום (`isListable` פוסל `discountPercent` ריק), אבל
  // שתי ברירות מחדל הפוכות לאותו שדה הן מלכודת לרענון הבא.
  if (p.category === "electricity") {
    return electricityRank(p);
  }
  return isMoney(p.priceAfterPromo)
    ? p.priceAfterPromo
    : isMoney(p.price)
      ? p.price
      : Infinity;
}

/** כמה חבילות מציג הדף בפועל, לפי קטגוריה. */
export function listableCounts(packages: Package[]) {
  const shown = listable(packages);
  return {
    total: shown.length,
    cellular: shown.filter((p) => p.category === "cellular").length,
    home: shown.filter((p) => p.category === "home").length,
    electricity: shown.filter((p) => p.category === "electricity").length,
  };
}

/**
 * המספרים שמאחורי רצועת "מה אנחנו משווקים".
 *
 * ⚠️ `internet`, `tv` ו-`bundle` **חופפים בכוונה**: חבילת טריפל נספרת
 * בשלושתם, כי כל אחד מהם עונה על שאלה אחרת שהמבקר שואל ("יש לכם
 * טלוויזיה?"). לכן אין לחבר אותם — הסכום גדול מ-`home`.
 *
 * ⚠️ מונה קו הטלפון יושב ב-`phoneCount` שמתחת ולא כשדה נוסף כאן, כדי
 * שהצורה שהמשטחים והבדיקות הקיימות משוות אליה תישאר כפי שהיא. הוא
 * קורא את אותם שערים בדיוק (`listable` → `isHomeSpec` → `hasSpec`),
 * כלומר זה אח של השדות כאן ולא הגדרה שנייה.
 */
export function serviceCounts(packages: Package[]) {
  const shown = listable(packages);
  // ⚠️ `isHomeSpec` ולא `p.category === "home"` עם `as HomeSpec`: ההמרה
  // הכריזה `HomeSpec` על פרמטר מטיפוס `Package`, כלומר גם על רשומת
  // חשמל. היא נכונה היום רק מפני שהיא מוחלת על מערך שכבר סונן — שער
  // שאין לו שום דבר בטיפוסים שמחזיק אותו במקום.
  // ⚠️ `hasSpec` אחרי `isHomeSpec`: הראשון בודק קטגוריה בלבד (ראה
  // ההערה שלמעלה), והשדות נקראים מתוך `spec` מיד אחריו. `spec: null`
  // על רשומת בית אחת זרק כאן `TypeError` — והקורא הוא השורה השנייה של
  // `page.tsx`, כלומר הדף כולו חזר 500 במקום להחסיר חבילה אחת ממונה.
  const home = shown.filter(isHomeSpec).filter(hasSpec);
  /*
   * ⚠️ אותו תיקון בדיוק כמו ב-`isComparable` ב-`savings.ts`, ומאותו
   * טעם: סטינג "החבילה המושלמת" (id 4) רשומה `hasInternet: true`
   * למרות שהיא שירות סטרימינג בלבד — המחלץ קרא את המילה "אינטרנט"
   * בתיאור. המחשבון כבר מסרב להתייחס אליה כאינטרנט, ובלי השורה הזו
   * אותה שכבה הצהירה שני דברים סותרים על אותה רשומה: הכרטיס
   * "אינטרנט וסיבים" ספר 30 והמחשבון ספר 29.
   *
   * ⚠️ הסינון חל על אינטרנט ועל החבילה המשולבת בלבד. `tv` דווקא
   * **כן** אמור לספור אותה — היא באמת טלוויזיה.
   */
  /*
   * ⚠️ `=== true` ולא הערך עצמו — אותו תיקון שענף הבית ב-`isComparable`
   * קיבל ולא הוחל כאן. `"false"` כמחרוזת (הצורה שהמחלץ מייצר כשהוא
   * קורא שדה טקסטואלי) הוא אמת ב-JS, ולכן רצועת השירותים הייתה סופרת
   * אינטרנט או טלוויזיה לרשומה שהדגל שלה דווקא כבוי — ובאותו עמוד
   * המחשבון, שכן מגודר, היה סופר אחרת. שני מספרים סותרים לאותו נתון
   * הם בדיוק מה שהתיקון מ-e9fc39f (id 4) נכתב למנוע.
   */
  const realInternet = home.filter(
    (p) => p.spec.hasInternet === true && !typeText(p).includes("TV"),
  );
  return {
    cellular: shown.filter((p) => p.category === "cellular").length,
    internet: realInternet.length,
    tv: home.filter((p) => p.spec.hasTv === true).length,
    bundle: realInternet.filter((p) => p.spec.hasTv === true).length,
    electricity: shown.filter((p) => p.category === "electricity").length,
  };
}

/**
 * כמה חבילות בית כוללות קו טלפון — המונה של האריח השישי בדף.
 *
 * ⚠️ קיים כי `hasPhone` היה **הדגל היחיד** ב-`HomeSpec` שאף משטח
 * בקטלוג לא קרא, והחור לא היה תיאורטי: id 83 ("בזק טלפון - מדברים 50
 * דקות", `hasPhone: true`, `hasInternet: false`, `hasTv: false`) נספר
 * ב-`listableCounts.home` וב-`CatalogTabs`, ומוצג בקטלוג — אבל **באף
 * אחד מחמשת אריחי "מה אנחנו משווקים"** (אומת: 55+29+16+13+18 כיסו 105
 * מ-106 החבילות שהדף מציג). כלומר הדף מציג חבילה שהוא מצהיר שאינו
 * משווק. זו אותה סתירה בין מספר מוצהר לרשימה מוצגת שהקובץ הזה מתוקן
 * ממנה שוב ושוב, רק מהצד שבו המונה מצהיר **פחות** ולא יותר.
 *
 * ⚠️ חופף ל-`internet`/`tv`/`bundle` בכוונה, מאותו טעם שכתוב שם: שש
 * מתוך שבע החבילות שנושאות קו הן טריפל, ו"יש לכם קו טלפון?" היא שאלה
 * נפרדת שהמבקר שואל. אין לחבר את האריחים.
 *
 * ⚠️ אותם שערים בדיוק כמו `serviceCounts` — `listable`, `isHomeSpec`
 * ואחריו `hasSpec` — ולא קריאה ישרה מ-`spec`, ו-`=== true` ולא הערך
 * עצמו (`"false"` כמחרוזת הוא אמת ב-JS). שתי הגדרות לאותו שדה הן
 * המלכודת שכל הקובץ הזה מתריע עליה.
 */
export function phoneCount(packages: Package[]): number {
  return listable(packages)
    .filter(isHomeSpec)
    .filter(hasSpec)
    .filter((p) => p.spec.hasPhone === true).length;
}

/**
 * ערך הדירוג של "כמה זה עולה היום".
 *
 * ⚠️ מסלול חשמל מדורג לפי אחוז ההנחה בסימן שלילי — כלומר **כל** מסלול
 * חשמל קטן מכל מחיר חודשי. זו הסיבה שכל מי שקורא ל-`cheapest` חייב
 * לסנן לקטגוריה קודם.
 */
export function byPrice(a: Package, b: Package): number {
  // ⚠️ אותם שערים בדיוק כמו ב-`afterPrice`, ולא `?? Infinity` לבדו:
  // `price: 0` (הצורה שהמחלץ מייצר כשהוא לא קרא מחיר — ראה ids 18/22)
  // דורג כזול ביותר בעמוד בזמן ש-`afterPrice` שלחה אותו לסוף.
  // ⚠️ `electricityRank` ולא `-discountPercent` כאן גם: שתי הפונקציות
  // מדרגות את אותו שדה, וההערה שמעל `afterPrice` דורשת שיסכימו. שעות
  // חלקיות שהיו משתתפות באחת ולא בשנייה היו מחזירות בדיוק את חוסר
  // ההסכמה שהקובץ הזה כבר תיקן פעם אחת.
  const value = (p: Package) =>
    p.category === "electricity"
      ? electricityRank(p)
      : isMoney(p.price)
        ? p.price
        : Infinity;
  // ⚠️ השוואה ולא חיסור. שתי רשומות בלי מחיר שמיש מקבלות שתיהן
  // `Infinity` (ids 18 ו-22 בקטלוג של היום), ו-`Infinity - Infinity`
  // הוא `NaN` — קומפרטור שמחזיר NaN נותן סדר שתלוי בסדר הקלט, דווקא
  // בשער שכל תפקידו לשלוח רשומה פגומה לסוף.
  const va = value(a);
  const vb = value(b);
  return va === vb ? 0 : va < vb ? -1 : 1;
}

/** הזולה ביותר לפי המחיר שמוצג היום. */
export function cheapest(packages: Package[], limit = 3): Package[] {
  return listable(packages).slice().sort(byPrice).slice(0, limit);
}

/**
 * הבחירה של הדף לקטגוריה: מוצמד ידנית קודם, אחריו הדגל "מומלץ" שהגיע
 * מהחברה, ורק אז מחיר.
 *
 * ⚠️ באתר הציבורי המיון הזה מגיע משכבת העריכה (`byEditorialThen`).
 * כאן אין מסד כזה, ולכן הסדר משוחזר מהשדות שקיימים בקטלוג עצמו. אם
 * יום אחד תיכנס לכאן שכבת עריכה — זו הפונקציה שצריכה להיעלם לטובתה.
 */
/**
 * האם הרשומה מסומנת כמומלצת — **ההגדרה היחידה**, לכל ארבעת הקוראים.
 *
 * ⚠️ `=== true` ולא טרות'יניס, ובמקום אחד. הדגל נקרא בארבעה משטחים
 * (`highlights`, `serviceCounts`, `sortCatalog` ב-`CatalogBrowser`, והתג
 * ב-`PackageCard`), ושלוש הגדרות שונות הסתדרו ביניהן רק כל עוד הנתון
 * נקי: `recommended: "false"` — הצורה שהמחלץ מייצר לשדה טקסטואלי —
 * הדליק את התג ודירג ראשון, ו-`recommended: 0` הדפיס "0" לשורת התגים
 * (`0 && jsx` מחזיר `0`, ו-React מרנדר אותו). ההערה ב-`sortCatalog`
 * הצהירה שההגדרה המצמצמת "שייכת ל-`catalog.ts`, שם `highlights` תקבע
 * אותה לכל הקוראים בבת אחת" — זו השורה הזו.
 */
export function isRecommended(p: Package): boolean {
  return p.recommended === true;
}

export function highlights(packages: Package[], category: Category, limit = 3): Package[] {
  /*
   * ⚠️ `=== true` ולא טרות'יניס. `recommended: "false"` (הצורה שהמחלץ
   * מייצר כשהוא קורא שדה טקסטואלי) הוא אמת ב-JS, ולכן רשומה שהדגל שלה
   * דווקא **כבוי** הייתה מדורגת ראשונה ברצועת "חבילות נבחרות". אותו
   * תיקון בדיוק שנעשה ל-`hasInternet` ב-`serviceCounts` ול-`recommended`
   * בציר המיון של `CatalogBrowser` — וזה הקורא השלישי של אותו שדה,
   * שנשאר מאחור.
   */
  const rank = (p: Package) => (p.editorial?.featured ? 0 : isRecommended(p) ? 1 : 2);
  return listable(byCategory(packages, category))
    .slice()
    .sort((a, b) => rank(a) - rank(b) || byPrice(a, b))
    .slice(0, limit);
}

/**
 * הספקים שיש להם בפועל חבילה גלויה, לפי עומק הקטלוג.
 *
 * ⚠️ המונה נספר מהרשימה שנמסרה ולא מ-`provider.count` שהגיע מהחילוץ:
 * ספק שכל חבילותיו נפלו ב-`isListable` חייב להיעלם מהרצועה, ולא
 * להישאר כלוגו שאין מאחוריו כלום.
 */
/*
 * ⚠️ הרשימה נבנית מ-`packages` ולא מ-`catalog.providers` לבדו.
 *
 * הפונקציה קיבלה מערך חבילות, ספרה ממנו — ואז הרכיבה את הרשימה
 * מ-`catalog.providers`, כלומר ספק שיש לו חבילה **במערך שנמסר** אך
 * אינו רשום ברשימת הספקים של הקטלוג נעלם מהרצועה בשקט. היום 12 מתוך
 * 12 הספקים מופיעים בשני המקומות ולכן הבאג רדום, אבל `providers` היא
 * המספר שהדף מצהיר עליו ("אנחנו עובדים עם N חברות"), ורענון שיוסיף
 * חבילה של ספק חדש בלי להוסיף אותו ל-`providers` של הקטלוג מוריד את
 * המספר במקום להעלות אותו. `catalog.providers` נשאר **מקור המטא-דאטה
 * והסדר** (לוגו, שם, קטגוריות); מי שחסר שם נבנה מה-`ProviderRef`
 * שעל החבילה עצמה.
 */
/**
 * ה-`slug` של הספק, או `null` כשאין ממה לקרוא אותו.
 *
 * ⚠️ `ProviderRef` שמיש לפני הקריאה ממנו. `provider: null` זרק
 * `TypeError` על `.slug` — ושני קוראים שונים עושים את זה באותו רינדור:
 * רצועת הלוגואים בהירו (`providers` מתחת, דרך `page.tsx`) ומסנן החברה
 * ב-`CatalogBrowser` (`matchesFilters`/`providerFacets`). כלומר רשומה
 * אחת בלי ספק הפילה את רינדור השרת של הדף כולו.
 *
 * ⚠️ שער **אחד** ולא העתקה בכל קורא. זה הדפוס שנמצא כאן שבע פעמים:
 * שער שחובר למשטח אחד ולא לאחיו. שער מקומי ב-`CatalogBrowser` היה גם
 * ביטחון מדומה — `providers` קוראת את אותו שדה ומתרסקת קודם.
 *
 * ⚠️ מחרוזת לא ריקה ולא רק "לא null": ה-`slug` הוא המפתח שמחבר את
 * הרשומה ל-`catalog.providers` (לוגו, שם, סדר), ומפתח שאינו מחרוזת
 * מייצר ספק-רפאים בלי לוגו ובלי שם.
 */
export function providerSlug(p: Package): string | null {
  const ref = p.provider;
  if (ref == null || typeof ref !== "object") return null;
  return typeof ref.slug === "string" && ref.slug ? ref.slug : null;
}

/**
 * שם הספק להצגה, עם נפילה חזרה ל-`slug`.
 *
 * ⚠️ מאותו טעם כמו `providerSlug`: `name` שאינו מחרוזת היה מצייר
 * "null" בתיבת הסימון של מסנן החברה. ה-`slug` הוא לא כותרת יפה, אבל
 * הוא מזהה אמיתי — ותיבת סימון בלי שם היא מסנן שאין דרך לדעת מה הוא
 * מסנן.
 */
export function providerName(p: Package): string {
  const ref = p.provider;
  const name = ref != null && typeof ref === "object" ? ref.name : null;
  return typeof name === "string" && name ? name : (providerSlug(p) ?? "");
}

/**
 * שם קובץ הלוגו, או `null` כשאין.
 *
 * ⚠️ הקורא הוא `<ProviderLogo>` בכרטיס ובמגש ההשוואה, והוא בונה
 * `/providers/${logo}` — כלומר `logo: null` היה הופך ל-`/providers/null`,
 * בקשה 404 על כל כרטיס. `provider: null` היה גרוע מזה וזרק `TypeError`
 * ברינדור השרת (אומת בבדיקה: הכרטיס הפיל את הדף כולו אחרי שהמסנן
 * והרצועה כבר גודרו). שם הספק מודפס ממילא לצד הלוגו בשני המשטחים,
 * ולכן לוגו חסר הוא פחות מידע ולא כרטיס שבור.
 */
export function providerLogo(p: Package): string | null {
  const ref = p.provider;
  const logo = ref != null && typeof ref === "object" ? ref.logo : null;
  return typeof logo === "string" && logo ? logo : null;
}

export function providers(packages: Package[]): Provider[] {
  const shown = listable(packages);
  const counts = new Map<string, number>();
  const refs = new Map<string, Package[]>();
  for (const p of shown) {
    // ספק שאין לו שום חבילה שמישה אינו אמור להופיע — זה בדיוק הכלל
    // שההערה שמעל הפונקציה מצהירה עליו. ראה `providerSlug`.
    const slug = providerSlug(p);
    if (slug == null) continue;
    counts.set(slug, (counts.get(slug) ?? 0) + 1);
    const bucket = refs.get(slug);
    if (bucket) bucket.push(p);
    else refs.set(slug, [p]);
  }

  /*
   * ⚠️ גם רשימת הספקים של הקטלוג עצמה נבדקת, ולא רק ה-`ProviderRef`
   * שעל החבילה: רשומה פגומה **אחת** במערך הזה (`null`, או `slug` שאינו
   * מחרוזת) זרקה את אותו `TypeError` ב-`.map`, לפני שאף חבילה נבדקה.
   * מי שנופל כאן עדיין יכול להיבנות מה-`ProviderRef` שעל החבילה
   * (`fromPackages` מתחת), כלומר הרצועה מאבדת מטא-דאטה ולא ספק.
   */
  const catalogProviders = catalog.providers.filter(
    (p): p is Provider => p != null && typeof p === "object" && typeof p.slug === "string" && !!p.slug,
  );
  const known = new Set(catalogProviders.map((p) => p.slug));
  /*
   * ⚠️ גם השם והלוגו **שברשימת הספקים** עוברים את אותם שערים.
   *
   * הסינון שמעל בדק `slug` בלבד, ושאר השדות הועברו כמות שהם ישר
   * לרצועה: רשומת ספק עם `name: null` ציירה בהירו `title="חבילות null"`
   * (אומת), כלומר בדיוק מה ש-`providerName` נכתב למנוע — רק שהוא הוחל
   * על ה-`ProviderRef` שעל החבילה ולא על האח שלו, רשומת הקטלוג. זה
   * הדפוס שהקובץ הזה מתעד שוב ושוב: שער שחובר למשטח אחד ולא לשני.
   *
   * ⚠️ הנפילה חזרה היא ל-`ProviderRef` של חבילה אמיתית של אותו ספק,
   * ולא ל-`slug` ישר: `fromCatalog` נבנה רק לספק שיש לו חבילה גלויה
   * (`counts > 0`), ולכן ה-`ref` קיים תמיד — ודווקא הוא עשוי להחזיק את
   * השם היפה שרשומת הקטלוג איבדה. `providerName` ממילא נופל ל-`slug`.
   */
  const fromCatalog: Provider[] = catalogProviders
    .filter((p) => (counts.get(p.slug) ?? 0) > 0)
    .map((p) => {
      const own = refs.get(p.slug)!;
      return {
        ...p,
        name: typeof p.name === "string" && p.name ? p.name : providerName(own[0]),
        logo: typeof p.logo === "string" && p.logo ? p.logo : (providerLogo(own[0]) ?? ""),
        count: counts.get(p.slug)!,
      };
    });
  const fromPackages: Provider[] = [...refs.entries()]
    .filter(([slug]) => !known.has(slug))
    .map(([slug, own]) => ({
      slug,
      name: providerName(own[0]),
      logo: providerLogo(own[0]) ?? "",
      categories: [...new Set(own.map((p) => p.category))],
      count: own.length,
    }));

  return [...fromCatalog, ...fromPackages].sort((a, b) => b.count - a.count);
}

/**
 * הצהרה מילולית על עליית מחיר שבאמת תגיע למסך.
 *
 * ⚠️ מחרוזת לא ריקה, בדיוק כמו `promoRise` ב-`format.ts` — המשטח
 * **היחיד** שמדפיס את השדה הזה. השער המספרי לצידו (`isMoney` על
 * `priceAfterPromo`) כבר מרוכז כאן; זה היה החצי שנשאר כל אחד לעצמו.
 */
function hasRiseNote(p: Package): boolean {
  return typeof p.priceAfterPromoNote === "string" && p.priceAfterPromoNote !== "";
}

/** כמה חבילות מגלות את המחיר שאחרי ההטבה — נתון האמון של הדף. */
export function disclosedRiseCount(packages: Package[]): number {
  return listable(packages).filter(
    (p) =>
      p.category !== "electricity" &&
      // ⚠️ `isMoney` ולא `!= null`: `priceAfterPromo: 0` אינו הצהרה על
      // עליית מחיר אלא שדה שלא נקרא, ו"נתון האמון" של הדף אינו יכול
      // להיות מנופח על ידי בדיוק הרשומות שלא דיווחו כלום.
      // ⚠️ ואותו כלל בדיוק על ההערה המילולית. `!= null` ספר כהצהרה גם
      // `""`, גם `0` וגם אובייקט (אומת: כל אחד מהם הגדיל את המונה ב-1
      // בזמן ש-`promoRise` לא החזירה דבר) — כלומר הדף הצהיר על שקיפות
      // שאין מאחוריה שורה אחת על אף כרטיס. מונה אמון שסופר אחרת מהמשטח
      // שמדפיס הוא בדיוק שתי ההגדרות לאותו שדה שהקובץ הזה מתריע עליהן.
      (isMoney(p.priceAfterPromo) || hasRiseNote(p)),
  ).length;
}

/**
 * האם `afterPrice` באמת יודעת מה יעלה החבילה אחרי ההטבה.
 *
 * ⚠️ `priceAfterPromo` הוא השדה המספרי, אבל 11 חבילות בקטלוג מצהירות
 * על העלייה **בטקסט חופשי בלבד** (`priceAfterPromoNote`) ומשאירות את
 * המספר ריק — למשל "פקיעה אחרי שנה וחצי, מחיר לאחר פקיעה 44.9 ש״ח"
 * על חבילה שמחירה 29.9. `afterPrice` נופלת במקרה הזה ל-`price`, כלומר
 * למחיר ההטבה, ומדרגת את החבילה כאילו 29.9 הוא מחיר הקבע שלה.
 *
 * למיון בקטלוג זו טעות נסבלת — המחיר וההערה מוצגים זה לצד זה והקורא
 * רואה את שניהם. במחשבון החיסכון זו טעות שלא ניתן לעמוד מאחוריה: הוא
 * מבטיח במפורש "המחיר שנשאר גם אחרי תום ההטבה", ובלי הבדיקה הזו הוא
 * מתגמל בדיוק את החבילות שמסתירות את העלייה — חבילה שמצהירה על
 * `priceAfterPromo` מספרי נענשת ולעולם לא תנצח, וחבילה שקוברת את
 * אותה עלייה בהערה חופשית עולה לראש. פירסור ההערה עצמה לא נעשה כאן
 * בכוונה: הנוסח חופשי לגמרי (יש בו "+ 10 ₪ נתב" שצריך חיבור, "מ-100 ₪"
 * שהוא רצפה ולא מחיר), וניחוש שגוי היה מחזיר אותנו בדיוק לכותרת
 * המומצאת שהמחשבון נבנה כדי למנוע.
 */
/*
 * ⚠️ גם שדה מספרי **פגום** הוא "לא יודעים", ולא רק שדה ריק עם הערה.
 *
 * הבדיקה המקורית שאלה רק `priceAfterPromo == null`, כלומר `0` (או
 * מחרוזת, או מספר שלילי) נחשב מחיר-אחרי-הטבה ידוע לגמרי. זו בדיוק
 * הצורה שהמחלץ מייצר כשהוא לא הצליח לקרוא מספר — `price: 0` בשתי
 * רשומות קיימות הוא אותו פגם באותו קובץ — והתוצאה חמורה פעמיים:
 * המיון "מחיר אחרי ההטבה: מהזול ליקר" שם את הרשומה הזו **בראש**
 * הרשימה (`afterPrice` החזירה 0), והכרטיס מדפיס "אחרי ההטבה ₪0" על
 * חבילה שמחירה 39.9. `isComparable` ב-`savings.ts` כבר פוסל אותה
 * דרך `isMoney`; כאן השער היה חסר.
 */
/*
 * ⚠️ וכאן דווקא **כל** תוכן בשדה ההערה ולא `hasRiseNote`, בכוונה.
 *
 * `disclosedRiseCount` שואלת "האם נאמר לגולש משהו" ולכן היא כפופה למה
 * שהמסך מדפיס; הפונקציה הזאת שואלת את השאלה ההפוכה — "האם מותר להבטיח
 * שהמחיר נשאר" — וערך שאינו קריא בשדה שכל תפקידו להצהיר על עלייה הוא
 * סימן שלא יודעים, לא היתר. שתי ההגדרות נבדלות כאן בכוונה ולכל אחת
 * כתוב למה; זה לא העתק שנשכח.
 */
export function hasKnownAfterPrice(p: Package): boolean {
  if (p.priceAfterPromo != null && !isMoney(p.priceAfterPromo)) return false;
  return !(p.priceAfterPromoNote && p.priceAfterPromo == null);
}

/**
 * ── השערים על שדות הטקסט שהמשטחים של `/lp` **מדפיסים** ──────────────
 *
 * ⚠️ הקטלוג נכנס דרך `as unknown as Catalog`, כלומר **אין ולידציה בזמן
 * ריצה**: הטיפוס מובטח על `packages.json` שקיים היום ולא על הקובץ
 * שהרענון הבא יכתוב. שדה שצורתו בלתי צפויה ונקרא בלי שער אינו מפיל
 * כרטיס אחד — הוא זורק בתוך רינדור השרת ומחזיר את **כל** הדף ב-500.
 * אותו שער כבר נבנה פעם אחר פעם רמה אחת מתחת (`providerSlug`,
 * `specOf`, `isCount`, `priceAfterPromoNote` ב-`promoRise`) ונשכח
 * דווקא בשכבה שמדפיסה.
 *
 * ⚠️ המודול הזה הוא העלה שכל שלושת המשטחים שלי קוראים ממנו:
 * `CatalogBrowser` ו-`PackageCard` שניהם מייבאים מכאן, ו-`PackageCard`
 * אינו יכול לייבא מ-`CatalogBrowser` (ייבוא מעגלי). הבית הטבעי של
 * שתי הפונקציות הוא `catalog.ts`, לצד `displayName` ו-`providerSlug`,
 * ושם כל הקוראים — כולל סטודיו הפוסטים — היו קוראים הגדרה אחת; זו
 * העברה לבעל הקובץ ההוא, לא העתק נוסף.
 */

/**
 * שדה טקסט חופשי שמותר להדפיס, או `null`.
 *
 * ⚠️ אומת בפועל: `type: {}` זרק `Objects are not valid as a React
 * child` גם בשבב הסוג של `PackageCard` וגם בשבבי הסוג של
 * `CatalogBrowser` — כלומר רשומה אחת פגומה החזירה את `/lp` כולו
 * ב-500. `description`/`benefits` זורקים את אותה שגיאה ברגע שהגולש
 * פותח "פרטים מלאים", ובנוסף `benefits` הוא אחד משלושת התנאים שפותחים
 * את הפאנל — כלומר ערך פגום גם מצייר כפתור וגם מפיל אותו בלחיצה.
 *
 * ⚠️ `typeof === "string"` ולא טרות'יניס, בדיוק כמו השער על
 * `priceAfterPromoNote` ב-`promoRise` ועל `p.type` ב-`savings.ts:441`
 * (שם ההערה מתעדת `type: 5` שמפיל `TypeError` על `.includes`). מספר
 * אינו זורק ב-React אבל הוא גם אינו תווית: שבב שכתוב בו "5" הוא מסנן
 * שאין דרך לדעת מה הוא מסנן.
 *
 * ⚠️ גם מחרוזת ריקה נופלת: שבב ריק הוא פקד בלי שם, ו-`typeFacets`
 * ממילא דילג על `!p.type`.
 */
export function freeText(value: unknown): string | null {
  return typeof value === "string" && value !== "" ? value : null;
}

/**
 * ה-`type` של החבילה **יחד עם** ה-`badges` שלה, כמחרוזת אחת לחיפוש.
 *
 * ⚠️ חי כאן ולא ב-`savings.ts` כי **שני** צרכנים שואלים את אותה שאלה
 * ("האם הרשומה הזאת היא טלוויזיה?") וענו עליה אחרת: `isComparable`
 * דרך הפונקציה הזאת, ו-`serviceCounts` בהשוואה מדויקת `type !== "TV"`.
 * התוצאה הייתה שתי אמירות סותרות על אותה רשומה באותו עמוד — רצועת
 * השירותים סופרת חבילה כאינטרנט בעוד המחשבון פוסל אותה כטלוויזיה —
 * וזו בדיוק הסתירה שהתיקון מ-e9fc39f (id 4) נכתב למנוע. העותק הכפול
 * היה הפריט הפתוח מסבב 32; מאוחד כאן כדי שלא יסחף.
 *
 * ⚠️ `badges` שאינו מערך **אינו** נקרא כסימן, וזו הכרעה מתועדת ולא
 * השמטה — ההנמקה המלאה ומחירה יושבים בהערה שמעל `isComparable`
 * ב-`savings.ts` ובבדיקה ב-`tools/round34-savings.test.mjs`. אל
 * תהפכו את הכיוון כאן בלי לקרוא אותן: פסילה על `badges` פגום מוציאה
 * רשומה **בריאה** מבריכת ההשוואה ומקטינה את הכותרת בשקט.
 */
export function typeText(p: Package): string {
  const type = typeof p.type === "string" ? p.type : "";
  const badges = Array.isArray(p.badges)
    ? p.badges.filter((b): b is string => typeof b === "string").join(" ")
    : "";
  return `${type} ${badges}`;
}

/**
 * שם החבילה **להצגה**.
 *
 * ⚠️ דרך `displayName` ולא `pkg.name` ישירות. `basePackages` משאירה שם
 * שאינו מחרוזת כמות שהוא **בכוונה** ("דריסה הייתה מוחקת את הראיה
 * היחידה שהרשומה פגומה"), ולכן השער חייב לשבת בצד שמדפיס — והוא נבנה
 * שם רק לצרכן אחד: `src/lib/posts/catalog.ts` קורא `displayName(p.name)`,
 * בזמן ששלושת המשטחים של הדף עצמו קראו את השדה חשוף. אומת בפועל:
 * `name: {}` זרק `Objects are not valid as a React child` בכותרת
 * הכרטיס, בשבב של מגש ההשוואה **וב**כותרת העמודה של טבלת ההשוואה.
 * זו הפעם השמינית שאותו שער חובר למשטח אחד ולא לאחיו.
 *
 * ⚠️ מחרוזת ריקה ולא `String(raw)` — זו ההכרעה של `displayName` עצמה
 * ("כותרת 'null' גרועה מכותרת חסרה"), ואותו קו שבו `ProviderLogo`
 * מחזיר `null` במקום לצייר `/providers/null`.
 */
export function packageTitle(pkg: Package): string {
  return displayName(pkg.name);
}

/**
 * שם החבילה לתוך **שם נגיש** — מובטח שאינו ריק.
 *
 * ⚠️ `packageTitle` מחזירה "" לרשומה פגומה, ו-"" בתוך `aria-label`
 * מייצר "הסר את  מההשוואה" — פקד שמכריז על פעולה בלי לומר על מה.
 * הנפילה חזרה היא לשם הספק, בדיוק כמו `providerName` שנופלת ל-`slug`
 * ("ה-slug הוא לא כותרת יפה, אבל הוא מזהה אמיתי"). בכותרת הנראית
 * לעומת זאת אין נפילה חזרה: שם הספק מודפס שם ממילא בשורה שמתחתיה.
 */
export function packageLabel(pkg: Package, providerFallback: string): string {
  return packageTitle(pkg) || providerFallback;
}
