export const catalog = catalogJson as unknown as Catalog;

/**
 * שם חבילה כפי שמציגים אותו לגולש.
 *
 * ⚠️ המחלץ משאיר בשם שאריות שלו, והן עולות לייצור כמות שהן: `[line]`
 * הוא מפריד גולמי שהפך לחלק מהכותרת ("סלקום משפחתי פלוס [line] חבילה
 * זו מיועדת לבעלי כרטיס אשראי בלבד" — וההמשך שאחריו הוא ממילא השורה
 * הראשונה של ה-`description`), `*2*` הוא סימון פנימי של גרסה שנייה
 * לאותה חבילה, ורווח כפול הוא פשוט טקסט שנקטע. כל השאריות האלה נראות
 * היום בדף החי.
 *
 * ⚠️ הניקוי כאן ולא בקובץ ה-JSON: הקובץ נכתב מחדש בכל רענון קטלוג
 * (ובשני מקומות — ראה ההערה למעלה), ולכן תיקון ידני בו נמחק בפעם
 * הבאה. `*IBC*` נשמר בסוגריים ולא נמחק כי IBC הוא שם התשתית ומבדיל
 * בין שתי חבילות סיבים של אותו ספק — רק המספר הוא סימון פנימי.
 *
 * ⚠️ נפילה חזרה למקור כשהניקוי מרוקן את השם: כותרת ריקה גרועה
 * משארית, ושם שכולו סימון פנימי הוא סימן שהנחת היסוד כאן לא מתקיימת.
 */
/*
 * ⚠️ `unknown` ולא `string`, ושער טיפוס בשורה הראשונה.
 *
 * הקטלוג נכנס לקוד דרך `as unknown as Catalog`, כלומר **אין ולידציה
 * בזמן ריצה** — הטיפוס מובטח על הקובץ שקיים היום ולא על הקובץ שהרענון
 * הבא יכתוב. `name: null` (או מספר) זרק כאן `TypeError` על `.split`,
 * והקורא הראשון הוא `basePackages()` — השורה הראשונה של
 * `page.tsx`, כלומר **רשומה אחת פגומה הפילה את רינדור השרת של `/lp`
 * כולו** לפני שאף שער אחר הספיק לפסול אותה. אותו כשל בדיוק תוקן כבר
 * רמה אחת מעל (`tierTable`/`hasSpec` ב-`savings.ts`, ושדות הפרוזה
 * ב-`format.ts`): רשומה פגומה נופלת בשקט, לא לוקחת איתה את הדף.
 *
 * ⚠️ המחרוזת הריקה ולא `String(raw)`: "נפילה חזרה למקור" שלמעלה
 * מניחה שהמקור הוא טקסט שאפשר להציג. ל-`null` אין מקור כזה, וכותרת
 * "null" גרועה מכותרת חסרה. `basePackages` מזהה את זה ומשאירה את
 * הרשומה בלי לדרוס את השדה.
 */
export function displayName(raw: unknown): string {
  if (typeof raw !== "string") return "";
  const cleaned = raw
    .split("[line]")[0]
    .replace(/\*(\d+)\*/g, " ")
    .replace(/\*([^*\s]+)\*/g, " ($1)")
    .replace(/\s+/g, " ")
    .trim();
  return cleaned || raw;
}

/**
 * השם שלוגיקה צריכה לקרוא — הגולמי, לפני ניקוי התצוגה.
 *
 * ⚠️ כל מי שמחפש ראיה בתוך השם — סימון פנימי, מספר קווים,
 * מילה שמעידה על קטגוריה — חייב לעבור דרך כאן ולא לקרוא את
 * `name` ישירות.
 */
export function logicName(p: Package): string {
  return p.rawName ?? p.name;
}

/*
 * ⚠️ רשומה שאינה אובייקט נופלת כאן, לפני שנקרא ממנה שדה אחד.
 *
 * זה אותו שער בדיוק שרשימת הספקים כבר קיבלה (`catalogProviders` מתחת,
 * ושם ההערה מנמקת אותו) — ולא הוחל על **מערך החבילות**, האח שלו. ההפרש
 * בחומרה לרעת זה שנשכח: `catalog.providers` נקרא רק מתוך `providers()`,
 * ואילו `basePackages()` היא **השורה הראשונה של `page.tsx`**. `null`
 * אחד במערך זרק כאן `TypeError` על `.name` (אומת) והפיל את רינדור השרת
 * של `/lp` כולו — לפני הירו, לפני המונים, לפני כל שער אחר. מחלץ שמייצר
 * קובץ JSON הוא בדיוק המקום שבו רשומה חסרה נראית כ-`null` במערך.
 *
 * ⚠️ גם ערך פרימיטיבי (מחרוזת, מספר) ולא רק `null`: הוא אינו זורק מיד,
 * אבל הוא זורם לכל הגזירות שמתחת כרשומה לכל דבר ונופל רק בשער כזה או
 * אחר — ושקט שתלוי במקריות אינו שער. מי שנופל כאן נעלם מ-`PACKAGES`,
 * כלומר גם מההשוואה מול `catalog.counts` בבדיקות: הצהרה של 109 מול
 * מערך של 108 מכשילה בשם במקום לעבור בשתיקה.
 */
function usablePackage(p: unknown): p is Package {
  return p != null && typeof p === "object" && !Array.isArray(p);
}

export function basePackages(): Package[] {
  return catalog.packages.filter(usablePackage).map((p) => {
    // ⚠️ שם שאינו מחרוזת נשאר כמות שהוא, ולא נדרס במחרוזת ריקה:
    // `displayName` מחזירה "" על קלט כזה (ראה ההערה שם), ודריסה הייתה
    // **מוחקת** את הראיה היחידה שהרשומה פגומה. הגזירות שמתחת
    // (`logicName` ואילך) סופרות על `rawName` כעל השם הגולמי, ולכן אין
    // טעם לסמן ניקוי שלא התרחש.
    if (typeof p.name !== "string") return p;
    const name = displayName(p.name);
    return name === p.name ? p : { ...p, name, rawName: p.name };
  });
}

/**
 * `spec` שאפשר לקרוא ממנו שדות, ולא רק משהו שיושב במפתח הזה.
 *
 * ⚠️ תאום של `hasSpec` ב-`savings.ts`, ומאותו טעם המתועד שם: `spec:
 * null` (או שדה חסר) זרק `TypeError` ולקח איתו את רינדור השרת של הדף
 * כולו במקום להפיל רשומה אחת בשקט. שם השער נכתב ל-`isComparable`
 * ולא הוחל על שתי הפונקציות כאן שקוראות מ-`spec` באותו רינדור —
 * `electricityRank` (דרך `byPrice`/`afterPrice`, כלומר כל מיון בעמוד)
 * ו-`serviceCounts` (השורה השנייה של `page.tsx`).
 *
 * ⚠️ מיוצאת כדי ש**גם `config.ts`** יקרא את אותה הגדרה. `crmCategory`
 * קראה `pkg.spec as HomeSpec` — המרה בלבד, בלי שום בדיקה — ואז
 * `spec && !spec.hasInternet`. `spec` פרימיטיבי (מחרוזת, מספר) או מערך
 * הוא טרות'י שאין בו `hasInternet`, ולכן חבילת סיבים כזו קיבלה
 * `"general"` במקום `"internet"` (אומת: `spec: "סיבים"` → `general`,
 * `spec: []` → `general`). זה אותו דפוס שהקובץ הזה מתעד שוב ושוב —
 * שער שחובר למשטח אחד ולא לאחיו — וכאן הוא נכתב **שלוש** פעמים
 * (כאן, `format.ts:153`, `savings.ts:475`) וחסר דווקא ברביעי. `spec`
 * שאינו קריא פירושו "אין מה לקרוא ממנו", כלומר נפילה לברירת המחדל
 * הכתובה ולא להסקה מתוך `undefined`.
 */
export function hasSpec(p: Package): boolean {
  return p.spec != null && typeof p.spec === "object" && !Array.isArray(p.spec);
}

