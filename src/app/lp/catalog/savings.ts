  // אחרי הרווח, ואילו הניסוח הזה נופל בין שתי החלופות. id 53 נפסלת
  // היום דרך "לאחר שנה" שבאותו תיאור וממילא יש לה `priceAfterPromo`,
  // ולכן הבריכה אינה משתנה — אבל רשומה שתכתוב רק את הצורה הזו נכנסה
  // לבריכה כמחיר "לנצח".
  // ⚠️ `(?:מובטח|תקף|קבוע) ל(?:\d+|שנה|שנתיים)` ולא ספרה לבדה. אותה
  // אסימטריה בדיוק שתוקנה כאן פעמיים: `למשך` קיבל את שלוש הצורות
  // (`למשך שנה`, `למשך שנתיים`, `למשך \d+ שנים`) ושלושת אחיו —
  // `מובטח ל`, `תקף ל` ו-`קבוע ל` — נשארו עם הספרה לבדה, בזמן
  // שההערה על `תקף ל 24 חודשים` כבר קבעה שאלה "אותה הצהרה בדיוק
  // כמו `מובטח ל-12 חודשים`". הצורה המילולית חיה בקטלוג: id 91
  // כותבת "תקף לשנה" ומצהירה על אותה עובדה פעמיים, כך שרק
  // ה-"לאחר שנה" השכן תפס אותה. id 91 נושאת `priceAfterPromo` 57.9
  // ולכן השער הזה אינו נקרא עליה בכלל והבריכה אינה משתנה — אבל
  // רשומה שתכתוב "תקף לשנה" ותשאיר את השדה ריק נכנסה לבריכה
  // במחיר ההטבה: ₪21.9 במקום ₪57.9, כלומר כותרת של ₪2,376 בשנה
  // במקום ₪1,945. זה השער לרענון הבא.
  new RegExp(
    String.raw`לאחר מכן[^.•\n]{0,60}\d|חודש(?:ים|יים)\s{0,4}(?:ב[-־]?\s?)?\d[\d,]*\.\d|\d[\d,]*\.\d\d?\s*ל[-־]?\s?\d+\s*חודש|חודש(?:ים|יים)\s{0,4}(?:ב[-־]?\s?)?\d[\d.,]*\s*` +
      SHEKEL +
      // ⚠️ `אחרי` ליד `לאחר`, ו-`שנתיים` ליד `שנה` — אותה הצהרה, נוסח
      // שכן, בדיוק הדפוס שכבר תוקן ב-`REQUIRES_MULTIPLE_LINES`
      // ("ואילך" ליד "ומעלה") וב-`PRICED_BY_LINE_COUNT`. ארבע הצורות
      // חיות בקטלוג: id 42 "אחרי שנתיים 69.9", id 53 "אחרי שנה דמי
      // טיפול", id 61 "פקיעה אחרי שנה וחצי", ו-id 87 נושאת את שגיאת
      // הכתיב החיה "לאחר משנה 69.90" — ולכן `מ?` לפני המילה.
      // אומת: `לאחר שנה` הוחזרה true בזמן ש-`אחרי שנה`,
      // `אחרי שנתיים`, `לאחר שנתיים` ו-`לאחר משנה` כולן false.
      // הכיוון שמרני (מוציא מהבריכה), והבריכה של היום אינה זזה:
      // ids 42/53/61 נפסלות ממילא משער אחר, ול-id 87 יש
      // `priceAfterPromo` ולכן השער אינו נקרא עליה כלל.
      String.raw`|(?:לאחר|אחרי)\s+מ?(?:שנה|שנתיים)(?![א-ת])|(?:לאחר|אחרי)\s+\d+\s+חודשים|` +
      AHKAZ +
      String.raw`|\d[\d.,]*\s*` +
      SHEKEL +
      String.raw`[^.•\n]{0,15}?ל?ב?שנה ה?ר[אוש]{2,3}נה|ל?ב?שנה ה?ר[אוש]{2,3}נה[^.•\n]{0,15}?\d[\d.,]*\s*` +
      SHEKEL +
      String.raw`|אחר כך|ואז \d|מהחודש ה|מחודש ה?[-־]?\s?\d|החודשים הראשונים|חודש(?:ים|יים|ם)? ה?ר[אוש]{2,3}נים|לחודשיים|חודש ראשון|תשלומים ה?ר[אוש]{2,3}נים|שנה ה?שניי?ה|שנה ה?שלישית|שנה ה?רביעית|למשך שנה|למשך שנתיים|למשך \d+ שנים|למשך חודש|למשך \d+ חודשים|למשך \d+ מחזורי|(?:מובטח|תקף|קבוע) ל[-־]?\s?(?:\d+|שנה|שנתיים)|לתקופה של \d+|בתום ה?(תקופה|הטבה|המבצע|השנה)|ב(?:תום|סיום)\s+ה?(?:תקופ[הת]|הטבה|מבצע|שנה)|(?:בתום|בסיום|לאחר|אחרי)\s+תקופת|לאחר תום|מחיר לאחר|מחיר רגיל`,
  );

/**
 * הטקסט שכל שערי הנוסח בקובץ הזה קוראים.
 *
 * ⚠️ פונקציה אחת ולא תבנית שמועתקת חמש פעמים: ההיסטוריה של הקובץ היא
 * שבכל פעם שנוסף שדה מישהו שכח אחד מהקוראים — `logicName` נוסף
 * לשלושה מסננים ולא לכולם, ו-`benefits` נשכח ב-`familyPriceOnly`
 * ("זו הייתה השמטה ולא החלטה").
 *
 * ⚠️ `priceAfterPromoNote` הוא השדה **הרביעי**, והוא נשכח בכל חמשת
 * השערים — דווקא השדה שקיים כדי להחזיק את המשפט של המפעיל על מה
 * שקורה כשההטבה נגמרת. עבור `declaresRiseInText` החור רדום (חבילה עם
 * הערה ובלי מספר נפסלת ממילא ב-`hasKnownAfterPrice`), אבל
 * `priceAfterPromoCorrected` בטיפוס מתעד בדיוק את התצורה שמחיה אותו:
 * מספר שהוזן **ידנית** לצד ההערה המקורית. id 109 הוא המקרה — ההערה
 * שלו היא "לאחר שנה 159 ₪ לחודש + 34.9 ₪ נתב", כלומר חיוב נתב חודשי
 * נפרד שהצהיר על עצמו בשדה שאף שער לא קרא.
 */
function gateText(p: Package): string {
  return `${logicName(p)} ${p.description ?? ""} ${p.benefits ?? ""} ${p.priceAfterPromoNote ?? ""}`;
}

/**
 * שם שאפשר לקרוא ממנו — ולא רק שדה שיושב במפתח `name`.
 *
 * ⚠️ שני דברים נשברים יחד על רשומה שהשם שלה אינו מחרוזת, ואף שער
 * בקובץ הזה לא בדק את זה:
 *
 *  1. **כל חמשת שערי הנוסח מתעוורים.** ההערה שמעל `declaresRiseInText`
 *     מתעדת במפורש שחמש חבילות בקטלוג חסרות `description` **ו**`benefits`
 *     גם יחד, ולכן השם הוא "הראיה היחידה שקיימת". רשומה שבה
 *     `"name": null` מזרימה ל-`gateText` את המחרוזת `"null"` — אפס טקסט
 *     שימושי — ולכן `declaresRiseInText` / `requiresMultipleLines` /
 *     `familyPriceOnly` / `afterPriceDependsOnLines` / `addonFreeThenPaid`
 *     כולם מחזירים `false` עליה **בלי לבדוק דבר**, בעוד היא ממשיכה
 *     להתחרות על ה-argmin. זה בדיוק ההיפוך של הכיוון השמרני שכל השערים
 *     האלה נבנו כדי לשמור עליו.
 *  2. **הנציג לא יכול לשחזר את המספר.** ההערה ב-`SavingsCalculator`
 *     מנמקת את עמודת `packageName` ואת שורת "מול <ספק> — <שם>" בכך
 *     שבלעדיהן הנציג מחזיק "חיסכון ₪1,020 בשנה" בלי שום דרך לדעת מולי
 *     מה נמדד. `${null}` כותב לשתיהן את המילה `null` — כלומר בדיוק
 *     אותו מספר שאי אפשר לעמוד מאחוריו, רק עם מראה של נתון.
 *
 * `basePackages` מתעדת שהיא **משאירה** שם כזה כמות שהוא במכוון ("דריסה
 * הייתה מוחקת את הראיה היחידה שהרשומה פגומה"), ולכן הגידור הוא כאן.
 * הקטלוג של היום נקי (אפס רשומות כאלה), והכיוון שמרני — בריכה קטנה
 * יותר — בדיוק כמו `hasSpec` ו-`typeText`.
 */
function hasReadableName(p: Package): boolean {
  const name = logicName(p);
  return typeof name === "string" && name.trim() !== "";
}

// ⚠️ גם `logicName` — כמו ב-`requiresMultipleLines` ו-`familyPriceOnly`.
// חמש חבילות בקטלוג חסרות `description` **ו**`benefits` גם יחד, ולכן
// שלושת המסננים האלה היו עבורן ריקים מראש. שם שנושא מחיר
// מבצע הוא דפוס קיים בקטלוג הזה, ולכן החור נסגר לפני הרענון הבא.
export function declaresRiseInText(p: Package): boolean {
  return RISE_IN_TEXT.test(gateText(p));
}

/**
 * חבילה שהמחיר שלה מותנה בכמות קווים שהמבקר לא בהכרח קונה.
 *
 * ⚠️ המשך ישיר של `price > 0`: אותו דפוס בדיוק, רק שהפעם המחיר נרשם
 * כמספר אמיתי במקום 0, ולכן חמק. גולן "4 ב 130 *2*" רשומה 32 ₪ — וזה
 * המחיר **לקו השני בחבילה של ארבעה** ("עלות החבילה לכל קו שני
 * ₪32.00"), לא מחיר של קו בודד. HOT "TOTAL 5G 300GB" פותחת ב-"*לרוכשים
 * 2 מנויים ויותר*", כלומר מינימום חוזי.
 *
 * היום אף אחת מהן אינה נבחרת (WeCom ב-29.9 ₪ מנצחת בכל כמות), ולכן זו
 * הגנה על **הרענון הבא** ולא תיקון של מספר שמוצג כרגע: ברגע שהזולה
 * ביותר תצא מהקטלוג, "32 ₪ לקו שני בחבילת ארבעה" הופך לכותרת של מי
 * שביקש קו אחד.
 *
 * ⚠️ נבדק גם מול `name`, ולא רק מול הטקסט: ל-"4 ב 130 *2*" אין
 * `description` כלל, והשם הוא הראיה היחידה שקיימת.
 */
const REQUIRES_MULTIPLE_LINES =
  // ⚠️ `ב[-־ ]?` ולא `ב\s?`: "3 קווים ב-99" עם מקף הוא אותו תמחור בדיוק
  // כמו "3 קווים ב99", והגרסה הקודמת תפסה רק את השנייה.
  // ⚠️ ושתי היחידות בכל חלופה. הרגקס היה אסימטרי בתוך עצמו:
  // "לרוכשים" הכיר רק מנויים, "קו שני" רק קו, והחלופה
  // האחרונה רק קווים — בזמן שהקטלוג מנסח את אותה הצהרה
  // בשתי היחידות. אומת: "לרוכשים 2 קווים", "3 מנויים ב 99"
  // ו-"מנוי שני" הוחזרו false בזמן ששלושת המראות הוחזרו true.
  /לרוכשים \d+ (?:מנויים|קווים)|(?:קו|מנוי) שני|\*\s?[2-9]\s?\*|\d+\s?(?:קווים|מנויים) ב[-־\s]?\s?\d/;

/**
 * מחירון מדורג שבו **המחיר שבמפרט** הוא המדרגה של כמה קווים.
 *
 * ⚠️ id 68 ("קיץ חם בדור 5", price 39.9) מוכרת "* קו בודד – 49.90 ₪
 * * 2 קווים – 44.90 ₪ לקו * 3 קווים ומעלה – **39.90 ₪** לקו", כלומר
 * ה-39.90 שבמפרט הוא המחיר לשלושה קווים ומעלה — ובאותו תיאור גם
 * "המחיר קבוע – לכל החיים!". הרגקס שלמעלה דורש "ב" לפני המספר
 * ("3 קווים ב99") ואינו תופס תבליט כוכבית, ולכן היא נשארה בבריכה.
 *
 * ⚠️ נדרשת התאמה **לאותו מספר** ולא עצם קיום מחירון מדורג, מאותו טעם
 * שמתועד על `proseFloorsAt`: כך השער פוסל רק כשהכותרת עצמה היא מדרגת
 * הקווים. id 129 אומרת "קו ראשון 39, בצירוף 2 קווים ומעלה 35 לקו"
 * ו-`price` שלה 39 — המחיר של קו בודד, ולכן היא **נשארת** בבריכה
 * בצדק; גרסה שתפסה את התבנית בלי המספר הוציאה אותה משם.
 *
 * היום WeCom ב-34 ₪ מנצחת את id 68 בכל כמות, ולכן זו הגנה על הרענון
 * הבא ולא תיקון של מספר שמוצג כרגע.
 *
 * ⚠️ `(?:[2-9]|\d{2,})` ולא `[2-9]` לבדו: מדרגה דו-ספרתית ("10 קווים
 * ומעלה – 29.90 ₪ לקו") היא אותה הצהרה בדיוק, והספרה הבודדת השאירה
 * אותה בבריכה כמחיר של **קו אחד**. המספר נשאר חסום מלמטה ב-2 ולא
 * הורחב ל-`\d+`, כי `1 קווים <price>` פירושו שהכותרת היא דווקא מחיר
 * הקו הבודד — בדיוק הכרעת id 129, שחייבת להישאר בבריכה.
 */
function headlineIsLineTierPrice(p: Package): boolean {
  /*
   * ⚠️ המספר שהשער משווה אליו הוא המחיר ש**מתפרסם**, ולא `price`
   * לבדו. השאלה שהשער שואל היא "האם המספר שבכותרת הוא מדרגת קווים",
   * והמספר שבכותרת הוא מה ש-`afterPrice`/`perLinePrice` מפרסמות —
   * כלומר `priceAfterPromo` כשהוא קיים. אותה רשומה בדיוק, עם 29.9
   * ב-`price`, נפסלה; עם 29.9 ב-`priceAfterPromo` עברה, נבחרה,
   * ועל פרוזה שאומרת "* קו בודד – 49.90 ₪ * 3 קווים – 29.90 ₪ לקו"
   * הכותרת יצאה ₪2,280 בשנה במקום ₪2,040 — ניפוח של 11.8% על אותה
   * הצהרה שהגרסה האחרת פוסלת. זו אי-עקביות **פנימית**: השער קרא שדה
   * אחד והמנוע פרסם שדה אחר.
   *
   * ⚠️ שני המחירים נבדקים ולא רק המתפרסם: `priceAfterPromo` יכול
   * להיות מדרגת הכמות בעוד `price` הוא מחיר הקו הבודד, ולהיפך.
   */
  const headline = new Set<number>();
  for (const value of [p.price, afterPrice(p)]) {
    if (typeof value === "number" && Number.isFinite(value)) headline.add(value);
  }
  if (headline.size === 0) return false;
  for (const m of gateText(p).matchAll(
    // ⚠️ "ואילך" ו-"מנויים", מאותה סיבה שהרשימה מונה גם
    // "ויותר" ליד "ומעלה": אותה הצהרה, נוסח שכן. id 42 כותבת
    // "לרוכשים 3 מנויים ואילך" בזמן ש-ids 36/37 כותבות "3 מנויים
    // ומעלה" ו-id 68 "3 קווים ומעלה" — ושתי האחרונות נתפסו.
    /(?:[2-9]|\d{2,})\s?(?:קווים|מנויים)\s*(?:ומעלה|ויותר|ואילך)?\s*(?:[–־-]|ב[-־\s]?)?\s*(\d[\d,]*(?:\.\d+)?)/g,
  )) {
    if (headline.has(Number(String(m[1]).replace(/,/g, "")))) return true;
  }
  return false;
}

export function requiresMultipleLines(p: Package): boolean {
  return REQUIRES_MULTIPLE_LINES.test(gateText(p)) || headlineIsLineTierPrice(p);
}

/**
 * חבילה שהמחיר שלה הוא מחיר **למנוי במסלול משפחתי** — כלומר משני
 * קווים ומעלה — בלי שהקטלוג אומר זאת במספרים.
 *
 * ⚠️ WeCom מוכרת את אותה חבילה בדיוק פעמיים: "wecomFree 4G" ב-34.9 ₪
 * ו-"wecomFamily 4G (מסלול משפחתי)" ב-29.9 ₪. אותם 10,000GB, אותן
 * 5,000 דקות, אותו eSIM; ההבדל היחיד הוא המילה "משפחתי" — ובמחירון
 * של WeCom "משפחתי" פירושו מנוי מ-2 מנויים. `lineTiers` ריק ואין
 * `priceAfterPromo`, ולכן שום מסנן לא תפס את זה, ומי שביקש **קו אחד**
 * קיבל כותרת שנבנתה על 29.9 במקום 34.9 — ₪60 בשנה שלא יראה.
 *
 * זו לא פסילה גורפת כמו `requiresMultipleLines`: לשני קווים ומעלה
 * המחיר המשפחתי הוא בדיוק המחיר שיגבו, ולכן הבדיקה תלוית-כמות ויושבת
 * ב-`computeSaving` לצד `priceUnknownAtLines`.
 */
// ⚠️ גם `family` באנגלית. הרשומה שבשבילה המסנן נכתב שמה
// `wecomFamily 4G` — באנגלית. מה שתפס אותה בפועל היה רק הסוגריים
// שבתיאור; אותה רשומה בלי הסוגריים — או אחות שלה בלי תיאור
// כלל — חוזרת לבריכת הקו הבודד ב-29.9 במקום 34.9, כלומר בדיוק
// ה-₪60 לשנה שההערה למעלה מתארת כתקלה שתוקנה.
const FAMILY_ONLY = /מסלול משפחתי|משפחתי|family/i;

// ⚠️ גם `benefits`, כמו בשלושת המסננים האחרים. זו הייתה השמטה
// ולא החלטה: ההערה שלמעלה מתארת את שלושתם כקבוצה אחת,
// ו-`declaresRiseInText` / `requiresMultipleLines` / `afterPriceDependsOnLines`
// כולם קוראים את שלושת השדות. רשומה שבה "(מסלול משפחתי)"
