import { afterPrice, hasKnownAfterPrice } from "./catalog";
import type { CellularSpec, HomeSpec, MonthlyPackage, Package } from "./types";

/**
 * ── הלוגיקה של מחשבון החיסכון ───────────────────────────────────────────
 *
 * ⚠️ חיה כאן ולא בתוך הקומפוננטה כדי שאפשר יהיה **להריץ אותה מול
 * הקטלוג האמיתי** ב-`tools/savings.test.mjs`. הכותרת שהמחשבון מפיק
 * ("אפשר לחסוך עד ₪1,560 בשנה") היא הבטחה מספרית שדף השוואת מחירים
 * נותן לגולש, והדרך היחידה לשמור עליה כשהקטלוג מתרענן היא בדיקה
 * שרצה על 109 החבילות ולא עין אנושית על דיף.
 */

export type Track = "cellular" | "home";

/** התקרה שהמחשבון מוכן להתייחס אליה כחשבון חודשי אמיתי. */
export const MAX_SPEND = 5000;

/**
 * עלייה במחיר שהוצהרה **בטקסט השיווקי בלבד**.
 *
 * ⚠️ זה החור שנשאר אחרי `hasKnownAfterPrice`. אותה פונקציה פוסלת רק
 * חבילה שמילאה `priceAfterPromoNote` והשאירה את המספר ריק — 11
 * חבילות. אבל 56 מתוך 90 החבילות החודשיות משאירות את **שני** השדות
 * ריקים, והמחשבון התייחס אליהן כאילו המחיר שלהן קבוע לנצח רק מפני
 * שאיש לא מילא שדה. זה תגמל בדיוק את מי שקבר את העלייה עמוק יותר:
 *
 *  • Partner Golden 5G — 39.9 ₪, שני השדות ריקים, ובתיאור:
 *    "מחיר התכנית מהחודש ה-13 והלאה- 59.9 ₪". עלייה של 50%.
 *  • גולן "חודשיים ראשונים 24.90" — 34.9 ₪, "מחיר מובטח ל-12 חודשים".
 *  • HOT "סיב 1G ב109" — "מחודש 4".
 *
 * לכן הטקסט **פוסל** את החבילה, ולא מנסה לגזור ממנו מחיר. פירסור
 * הנוסח החופשי הוא בדיוק הניחוש שהמחשבון נבנה כדי למנוע (יש בו
 * "+ 10 ₪ נתב" שצריך חיבור ו-"מ-100 ₪" שהוא רצפה); "לא יודעים —
 * לא מבטיחים" הוא התשובה היחידה שאפשר לעמוד מאחוריה.
 */
const RISE_IN_TEXT =
  /לאחר מכן|מהחודש ה|מחודש \d|החודשים הראשונים|חודשים ראשונים|למשך שנה|מובטח ל[-־]?\s?\d+|לתקופה של \d+|בתום ה?(תקופה|הטבה|המבצע)|לאחר תום|מחיר לאחר|מחיר רגיל/;

export function declaresRiseInText(p: Package): boolean {
  return RISE_IN_TEXT.test(`${p.description ?? ""} ${p.benefits ?? ""}`);
}

/**
 * חבילה שהמחיר שלה מותנה בכמות קווים שהמבקר לא בהכרח קונה.
 *
 * ⚠️ המשך ישיר של `price > 0`: אותו דפוס בדיוק, רק שהפעם המחיר נרשם
 * כמספר אמיתי במקום 0, ולכן חמק. גולן "4 ב 130 *2*" רשומה 32 ₪ — וזה
 * המחיר **לקו השני בחבילה של ארבעה** ("עלות החבילה לכל קו שני
 * ₪32.00"), לא מחיר של קו בודד. HOT "TOTAL 5G 300GB" פותחת ב-"*לרוכשים
 * 2 מנויים ויותר*", כלומר מינימום חוזי.
 *
 * היום אף אחת מהן אינה נבחרת (WeCom ב-29.9 ₪ מנצחת בכל כמות), ולכן זו
 * הגנה על **הרענון הבא** ולא תיקון של מספר שמוצג כרגע: ברגע שהזולה
 * ביותר תצא מהקטלוג, "32 ₪ לקו שני בחבילת ארבעה" הופך לכותרת של מי
 * שביקש קו אחד.
 *
 * ⚠️ נבדק גם מול `name`, ולא רק מול הטקסט: ל-"4 ב 130 *2*" אין
 * `description` כלל, והשם הוא הראיה היחידה שקיימת.
 */
const REQUIRES_MULTIPLE_LINES =
  /לרוכשים \d+ מנויים|קו שני|\*\s?[2-9]\s?\*|\d+\s?קווים ב\s?\d/;

export function requiresMultipleLines(p: Package): boolean {
  return REQUIRES_MULTIPLE_LINES.test(`${p.name} ${p.description ?? ""} ${p.benefits ?? ""}`);
}

/**
 * חבילה שהמבקר במסלול הזה באמת יכול לעבור אליה.
 *
 * ⚠️ הפילטר הזה הוא מה שמפריד בין "עד כמה אפשר לחסוך" לבין מספר
 * מומצא. בלעדיו הזולה ביותר ב-`home` היא **קו טלפון של בזק ל-50 דקות**
 * (19.9 ₪) — כלומר מי שמשלם 220 ₪ על טריפל קיבל כותרת של ₪2,401
 * חיסכון מול מוצר שאינו אינטרנט ואינו טלוויזיה. באותו אופן 6 מתוך 8
 * החבילות הזולות בסלולר הן כשר או DATA ONLY, שאינן תחליף לקו רגיל.
 *
 * `price > 0` נבדק כאן ולא נשען על `listable()` של הקורא: בקטלוג יש
 * חבילות שמתומחרות לחבילה שלמה (`3 קווים ב99`) ורשומות כ-0, ומחיר 0
 * מייצר "חיסכון" של מלוא החשבון.
 */
export function isComparable(p: Package, track: Track): p is MonthlyPackage {
  if (p.category !== track || p.priceModel !== "monthly") return false;
  if (p.price == null || p.price <= 0) return false;
  if (p.editorial?.hidden) return false;
  // ⚠️ חבילה שהעלייה שלה מוצהרת בטקסט חופשי בלבד אינה בת-השוואה כאן:
  // המחיר היחיד שאפשר לחשב ממנה הוא מחיר ההטבה, והכותרת מבטיחה את
  // ההפך. ראה `hasKnownAfterPrice` ו-`declaresRiseInText`.
  if (!hasKnownAfterPrice(p)) return false;
  if (p.priceAfterPromo == null && declaresRiseInText(p)) return false;
  // ⚠️ מחיר שמותנה בכמות קווים אינו מחיר שהמבקר הזה יקבל. ראה
  // `requiresMultipleLines`.
  if (requiresMultipleLines(p)) return false;

  if (track === "cellular") {
    const spec = p.spec as CellularSpec;
    return !spec.kosher && (spec.unlimitedData || (spec.dataGb ?? 0) > 0) && (spec.minutes ?? 0) >= 1000;
  }
  /*
   * ⚠️ **גם אינטרנט וגם טלוויזיה**, ולא `hasInternet` לבדו.
   *
   * המסלול מציג את עצמו כ"אינטרנט וטלוויזיה" והמבקר מזין את החשבון
   * החודשי **הכולל** שלו. מתוך 25 חבילות הבית שעברו את הפילטר 13 הן
   * אינטרנט בלבד — כלומר מי שמשלם 220 ₪ על טריפל קיבל כותרת חיסכון
   * מול חבילה שאין בה טלוויזיה, והפער הזה הוא לא הנחה אלא שירות
   * שנעלם. התנאי הקודם חסם בדיוק את הכיוון ההפוך (TV בלבד) והשאיר
   * את זה פתוח.
   *
   * קו הטלפון עדיין אינו נדרש — הוא מוזכר בהסתייגות שמתחת למספר.
   *
   * ⚠️ `type !== "TV"` הוא **תיקון לנתון שגוי במקור**, לא הידור נוסף.
   * סטינג "החבילה המושלמת" רשומה `hasInternet: true` למרות שהיא שירות
   * סטרימינג בלבד ("שירות טלוויזיה הפועל על גבי האינטרנט") — המחלץ
   * קרא את המילה "אינטרנט" בתיאור. היא הזולה בקטגוריה, כלומר בלי
   * השורה הזו היא הופכת לחבילה שמולה נמדד כל חשבון טריפל בארץ.
   */
  const spec = p.spec as HomeSpec;
  return spec.hasInternet && spec.hasTv && p.type !== "TV";
}

/**
 * המחיר לקו **שנשאר אחרי שההטבה נגמרת**.
 *
 * ⚠️ זה הלב של התיקון. `price` לבדו הוא מחיר ההטבה: HOT Synergy עולה
 * 21.9 ₪ והופך ל-57.9 ₪ בתום שנה — פי 2.64. כותרת שנתית שנבנתה על
 * 21.9 מנפחת את החיסכון פי 3.3, וגרוע מכך היא סותרת את ההבטחה של
 * הדף עצמו ("כולל המחיר אחרי תום ההטבה"). `afterPrice` כבר מחזירה את
 * המחיר הקבוע, וזה המספר היחיד שאפשר לעמוד מאחוריו לשנה שלמה.
 *
 * מדרגות הקווים מתומחרות על בסיס ההטבה, ולכן הן נלקחות בחשבון רק
 * כשהחבילה לא הצהירה על עלייה — אחרת היינו מערבבים מחיר מבצע לקו עם
 * מחיר קבוע ומקבלים סכום שאינו נכון באף נקודת זמן. (סלקום "משפחתי
 * פלוס" היא המקרה: 39.9 היום, 59.9 אחר כך, ומדרגות שמתומחרות מול
 * 39.9. 59.9 לכל כמות הוא המספר השמרני, ולכן הנבחר.)
 */
export function perLinePrice(p: MonthlyPackage, lines: number): number {
  const base = afterPrice(p);
  if (p.priceAfterPromo != null) return base;
  const tiers = (p.spec as CellularSpec).lineTiers;
  if (!tiers?.length) return base;
  const tier = tiers.filter((t) => t.lines <= lines).sort((a, b) => b.lines - a.lines)[0];
  /*
   * ⚠️ `tier.price` כפי שהוא, ובלי `Math.min` מול המחיר הבסיסי.
   *
   * מדרגה היא המחיר שהמפעיל גובה בכמות הזו — לפעמים **גבוה** מהמחיר
   * המוצג. גולן "קיץ חם בדור 5" מוצגת ב-39.9 אבל דורשת 44.9 ₪ לקו
   * בשני קווים; `Math.min` החזיר 39.9 והציג לזוג חיסכון גדול ב-₪120
   * בשנה ממה שיקבלו בפועל.
   */
  return tier ? tier.price : base;
}

export interface Saving {
  /** החבילה שנבחרה, או `null` כשאין בקטגוריה חבילה בת-השוואה. */
  pick: MonthlyPackage | null;
  monthly: number;
  yearly: number;
  /** יש חבילה, והיא באמת זולה מהחשבון הנוכחי. */
  worthwhile: boolean;
}

/**
 * ⚠️ מעוגל פעם אחת, והשנה נגזרת ממנו.
 *
 * חבילה במחיר 29.9 ₪ כפול שלושה קווים מייצרת "חיסכון של ₪1,563.6
 * בשנה" — והאגורות האלה הן בדיוק מה שגורם למספר להיראות מומצא.
 * חשוב מזה: עיגול נפרד לחודש ולשנה הציג שני מספרים שסותרים זה את זה
 * על אותו מסך (₪154 בחודש לצד ₪1,852 בשנה, כשהמכפלה היא 1,848).
 * לכן מעגלים את החודש ומכפילים — שתי השורות תמיד מסתדרות.
 */
export function computeSaving(
  packages: Package[],
  track: Track,
  units: number,
  monthlySpend: number,
): Saving {
  const pool = packages.filter((p): p is MonthlyPackage => isComparable(p, track));
  const pick = pool.reduce<MonthlyPackage | null>(
    (best, p) => (best == null || perLinePrice(p, units) < perLinePrice(best, units) ? p : best),
    null,
  );
  if (!pick) return { pick: null, monthly: 0, yearly: 0, worthwhile: false };

  // Cellular is priced per line; a home package is one household bill.
  const perLine = perLinePrice(pick, units);
  const newMonthly = track === "cellular" ? perLine * units : perLine;
  const monthly = Math.round(monthlySpend - newMonthly);
  return { pick, monthly, yearly: monthly * 12, worthwhile: monthlySpend > 0 && monthly > 0 };
}

/**
 * קריאת הסכום שהמבקר הקליד.
 *
 * ⚠️ `\d` בלי הדגל `u` לא תופס ספרות ערביות-הודיות, ומקלדת ערבית בנייד
 * הייתה מרוקנת את המחרוזת ומשאירה את הכפתור מושבת בלי הסבר. לכן
 * הספרות מנורמלות ל-ASCII לפני הניקוי.
 */
export function parseSpend(raw: string): number {
  const ascii = raw.replace(/[٠-٩۰-۹]/g, (d) =>
    String((d.codePointAt(0)! - 0x0660) % 16),
  );
  /*
   * ⚠️ תווי זבל **פוסלים** את הקלט, לא מסוננים ממנו.
   *
   * הסינון השקט של `[^\d.]` הפך `-500` ל-500 ו-`abc220` ל-220: המסך
   * הצהיר "אתם משלמים ₪500 בחודש" על סכום שלילי, והנציג קיבל בהערה
   * סכום שהלקוח מעולם לא הקליד. מותרים רק מפרידי אלפים ורווחים, שהם
   * דרך לגיטימית לכתוב מספר; כל השאר מחזיר 0, מה שמשבית את הכפתור
   * ומציג את ההסבר שליד השדה.
   */
  if (/[^\d.,\s₪]/.test(ascii)) return 0;
  const cleaned = ascii.replace(/[^\d.]/g, "");
  /*
   * ⚠️ יותר מנקודה עשרונית אחת פוסלת את הקלט.
   *
   * הניסיון הקודם "להציל" את הקלט חיבר את החלקים — `1.2.3` הפך ל-1.23
   * **בשקט**: הכפתור נדלק, המסך הראה תוצאה, והנציג קיבל "משלם היום
   * ₪1.23 בחודש". קלט שאינו מספר צריך להיראות כך, לא להפוך למספר אחר.
   */
  if ((cleaned.match(/\./g)?.length ?? 0) > 1) return 0;
  /*
   * ⚠️ אותו כלל בדיוק חל על הפסיק — והוא **נשכח**.
   *
   * השומר למעלה נכתב לנקודה בלבד, ולכן `220,5` (הרגל אירופאי לכתוב
   * 220.5) עבר את הסינון והפך בשקט ל-**2205**: המסך הצהיר "אתם משלמים
   * ₪2,205 בחודש", הכותרת קפצה ל-₪26,100 בשנה, והנציג קיבל בהערה סכום
   * שהלקוח מעולם לא הזין. `2,20` — טעות הקלדה של קו אחד — הפך ל-220.
   *
   * פסיק לגיטימי רק כמפריד אלפים, כלומר בדיוק שלוש ספרות אחריו ולפני
   * הנקודה העשרונית. `1,200` ו-`5,000` ממשיכים לעבוד; כל השאר מחזיר 0
   * ומדליק את ההסבר שליד השדה, כמו כל קלט לא-חוקי אחר.
   */
  if (ascii.includes(",") && !/^\s*₪?\s*\d{1,3}(,\d{3})+(\.\d+)?\s*₪?\s*$/.test(ascii)) return 0;
  const value = Number(cleaned);
  if (!Number.isFinite(value) || value <= 0) return 0;
  return Math.min(value, MAX_SPEND);
}
