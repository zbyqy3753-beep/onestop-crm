/**
 * חבילה שהמבקר במסלול הזה באמת יכול לעבור אליה.
 *
 * ⚠️ הפילטר הזה הוא מה שמפריד בין "עד כמה אפשר לחסוך" לבין מספר
 * מומצא. בלעדיו הזולה ביותר ב-`home` היא **קו טלפון של בזק ל-50 דקות**
 * (19.9 ₪) — כלומר מי שמשלם 220 ₪ על טריפל קיבל כותרת של ₪2,401
 * חיסכון מול מוצר שאינו אינטרנט ואינו טלוויזיה. באותו אופן 6 מתוך 8
 * החבילות הזולות בסלולר הן כשר או DATA ONLY, שאינן תחליף לקו רגיל.
 *
 * `price > 0` נבדק כאן ולא נשען על `listable()` של הקורא: בקטלוג יש
 * חבילות שמתומחרות לחבילה שלמה (`3 קווים ב99`) ורשומות כ-0, ומחיר 0
 * מייצר "חיסכון" של מלוא החשבון.
 */
/** מספר שאפשר להציג כמחיר — ולא מחרוזת שנראית כמו אחד. */
function isMoney(value: unknown): value is number {
  return typeof value === "number" && Number.isFinite(value) && value > 0;
}

/**
 * טבלת מדרגות שאפשר **לעבור עליה**, ולא רק משהו שיש לו `length`.
 *
 * ⚠️ שלושת הקוראים של `lineTiers` בדקו `tiers?.length` ומיד אחר כך
 * קראו ל-`every` / `some` / `filter`. `length` הוא אמת גם על מחרוזת
 * וגם על `{ length: 2 }`, והקטלוג נכנס דרך `as unknown as Catalog`
 * בלי ולידציה — כלומר רענון שיכתוב `"lineTiers": "2"` (או שיישאב את
 * השדה כמחרוזת JSON, כפי שקרה ל-`price`) מפיל את **רינדור השרת** של
 * הדף כולו ב-`TypeError: tiers.every is not a function`, ולא מפיל
 * חבילה אחת בשקט כמו שכל שאר השערים בקובץ הזה עושים.
 *
 * `Array.isArray` ולא `typeof === "object"`: `Set` ו-`Map` גם הם
 * אובייקטים עם `size`, ואין להם `every`.
 *
 * ⚠️ `spec?.lineTiers` ולא `spec.lineTiers` — השער שנכתב כאן נגד
 * `TypeError` ברינדור השרת נפל בעצמו רמה אחת מעל: רשומה שבה
 * `"spec": null` (או שהשדה חסר לגמרי, שתי צורות שהקטלוג נכנס איתן
 * דרך `as unknown as Catalog` בלי ולידציה) הפילה
 * `Cannot read properties of null (reading 'lineTiers')` בתוך
 * `isComparable`, כלומר בתוך רינדור השרת של `/lp` כולו. `spec: "x"`
 * דווקא נפל בשקט — ההוכחה שהיה כאן מצב אחד חסר ולא החלטה.
 */
function tierTable(
  spec: Partial<CellularSpec> | null | undefined,
): { lines: number; price: number }[] | null {
  const tiers = spec?.lineTiers;
  return Array.isArray(tiers) && tiers.length > 0 ? tiers : null;
}

/** `spec` שאפשר לקרוא ממנו שדות, ולא רק משהו שיושב במפתח הזה. */
function hasSpec(p: Package): boolean {
  return p.spec != null && typeof p.spec === "object" && !Array.isArray(p.spec);
}

export function isComparable(p: Package, track: Track): p is MonthlyPackage {
  if (p.category !== track || p.priceModel !== "monthly") return false;
  // ⚠️ `typeof` ולא `== null` — ראה `isListable`: הקטלוג נכנס דרך cast
  // בלי ולידציה, ומחיר שיישאב פעם אחת כמחרוזת עובר כל השוואה מספרית
  // ב-JS ומגיע לכותרת כ-NaN.
  if (typeof p.price !== "number" || !Number.isFinite(p.price) || p.price <= 0) return false;
  /*
    ⚠️ אותה בדיקה גם על המחירים האחרים שהכותרת נבנית
    עליהם. השער שמעל בדק רק את `price`, בעוד ש-`perLinePrice`
    מחזירה בפועל את `priceAfterPromo` או מחיר מדרגה — שניהם עברו
    בלי שום ולידציה. `"19"` כמחרוזת היה מנצח את הבחירה
    ומייצר כותרת ממחרוזת, ו-`"69 ₪"` מפיל את שלב 3 עם
    `value.toFixed is not a function`. הקטלוג היום נקי — זה השער
    לרענון הבא.
  */
  if (p.priceAfterPromo != null && !isMoney(p.priceAfterPromo)) return false;
  /*
    ⚠️ `spec` עצמו, לפני כל קריאה ממנו. כל השערים שמתחת — המדרגות,
    הסלולר (`kosher` / `dataGb` / `minutes`) והבית (`hasInternet` /
    `hasTv`) — קוראים שדות מתוכו, ו-`spec: null` (או שדה חסר) הפיל
    `TypeError` ולקח איתו את רינדור השרת של הדף כולו במקום להפיל
    רשומה אחת בשקט. ראה `tierTable` ו-`hasSpec`. `{}` נפסל כאן גם
    כן, אבל רק בגלל השערים שמתחת — אין בו לא מהירות ולא גלישה.
  */
  if (!hasSpec(p)) return false;
  // ⚠️ `lineTiers` שאינו מערך הוא רשומה פגומה ולא "בלי מדרגות": ראה
  // `tierTable`. שדה כזה נפל כאן ב-`TypeError` והפיל את רינדור השרת של
  // כל הדף, במקום להפיל חבילה אחת בשקט כמו כל שער אחר בקובץ הזה.
  const rawTiers = (p.spec as Partial<CellularSpec>).lineTiers;
  if (rawTiers != null && !Array.isArray(rawTiers)) return false;
  const tiers = tierTable(p.spec as Partial<CellularSpec>);
  // ⚠️ גם `t.lines >= 1`. מדרגה עם `lines: 0` (או שלילי) עברה כ-
  // `Number.isInteger`, ואז `priceUnknownAtLines` רואה `t.lines <= lines` כ-true
  // ומוותרת על הבדיקה, ו-`perLinePrice` עלולה לבחור אותה. הקטלוג נקי
  // היום — זה השער לרענון הבא, בדיוק כמו השערים שמעליו.
  //
  // ⚠️ `t != null` לפני `t.price`: מדרגה שהיא `null` בתוך מערך תקין
  // הפילה את אותו `TypeError` ברמה אחת פנימה.
  if (tiers && !tiers.every((t) => t != null && isMoney(t.price) && Number.isInteger(t.lines) && t.lines >= 1)) {
    return false;
  }
  if (p.editorial?.hidden) return false;
  // ⚠️ חבילה שהעלייה שלה מוצהרת בטקסט חופשי בלבד אינה בת-השוואה כאן:
  // המחיר היחיד שאפשר לחשב ממנה הוא מחיר ההטבה, והכותרת מבטיחה את
  // ההפך. ראה `hasKnownAfterPrice` ו-`declaresRiseInText`.
  if (!hasKnownAfterPrice(p)) return false;
  if (p.priceAfterPromo == null && declaresRiseInText(p)) return false;
  // ⚠️ מחיר שמותנה בכמות קווים אינו מחיר שהמבקר הזה יקבל. ראה
  // `requiresMultipleLines`.
  if (requiresMultipleLines(p)) return false;
  // ⚠️ מחיר-אחרי-הטבה אחד לחבילה שמצהירה על מחיר לפי כמות. ראה
  // `afterPriceDependsOnLines`.
  if (afterPriceDependsOnLines(p)) return false;
  // ⚠️ תוכן (או שירות) שנכנס בחינם ומתחיל להיות מחויב הוא חיוב חודשי שמחיר-אחרי-
  // ההטבה לא מכיל. ראה `addonFreeThenPaid`.
  if (addonFreeThenPaid(p)) return false;

  if (track === "cellular") {
    const spec = p.spec as CellularSpec;
    /*
     * ⚠️ `=== false` ולא `!spec.kosher`, ו-`type` כסימן שני — בדיוק
     * אותם שני תיקונים שענף הבית שמתחת כבר קיבל (`hasInternet === true`
     * ו-`p.type !== "TV"`), ושלא הוחלו על אחיו.
     *
     * `!spec.kosher` קורא **היעדר הצהרה** כ"לא כשר": `kosher: null` —
     * הצורה שהמחלץ מייצר לשדה שלא קרא, וקיימת בפועל בקטלוג הזה
     * (`dataGb: null` בשמונה רשומות) — עבר את השער כקו רגיל. זה בדיוק
     * הכיוון שההערה שמעל הפונקציה מזהירה ממנו: שמונה רשומות הכשר
     * נושאות את המחירים הזולים בקטגוריה (₪25–₪39 מול ₪34 של הזולה
     * בבריכה), ולכן רשומת כשר שדגל הכשרות שלה לא נקרא הופכת מיד
     * לחבילה שמולה נמדד כל חשבון סלולר — חיסכון שמוצג מול מוצר שאינו
     * תחליף לקו רגיל. id 46 (`Kosher 5000 MIN Plus 700 2025`, ₪26)
     * עובר היום **את כל** שערי הנוסח והמחיר, ונעצר כאן בלבד.
     *
     * `type` הוא הסימן השני על אותה רשומה: בכל 57 רשומות הסלולר
     * `type: "כשר"` מתקיים בדיוק כש-`spec.kosher === true` (שאר הטיפוסים
     * הם 5G / 4G / בסיס), ולכן הוא שומר על השער גם כשה-`spec` נקרא חלקית.
     *
     * ⚠️ וגם חבילת הגלישה: `spec.unlimitedData` כערך **אמת ולא כבוליאן**
     * (`"false"` — מה שמחלץ מייצר כשהוא קורא שדה טקסטואלי, הצורה
     * שההערה בענף הבית מתעדת במפורש) סיפק את דרישת הגלישה בזמן
     * ש-`dataGb` ריק, כלומר הכניס לבריכה **קו ללא גלישה כלל**. אותו
     * דבר ל-`dataGb`/`minutes`: `"100" > 0` ו-`"5000" >= 1000` הם אמת
     * ב-JS, והקטלוג נכנס דרך `as unknown as Catalog` בלי ולידציה.
     */
    if (spec.kosher !== false || (p.type ?? "").includes("כשר")) return false;
    const hasData =
      spec.unlimitedData === true || (typeof spec.dataGb === "number" && spec.dataGb > 0);
    return hasData && typeof spec.minutes === "number" && spec.minutes >= 1000;
  }
  /*
   * ⚠️ **גם אינטרנט וגם טלוויזיה**, ולא `hasInternet` לבדו.
   *
   * המסלול מציג את עצמו כ"אינטרנט וטלוויזיה" והמבקר מזין את החשבון
   * החודשי **הכולל** שלו. מתוך 25 חבילות הבית שעברו את הפילטר 13 הן
   * אינטרנט בלבד — כלומר מי שמשלם 220 ₪ על טריפל קיבל כותרת חיסכון
   * מול חבילה שאין בה טלוויזיה, והפער הזה הוא לא הנחה אלא שירות
   * שנעלם. התנאי הקודם חסם בדיוק את הכיוון ההפוך (TV בלבד) והשאיר
   * את זה פתוח.
   *
   * קו הטלפון עדיין אינו נדרש — הוא מוזכר בהסתייגות שמתחת למספר.
   *
   * ⚠️ `type !== "TV"` הוא **תיקון לנתון שגוי במקור**, לא הידור נוסף.
   * סטינג "החבילה המושלמת" רשומה `hasInternet: true` למרות שהיא שירות
   * סטרימינג בלבד ("שירות טלוויזיה הפועל על גבי האינטרנט") — המחלץ
   * קרא את המילה "אינטרנט" בתיאור. היא הזולה בקטגוריה, כלומר בלי
   * השורה הזו היא הופכת לחבילה שמולה נמדד כל חשבון טריפל בארץ.
   */
  // ⚠️ נתב שמתומחר מחוץ למחיר הוא חיוב חודשי שהכותרת לא רואה. ראה
  // `routerPricedSeparately`.
  if (routerPricedSeparately(p)) return false;
  const spec = p.spec as HomeSpec;
  /*
   * ⚠️ `=== true` ולא הערך עצמו. הפונקציה מוצהרת `p is MonthlyPackage`,
   * כלומר **בוליאן** — אבל `spec.hasInternet && …` החזיר את האופרנד
   * הראשון הכבוי, ועל רשומה שבה השדה חסר התוצאה הייתה `undefined`.
   * שער טיפוס שמחזיר `undefined` במקום `false` הוא בדיוק הסוג של
   * חוסר-דיוק ש-`isMoney` ו-`tierTable` נכתבו נגדו: `"true"` כמחרוזת
   * (הצורה שמחלץ מייצר כשהוא קורא שדה טקסטואלי) היה עובר כאן כאמת.
   */
  return spec.hasInternet === true && spec.hasTv === true && p.type !== "TV";
}

/**
 * המחיר לקו **שנשאר אחרי שההטבה נגמרת**.
 *
 * ⚠️ זה הלב של התיקון. `price` לבדו הוא מחיר ההטבה: HOT Synergy עולה
 * 21.9 ₪ והופך ל-57.9 ₪ בתום שנה — פי 2.64. כותרת שנתית שנבנתה על
 * 21.9 מנפחת את החיסכון פי 3.3, וגרוע מכך היא סותרת את ההבטחה של
 * הדף עצמו ("כולל המחיר אחרי תום ההטבה"). `afterPrice` כבר מחזירה את
 * המחיר הקבוע, וזה המספר היחיד שאפשר לעמוד מאחוריו לשנה שלמה.
 *
 * מדרגות הקווים מתומחרות על בסיס ההטבה, ולכן הן נלקחות בחשבון רק
 * כשהחבילה לא הצהירה על עלייה — אחרת היינו מערבבים מחיר מבצע לקו עם
 * מחיר קבוע ומקבלים סכום שאינו נכון באף נקודת זמן. (סלקום "משפחתי
 * פלוס" היא המקרה: 39.9 היום, 59.9 אחר כך, ומדרגות שמתומחרות מול
 * 39.9. 59.9 לכל כמות הוא המספר השמרני, ולכן הנבחר.)
 */
export function perLinePrice(p: MonthlyPackage, lines: number): number {
  const base = afterPrice(p);
  if (p.priceAfterPromo != null) return base;
  // ⚠️ `tierTable` ולא `tiers?.length`. ראה `tierTable`.
  const tiers = tierTable(p.spec as Partial<CellularSpec>);
  if (!tiers) return base;
  const tier = tiers.filter((t) => t != null && t.lines <= lines).sort((a, b) => b.lines - a.lines)[0];
  /*
   * ⚠️ `tier.price` כפי שהוא, ובלי `Math.min` מול המחיר הבסיסי.
   *
   * מדרגה היא המחיר שהמפעיל גובה בכמות הזו — לפעמים **גבוה** מהמחיר
   * המוצג. גולן "קיץ חם בדור 5" מוצגת ב-39.9 אבל דורשת 44.9 ₪ לקו
   * בשני קווים; `Math.min` החזיר 39.9 והציג לזוג חיסכון גדול ב-₪120
   * בשנה ממה שיקבלו בפועל.
   */
  return tier ? tier.price : base;
}

/**
 * כמות קווים שהמחיר בה **אינו ידוע**, למרות שיש מחיר רשום.
 *
 * ⚠️ ההנחה ש-`price` הוא תמיד המחיר לקו בודד אינה נכונה. גולן "קיץ חם
 * בדור 5" רשומה 39.9 ₪ — וזה מחיר **שלושה** קווים; התיאור מפרט "קו
 * בודד – 49.90 ₪, 2 קווים – 44.90 ₪ לקו, 3 קווים ומעלה – 39.90 ₪ לקו",
 * ו-`lineTiers` מתחיל ב-2. מי שביקש קו אחד קיבל 39.9 (נפילה ל-`base`
 * בהיעדר מדרגה מתאימה), כלומר כותרת מנופחת ב-₪120 בשנה מול מה שיגבו
 * ממנו בפועל — אותו סוג טעות ש-`Math.min` יצר לכיוון השני, רק שהפעם
 * היא נובעת מ**היעדר** מדרגה ולא ממדרגה שגויה.
 *
 * הזיהוי אינו פירסור של הטקסט אלא סתירה פנימית בנתונים עצמם: טבלת
 * מדרגות רק **מוזילה** ככל שמוסיפים קווים, ולכן מחיר בסיס **נמוך**
 * מהמדרגה בכמות הקטנה ביותר שהוצהרה אינו יכול להיות המחיר בכמות
 * קטנה עוד יותר. במצב כזה המחיר לכמות המבוקשת פשוט לא נמסר, ו"לא
 * יודעים — לא מבטיחים" הוא אותו כלל שכבר חל על עליות מחיר.
 *
 * Partner Star (39.9 בסיס, מדרגות מ-3 קווים ב-33) וסלקום 5G PRO
 * (59.9 בסיס, מדרגה 2 ב-59.9) עקביות ולכן נשארות.
 */
export function priceUnknownAtLines(p: MonthlyPackage, lines: number): boolean {
  // מחיר-אחרי-הטבה מדווח גובר על המדרגות בכל כמות. ראה `perLinePrice`.
  if (p.priceAfterPromo != null) return false;
  // ⚠️ `tierTable` ולא `tiers?.length`. ראה `tierTable`.
  const tiers = tierTable(p.spec as Partial<CellularSpec>);
  if (!tiers) return false;
  if (tiers.some((t) => t != null && t.lines <= lines)) return false;
  const smallest = tiers.filter((t) => t != null).sort((a, b) => a.lines - b.lines)[0];
  if (smallest == null) return false;
  return afterPrice(p) < smallest.price;
}

export interface Saving {
  /** החבילה שנבחרה, או `null` כשאין בקטגוריה חבילה בת-השוואה. */
  pick: MonthlyPackage | null;
  monthly: number;
  yearly: number;
  /** יש חבילה, והיא באמת זולה מהחשבון הנוכחי. */
  worthwhile: boolean;
  /**
   * מספר הקווים **המגודר** שהחישוב נעשה בו — לא ה-`units` שנמסר.
   *
   * ⚠️ והמחיר לקו שנגזר ממנו. שניהם כבר חושבו כאן, ולא נחשפו: הצרכן
   * היחיד גזר את המחיר מחדש ב-`perLinePrice(saving.pick, units)` עם
   * ה-`units` ה**לא מגודר**, ולכן שני מספרים על אותו מסך יכלו לסתור
   * זה את זה. נמדד על חבילה שמדרגתה מוצהרת ב-`lines: 1` (צורה שהקטלוג
   * משתמש בה) עם `units: 0`: המנוע חייב 20 בעוד הגזירה החזירה 12.
   * הגידור נעשה "כשער לקורא הבא" — ולכן התוצאה שלו היא מה שנחשף.
   */
  lines: number;
  /** המחיר לקו של `pick` ב-`lines` — המספר שעליו `monthly` נבנה. */
  perLine: number;
}

/**
 * ⚠️ מעוגל פעם אחת, והשנה נגזרת ממנו.
 *
 * חבילה במחיר 29.9 ₪ כפול שלושה קווים מייצרת "חיסכון של ₪1,563.6
 * בשנה" — והאגורות האלה הן בדיוק מה שגורם למספר להיראות מומצא.
 * חשוב מזה: עיגול נפרד לחודש ולשנה הציג שני מספרים שסותרים זה את זה
 * על אותו מסך (₪154 בחודש לצד ₪1,852 בשנה, כשהמכפלה היא 1,848).
 * לכן מעגלים את החודש ומכפילים — שתי השורות תמיד מסתדרות.
 */
/**
 * מספר הקווים הגבוה ביותר שהמחשבון מחשב עליו.
 *
 * ⚠️ הגידור היה מלמטה בלבד. הנימוק שגידר את הצד הנמוך — "הסלקטור מגיש
 * 1..10 ולכן זה שער לקורא הבא" — חל במדויק על הצד הגבוה, ולא יושם:
 * `computeSaving(PACKAGES, "cellular", 1e6, 1000)` החזיר `monthly`
 * של 29,899,000- ו-`yearly` של 358,788,000-. `worthwhile` הוא `false`
 * ולכן הכותרת לא הציגה את זה, אבל זה מספר חסר-פשר שיוצא מהמנוע.
 */
export const MAX_LINES = 10;

export function computeSaving(
  packages: Package[],
  track: Track,
  units: number,
  monthlySpend: number,
): Saving {
  /*
   * ⚠️ כמות הקווים מגודרת כאן, כמו שהסכום מגודר ב-`parseSpend`.
   *
   * `units` הוא `number` ולא "מספר קווים", והוא נכנס לחישוב גם כמכפיל
   * של העלות (`unitCount`). `0` מאפס את העלות לגמרי, ואז הכותרת הכריזה
   * על חיסכון בגובה **כל** החשבון (₪1,000 בחודש מול חבילה של ₪34),
   * ו-`-2` החזיר חיסכון **גדול** מהחשבון (₪1,068 מול ₪1,000) עם
   * `worthwhile: true` — הפרה של האינווריאנט היחיד שהקובץ הזה נבנה
   * סביבו. הסלקטור מגיש 1..10 ולכן זה שער לקורא הבא (ולמעבר מסלול,
   * שאינו מאפס את הבחירה) ולא באג מוצג.
   */
  const lines = Number.isInteger(units) && units >= 1 ? Math.min(units, MAX_LINES) : 1;
  /*
   * ⚠️ והסכום מגודר כאן באותה מידה, ומאותו נימוק מילה במילה.
   *
   * `MAX_LINES` נוסף אחרי שהתברר ש"הסלקטור מגיש 1..10 ולכן זה שער
   * לקורא הבא" חל גם על הצד הגבוה. `MIN_SPEND` ו-`MAX_SPEND` מוגדרים
   * בקובץ **הזה**, ו-`computeSaving` לא כיבד אף אחד מהם: `Infinity`
   * החזיר `worthwhile: true` עם `yearly: Infinity`, `NaN` החזיר
   * `monthly: NaN` (כלומר `Saving` שמבטיח `number` ואינו מקיים),
   * ו-`1e9` החזיר כותרת של ₪11,999,999,592 לשנה — פי 200,000 מהתקרה
   * שהקובץ הזה מצהיר עליה. הקיטום ב-`parseSpend` הוא שומר של **השדה**,
   * והוא לא השומר של המנוע: `computeSaving` מיוצאת, נבדקת ישירות,
   * ועוברת מסלול מעבר מסלול שאינו מאפס את הבחירה.
   *
   * הטווח 0..`MAX_SPEND` נשאר בדיוק כפי שהיה — כל הקוראים של היום
   * מעבירים פלט של `parseSpend`, ולכן אין כאן שינוי במספר מוצג.
   */
  const spend =
    Number.isFinite(monthlySpend) && monthlySpend > 0 ? Math.min(monthlySpend, MAX_SPEND) : 0;
  const pool = packages
    .filter((p): p is MonthlyPackage => isComparable(p, track))
    // ⚠️ תלוי-כמות, ולכן כאן ולא ב-`isComparable`. ראה `priceUnknownAtLines`.
    .filter((p) => !priceUnknownAtLines(p, lines))
    // ⚠️ מחיר "משפחתי" הוא מחיר לשני קווים ומעלה. ראה `familyPriceOnly`.
    .filter((p) => track !== "cellular" || lines >= 2 || !familyPriceOnly(p));
  const pick = pool.reduce<MonthlyPackage | null>(
    (best, p) => (best == null || perLinePrice(p, lines) < perLinePrice(best, lines) ? p : best),
    null,
  );
  if (!pick) return { pick: null, monthly: 0, yearly: 0, worthwhile: false, lines, perLine: 0 };

  // Cellular is priced per line; a home package is one household bill.
  const perLine = perLinePrice(pick, lines);
  const unitCount = track === "cellular" ? lines : 1;
  /*
   * ⚠️ `Math.floor` ולא `Math.round`. הכותרת אומרת "אפשר לחסוך **עד**",
   * והעיגול כלפי מעלה מוכפל אחר כך ב-12 — כלומר שגיאת העיגול גדלה פי
   * 12 לכיוון ההבטחה. מי שהקליד ₪220.50 (בדיוק הדוגמה שבהודעת השדה)
   * מול חבילה של ₪34 ראה "₪2,244 בשנה" במקום ₪2,238, ומי שהקליד
   * ₪34.50 ראה "₪12 בשנה" על חיסכון אמיתי של ₪6 — ניפוח של 100%,
   * ו-`worthwhile` שנדלק בזכות העיגול בלבד. עיגול כלפי מטה לעולם לא
   * מבטיח יותר ממה שיש, ושומר על `yearly === monthly * 12`.
   *
   * ⚠️ החיסור נעשה **באגורות** ולא בשקלים. `512.8 - 59.8` הוא
   * `452.99999999999994` ב-IEEE-754, ו-`Math.floor` עליו מחזיר 452
   * במקום 453 — ₪12 בשנה שנמחקים מהכותרת. השגיאה תמיד לכיוון החִסרון
   * ולכן היא לא ניפחה הבטחה, אבל היא הופיעה ב-690 סכומים על רשת של
   * אגורה (למשל ₪512.80–₪571.80 בשני קווים מול 29.9). עיגול כל אחד
   * מהאגפים לאגורה **לפני** החיסור מסיר גם את הסחף של `perLine * units`
   * (`29.9 * 10 === 299.00000000000006`).
   */
  const monthly = Math.floor(
    (Math.round(spend * 100) - Math.round(perLine * 100) * unitCount) / 100,
  );
  return {
    pick,
    monthly,
    yearly: monthly * 12,
    worthwhile: spend > 0 && monthly > 0,
    lines,
    perLine,
  };
}

/**
 * הסכום החודשי הנמוך ביותר שהמחשבון מוכן להתייחס אליו כחשבון אמיתי.
 *
 * ⚠️ `> 0` לבדו הכניס את `0.5` למסך: הכפתור נדלק, המחשבון הצהיר "אתם
 * כבר משלמים מעט יחסית", והנציג קיבל בהערה "משלם היום ₪0.5 בחודש".
 * החבילה הזולה בקטלוג היא 19.9 ₪, ולכן חשבון חד-ספרתי אינו סכום שנפל
 * בו קו אחד — הוא קלט שגוי, וצריך להיראות כך.
 */
export const MIN_SPEND = 10;

/**
 * הפורמט **השלם** של סכום שהמחשבון מקבל.
 *
 * ⚠️ זה התיקון לשורש של כל משפחת הבאגים הזו: הגרסה הקודמת **ניקתה**
 * את המחרוזת (`replace(/[^\d.]/g, "")`) ורק אחר כך חיפשה חריגות, ולכן
 * כל שומר נכתב בנפרד וכל אחד פספס משהו אחר. כאן המחרוזת כולה חייבת
 * להתאים לתבנית אחת, ומה שלא תואם נפסל — בלי "הצלה" שקטה:
 *
 *  • `1.200` — הכתיב האירופאי לאלף ומאתיים. השומר הקודם נכתב לפסיק
 *    בלבד ("יותר מנקודה אחת"), ולכן נקודה **בודדת** חמקה: הקלט הפך
 *    בשקט ל-1.2, המסך הצהיר "אתם משלמים ₪1.2 בחודש", והנציג קיבל את
 *    אותו מספר בהערה. זה בדיוק התרחיש של `220,5`, רק בכיוון ההפוך.
 *    לכן החלק העשרוני מוגבל לשתי ספרות — לחשבון חודשי אין שלוש.
 *  • `2 20` — רווח באמצע. `\s` היה ברשימת המותרים ונמחק בניקוי, כלומר
 *    טעות הקלדה של רווח אחד הכפילה סדר גודל. רווח מותר רק בקצוות.
 *
 * `1,200`, `₪ 1,200`, `1,200.50`, `220.5` ו-`0050` ממשיכים לעבוד.
 */
const AMOUNT = /^₪?\s*(?:\d{1,3}(?:,\d{3})+|\d+)(?:\.\d{1,2})?\s*₪?$/;

/**
 * קריאת הסכום שהמבקר הקליד.
 *
 * ⚠️ `\d` בלי הדגל `u` לא תופס ספרות ערביות-הודיות, ומקלדת ערבית בנייד
 * הייתה מרוקנת את המחרוזת ומשאירה את הכפתור מושבת בלי הסבר. לכן
 * הספרות מנורמלות ל-ASCII לפני הבדיקה.
 */
export function parseSpend(raw: string): number {
  const value = parseSpendRaw(raw);
  return value === 0 ? 0 : Math.min(value, MAX_SPEND);
}

/**
 * סימנים בלתי-נראים שנוסעים עם הדבקה — `\s` ב-JS אינו תופס אף אחד מהם.
 *
 * ⚠️ הרשימה נכתבה מול U+200E/200F (מה שדף עברי ואקסל עברי מעטיפים בו
 * סכום) ונעצרה שם, אף שאותו קובץ מנרמל במפורש **ספרות ערביות-הודיות**
 * ואת מפריד העשרוני `٫` ומפריד האלפים `٬`. כלומר הדבקה ממקלדת ומדף
 * ערביים היא מסלול נתמך בקובץ הזה — והסימן שהמסלול הזה נושא הוא דווקא
 * U+061C (ARABIC LETTER MARK), שלא היה ברשימה. נוספו גם U+200B/200C/200D
 * (ZWSP/ZWNJ/ZWJ), שנוסעים עם העתקה מדפי אינטרנט ומ-PDF.
 *
 * שתי התקלות הן אותן שתיים שתוקנו כבר פעמיים בשדה הזה: סכום תקין
 * שנפסל בזמן שהמסך מציע לגולש בדיוק את מה שכתוב בשדה מולו, והדבקת תא
 * ריק שהדליקה הודעת שגיאה מתחת לשדה שנראה ריק לגמרי (ראה `isBlankSpend`).
 *
 * ⚠️ קבוע **אחד** לשני הקוראים. `parseSpendRaw` החזיק עותק מוטבע
 * בתוכו, וההערה שם מסבירה רק למה לא לייבא את `stripBidi` מהשרת — לא
 * למה להחזיק שתי רשימות שחייבות להישאר זהות. זו ההיסטוריה של כל
 * שער בקובץ הזה שנשכח באחד הקוראים.
 */
const INVISIBLE = /[\u061c\u200b-\u200f\u202a-\u202e\u2066-\u2069]/g;

/**
 * האם השדה ריק בעיני הפרסור.
 *
 * ⚠️ `raw.trim()` **אינו** מספיק: `\s` ב-JS לא תופס סימני כיווניות,
 * ולכן הדבקה של תא ריק מאקסל עברי (תא שמכיל רק U+200F) נראתה כ"הוקלד משהו",
 * ו"יציאה מהשדה בלי להקליד אינה טעות" — החוזה שהמחשבון מצהיר עליו —
 * נשבר: השדה נראה ריק לחלוטין והודעת השגיאה נדלקה מתחתיו.
 */
export function isBlankSpend(raw: string): boolean {
  return raw.replace(INVISIBLE, "").trim() === "";
}

/**
 * אותה קריאה בדיוק, **בלי** הקיטום ל-`MAX_SPEND`.
 *
 * ⚠️ השדה במחשבון היה כותב את הערך המקוטע חזרה לתוך עצמו בכל הקשה,
 * ולכן מי שמשלם ₪5,200 ראה את השדה נתקע על `5,000` וכל תו נוסף נבלע —
 * והנציג קיבל בהערה סכום שהלקוח מעולם לא הזין. כדי שהשדה יוכל להציג
 * את מה שהוקלד ובכל זאת לחשב עד התקרה, הקיטום חייב להיות נפרד
 * מהקריאה.
 */
export function parseSpendRaw(raw: string): number {
  const ascii = raw
    /*
      ⚠️ סימני כיווניות ראשונים, לפני כל שאר הנירמול. דף עברי,
      אקסל וחשבונית של חברת סלולר מעטיפים סכום ב-U+200E/U+200F כדי
      שהתצוגה תיראה נכון, והם נוסעים עם ההדבקה. `\s` ב-JS אינו תופס
      אותם, ולכן `₪1,200` שהודבק מדף עברי נפסל — והמבקר קיבל
      הודעה שמציעה לו בדיוק את מה שכתוב בשדה מולו. זה הניקוי
      ש-`stripBidi` עושה לכל שדה שמגיע לשרת, רק שכאן הבדיקה רצה בדפדפן
      לפני שהשרת רואה את הערך (ובלי ייבוא — הקובץ רץ גם מתוך הבדיקה).

      ⚠️ הרשימה עצמה חיה ב-`INVISIBLE`, קבוע אחד שגם `isBlankSpend`
      קורא. כאן היה עותק מוטבע שלה, ושני העותקים התיישנו יחד: ראה
      שם למה U+061C ו-U+200B-200D הם אותו מסלול הדבקה בדיוק.
    */
    .replace(INVISIBLE, "")
    .replace(/[٠-٩۰-۹]/g, (d) => String((d.codePointAt(0)! - 0x0660) % 16))
    // אותה מקלדת מפיקה גם מפריד עשרוני `٫` ומפריד אלפים `٬` — בלי
    // השורה הזו `٢٢٠٫٥` נפסל בעוד שההודעה מציעה "220.50".
    .replace(/٫/g, ".")
    .replace(/٬/g, ",")
    .trim();
  if (!AMOUNT.test(ascii)) return 0;
  const value = Number(ascii.replace(/[^\d.]/g, ""));
  if (!Number.isFinite(value) || value < MIN_SPEND) return 0;
  return value;
}
