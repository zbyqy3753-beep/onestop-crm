/**
 * ⚠️ 6 הוא לא מספר שנבחר כאן — זו דרישת המינימום של Supabase Auth.
 * הסיסמה נשמרת שם, וסיסמה קצרה יותר תיפסל בקריאת ה-API עם שגיאה
 * באנגלית שאיש לא יבין. הבדיקה כאן היא רק כדי שההודעה תגיע בעברית
 * ולפני שנגענו בחשבון.
 */
export const MIN_PASSWORD_LENGTH = 6;

/**
 * מה לא בסדר בסיסמה, או `null` אם היא תקינה.
 *
 * מחזירה מחרוזת בעברית ולא boolean: העובד שמקבל "הסיסמה לא עומדת
 * בדרישות" בלי לדעת באיזו דרישה מנסה שוב ושוב את אותו רעיון.
 *
 * ⚠️ הפרמטר השני ירד יחד עם הכללים. הוא החזיק את המייל והשם כדי
 * לפסול סיסמה שמכילה אותם, ואין לו יותר קורא — מי שיחזיר כלל
 * תלוי-משתמש יחזיר גם אותו, ואת ארבעת מקומות הקריאה איתו.
 */
export function passwordProblem(password: string): string | null {
  if (password.length < MIN_PASSWORD_LENGTH) {
    return `הסיסמה חייבת להכיל לפחות ${MIN_PASSWORD_LENGTH} תווים`;
  }

  // ⚠️ רווחים בקצוות נפסלים ולא נחתכים בשקט: סיסמה שנחתכה בשמירה
  // ולא בהתחברות היא נעילה בחוץ שאי אפשר לאבחן.
  if (password !== password.trim()) {
    return "הסיסמה לא יכולה להתחיל או להסתיים ברווח";
  }

  return null;
}
