/**
 * רשימת השעות שנשלחת אחרי לחיצה על "לתאם שעה".
 *
 * ⚠️ **לא תבנית.** רשימה אינטראקטיבית אסורה בהודעה יזומה, ומותרת רק
 * בתוך חלון 24 השעות — ולכן היא יכולה לצאת רק אחרי שהלקוח לחץ. זו
 * גם הסיבה שהזרימה מפוצלת לשניים ולא מציעה שעות כבר בהודעה הראשונה.
 *
 * ⚠️ הגוף לא חוזר על ההצעה ולא מוכר שוב. הלקוח כבר הביע עניין בלחיצה;
 * כל משפט נוסף כאן רק דוחה את הרגע שבו הוא בוחר.
 */
