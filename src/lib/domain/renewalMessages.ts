/**
 * נוסח ההודעות שנשלחות **ללקוחות** בזרימת החידושים.
 *
 * ⚠️⚠️ הקובץ הזה נפרד מ-`whatsapp.ts` בכוונה, וההפרדה אינה ארגונית.
 * `whatsapp.ts` מכיל הודעות פנימיות לעובדים — נפח קטן, נמענים מוכרים,
 * אפס חשיפה. כאן מדובר בדיוור יוצא ללקוחות, שכפוף לכללים אחרים
 * לגמרי. ערבוב השניים באותו קובץ היה מזמין שימוש בתבנית פנימית מול
 * לקוח בטעות.
 *
 * ⚠️ **שורת ההסרה אינה קישוט ואסור להסיר אותה.** חוק התקשורת (תיקון
 * 40) מתיר דיוור שיווקי ללקוח עבר בלי הסכמה מפורשת, אבל **רק** כשיש
 * בכל הודעה דרך פשוטה להסיר. בלעדיה החשיפה היא פיצוי סטטוטורי לכל
 * הודעה, בלי הוכחת נזק. `parseReply` מזהה את המילה "הסר" ומכבד אותה
 * מיידית — שני הצדדים חייבים להתקיים יחד.
 */

/** שורת ההסרה. אחת, קבועה, ומופיעה בכל הודעה יוצאת ללקוח. */
const OPT_OUT_LINE = "להסרה מרשימת הדיוור השב: הסר";

export interface RenewalContactView {
  name: string;
}

/**
 * ההודעה הראשונה ללקוח.
 *
 * מבנה: מי אנחנו ושכבר היינו יחד → מה קורה עכשיו → מה אנחנו עושים
 * בשבילו → מה השאלה → איך להסיר.
 *
 * ⚠️ הזיהוי בפתיחה הוא חובה מעשית ולא נימוס: זו הודעה ראשונה ממספר
 * שהלקוח לא מכיר. בלי שם העסק בשורה הראשונה היא נקראת כהודעת הונאה,
 * והתגובה הצפויה היא חסימה ודיווח — שזה בדיוק מה שמסכן את המספר.
 *
 * ⚠️ **התזכורת שהוא כבר היה לקוח היא הליבה של ההודעה.** בלעדיה זו
 * פנייה קרה של מישהו שרוצה למכור לו משהו, ואיתה זו המשכיות של יחסים
 * קיימים — ההבדל בין "עוד שיווק" לבין "אלה שטיפלו בי חוזרים אליי".
 * זה גם מה שמעמיד את ההודעה בצד הנכון של חוק התקשורת: הפטור בתיקון
 * 40 נשען בדיוק על היות הנמען לקוח עבר.
 *
 * ⚠️ הטון הוא **דאגה ולא מכירה** — "לא נשאיר אותך עם זה". המחיר עולה
 * ממילא; מה שאנחנו מציעים זה לא להיתקע איתו לבד.
 *
 * ⚠️⚠️ **בלי ספק, בלי שם חבילה ובלי מחירים.** הגרסה המקורית ציטטה את
 * החבילה הנוכחית ואת המחיר לפני ואחרי, והנוסח יצא כמו חשבונית. שתי
 * בעיות: הוא נקרא כמו הודעה אוטומטית מהספק (כלומר ספאם), והוא חושף
 * מול לקוח שלא ביקש כלום שאנחנו מחזיקים את פרטי החבילה שלו. הפרטים
 * עדיין נחלצים מה-PDF ונשמרים על `RenewalContact` — הנציג רואה אותם
 * במסך החידושים לפני השיחה. הם פשוט לא נאמרים בהודעה.
 */
export function renewalOpener(c: RenewalContactView): string {
  return [
    `שלום ${c.name}, כאן ONE STOP! 🤝`,
    "",
    "זוכר אותנו? אנחנו אלו שדאגו לך לחבילת התקשורת שלך. 📱",
    "כשהצטרפת הבטחנו שתמיד תשלם כמה שפחות — ואנחנו כאן כדי לקיים.",
    "",
    "תקופת ההטבה שלך מסתיימת בקרוב ומחירי התקשורת עולים, אז ריכזנו עבורך את ההצעות המשתלמות ביותר בשוק. 🎯",
    "",
    "באיזו שעה נוח לך שנדבר? 📞",
    "",
    OPT_OUT_LINE,
  ].join("\n");
}

/**
 * אישור אחרי שהלקוח נקב בשעה.
 *
 * `label` מגיע מ-`parseReply` ומנוסח כבר בעברית ("מחר בין 17:00 ל-18:00").
 * הוא מוחזר ללקוח **במפורש** ולא כ"קבענו" סתם: זו ההזדמנות היחידה
 * שלו לתפוס שהבנו לא נכון, לפני שעובד מתקשר בזמן הלא נכון.
 *
 * ⚠️ התווית היא **טווח ולא נקודה** (ראה `WINDOW_MINUTES` ב-`reply.ts`),
 * ולכן הנוסח כאן חייב לסבול את שתיהן דקדוקית — "נחזור אליך {label}"
 * עובד גם עם "מחר בין 17:00 ל-18:00". הנוסח הקודם התחיל ב"אם השעה לא
 * מתאימה" והיה סותר את הטווח שהובטח שורה מעליו.
 */
export function renewalConfirmation(label: string): string {
  return [
    `מצוין, רשמנו לפנינו — נחזור אליך ${label}.`,
    "",
    "אם זה לא מתאים, פשוט השב לי כאן עם שעה אחרת.",
    "",
    OPT_OUT_LINE,
  ].join("\n");
}

/**
 * תשובה לבקשת הסרה.
 *
 * ⚠️ בלי שורת הסרה — היא כבר בוצעה, וחזרה עליה כאן הייתה נקראת
 * כאילו לא הבנו. זו גם ההודעה **האחרונה** שהלקוח יקבל מאיתנו.
 */
export function renewalOptOutAck(): string {
  return "הוסרת מרשימת הדיוור ולא תקבל מאיתנו הודעות נוספות. יום טוב!";
}

/** תשובה לסירוב — קצרה, בלי ניסיון שכנוע. */
export function renewalDeclineAck(): string {
  return ["תודה על העדכון, לא נטריד יותר בנושא.", "", OPT_OUT_LINE].join("\n");
}

/**
 * תשובה כשלא הצלחנו לפענח.
 *
 * ⚠️ **לא** שואלת שוב "באיזו שעה" בלולאה. אם הלקוח כתב משהו שלא
 * הבנו, שאלה חוזרת זהה תיתן את אותה תשובה שוב — ובינתיים הוא סומן
 * `needsReview` ועובד יראה אותו במסך ויתקשר.
 */
export function renewalUnclearAck(): string {
  return [
    "תודה, קיבלנו. נציג שלנו יחזור אליך בהקדם.",
    "",
    OPT_OUT_LINE,
  ].join("\n");
}
