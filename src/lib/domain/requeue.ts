/**
 * ── החייאת שורה מתה בתור ──────────────────────────────────────────────
 *
 * ⚠️ **מודול טהור, בלי שום ייבוא** — אותו שיקול כמו ב-`alerts.ts`.
 *
 * ⚠️⚠️ **הבעיה: מפתח דדופ מורעל.** `dedupeKey` הוא `@unique` גלובלי
 * ושורות לא נמחקות לעולם, ולכן שורה שבוטלה או נכשלה תופסת את המפתח
 * שלה **לנצח**. כל ניסיון ליצור אותה מחדש נדחה — ובשקט, כי ה-catch
 * ב-`enqueueForUser` בלע כל שגיאה כאילו היא "כבר בתור".
 *
 * בייצור נמצאו כך 12 לידים שהתזכורת שלהם לא תצא שוב לעולם. שני
 * המסלולים שמגיעים לשם:
 *
 * 1. נקבעה חזרה ל-16:00, שונתה ל-17:00 — `cancelSuperseded` ביטלה את
 *    השורה — והוחזרה ל-16:00. המפתח נגזר מ-`followUpAt`, ולכן הוא
 *    זהה, והשורה החדשה נדחית. במסך רואים חזרה, בתור אין כלום.
 * 2. השורה מיצתה את ניסיונותיה והפכה ל-`failed`. הליד עדיין מחזיק את
 *    אותו `followUpAt`, וכל תקתוק מנסה ליצור מחדש ונכשל בשקט.
 */

/**
 * עד כמה מאוחר עוד שווה להחיות.
 *
 * ⚠️⚠️ **בלי הגבול הזה התיקון גרוע מהבאג.** 12 הלידים שנמצאו הם
 * חזרות מאוגוסט; החייאה ללא תנאי הייתה מעירה את כולם בבת אחת
 * ושולחת מבול תזכורות על מועדים שעברו מזמן.
 *
 * ⚠️ אותם 48 שעות כמו `STALE_AFTER_MS` ב-`outbox.ts`, ובכוונה: שני
 * הכללים אומרים את אותו דבר — "מאוחר מדי מכדי להיות רלוונטי" —
 * ומספר שונה ביניהם היה יוצר שורה שמוחייאת ומיד מבוטלת כ-`stale`.
 */
export const REVIVE_WINDOW_MS = 48 * 3_600_000;

/**
 * האם שורה קיימת שחוסמת את המפתח ראויה להחייאה.
 *
 * ⚠️ **שורה חיה לעולם לא.** `queued` / `sending` / `sent` הם בדיוק
 * ה-no-op שהדדופ נועד לו, והחייאה שלהם הייתה מאפסת את הניסיונות של
 * הודעה שממש עכשיו יוצאת — או שולחת פעם שנייה משהו שכבר נשלח.
 */
export function shouldReviveRow(input: {
  status: string;
  /** מועד השליחה **החדש**, כפי שהקורא חישב אותו עכשיו. */
  scheduledFor: number;
  now: number;
}): boolean {
  if (input.status !== "cancelled" && input.status !== "failed") return false;
  return input.now - input.scheduledFor < REVIVE_WINDOW_MS;
}
