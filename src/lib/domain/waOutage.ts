/**
 * כמה כשלים ברצף הם חסימה.
 *
 * ⚠️ שלושה, ולא אחד: לכל מערכת יש מספר פסול פה ושם, ואדום על כשל בודד
 * הוא אדום קבוע שמלמדים להתעלם ממנו. ולא עשרה: `BATCH` בניקוז הוא 10,
 * כך שחסימה אמיתית חוצה שלושה כבר במחזור הראשון — כלומר תוך שתי דקות.
 */
export const OUTAGE_MIN_FAILURES = 3;

export interface WaOutage {
  /** מתי יצאה בפעם האחרונה הודעה שהצליחה. `null` = מעולם. */
  since: string | null;
  count: number;
  /** הטקסט הגולמי של מטא, כפי שנשמר ב-`lastError`. */
  error: string | null;
}

/**
 * האם השליחה חסומה — לפי הכשלים **מאז השליחה המוצלחת האחרונה**.
 *
 * ⚠️⚠️ הקישור להצלחה האחרונה הוא כל ההבדל בין התראה שימושית לרעש.
 * מספר טלפון פסול נכשל בזמן שכל השאר עוברים, וההצלחה מאפסת את המונה;
 * חסימה מערכתית מפילה את כולם ולכן המונה מטפס. ספירת כשלים מצטברת
 * בלי הקישור הזה עולה לנצח ומתריעה תמיד.
 *
 * ⚠️ הבאנר מנקה את עצמו: ברגע שהודעה אחת עוברת, אין יותר כשלים "מאז
 * ההצלחה האחרונה". אין כאן מצב שצריך לאפס ידנית ואין מה לסגור.
 */
export function detectOutage(input: {
  lastSentAt: string | null;
  /** כשלים מאז `lastSentAt` (או מאז ומתמיד, כשהוא `null`). */
  failedSinceCount: number;
  latestError: string | null;
}): WaOutage | null {
  if (input.failedSinceCount < OUTAGE_MIN_FAILURES) return null;

  return {
    since: input.lastSentAt,
    count: input.failedSinceCount,
    error: input.latestError,
  };
}

/**
 * מה לעשות עם השגיאה שמטא החזירה.
 *
 * ⚠️ **התרגום הוא הפעולה, לא התיאור.** "Business eligibility payment
 * issue" נכון לחלוטין ולא אומר למנהל שום דבר שהוא יכול לעשות איתו;
 * "החיוב נדחה, יש להסדיר תשלום ב-Billing Hub" כן.
 *
 * ⚠️ שגיאה שאינה ברשימה מחזירה `null`, והבאנר מציג את הגולמי. ניחוש
 * כאן היה שולח מנהל לתקן את הדבר הלא נכון.
 */
export function explainWaError(error: string | null): string | null {
  if (!error) return null;
  const text = error.trim().toLowerCase();

  for (const { match, hint } of HINTS) {
    if (text.includes(match)) return hint;
  }
  return null;
}

