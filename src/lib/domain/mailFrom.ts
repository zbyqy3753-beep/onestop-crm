/**
 * כותרת `From` — השם שהנמען רואה, לא רק הכתובת.
 *
 * ⚠️ **פונקציה ולא שרשור מחרוזות במקום השליחה.** כותרת `From` היא
 * בדיוק המקום שבו שם עם פסיק נקרא כשתי כתובות, שם עם גרש שובר את
 * הציטוט, ותו שורה חדשה מאפשר להזריק כותרות נוספות למייל — כולל
 * `Bcc`. השם מגיע ממשתנה סביבה, כלומר מבחוץ.
 *
 * ⚠️ **שם ריק מחזיר את הכתובת לבדה** ולא `"" <a@b.com>`. סוגריים
 * ריקים נראים ללקוח המייל כמו תקלה, ומעלים ניקוד ספאם.
 */
export function fromHeader(address: string, name?: string): string {
  const clean = (name ?? "")
    // תווי בקרה, ובראשם CR/LF — הזרקת כותרות
    .replace(/[\r\n\t\v\f\0]/g, "")
    .trim();

  if (clean.length === 0) return address;

  // סדר חשוב: הקו הנטוי ראשון, אחרת הוא היה מכפיל את מה שהמרכאות הוסיפו
  const quoted = clean.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
  return `"${quoted}" <${address}>`;
}
