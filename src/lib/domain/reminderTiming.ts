/**
 * ── מתי התזכורת יוצאת, ביחס למועד החזרה ────────────────────────────
 *
 * ⚠️ **מודול טהור, בלי שום ייבוא** — אותו שיקול כמו ב-`alerts.ts`:
 * זה מה שמאפשר למריץ הבדיקות של Node לייבא אותו ישירות.
 *
 * ⚠️⚠️ **הכותרת של התזכורת נגזרת מכאן, וזה בדיוק מה שנשבר.** עד
 * לתיקון הזה השאלה "האם ההודעה מאחרת" נמדדה מול **מועד השליחה
 * המתוכנן** (מועד החזרה פחות ההקדמה) ולא מול מועד החזרה עצמו.
 * השעון מנקז את התור אחת לכמה דקות, ומילוי התור קורה באותו מחזור,
 * ולכן חזרה שנקבעה ל-10:31 נכנסה לתור רק ב-10:25 — ארבע דקות אחרי
 * ה-10:21 המתוכנן. התוצאה אצל העובד: "⏰ תזכורת באיחור — החזרה
 * הייתה ב-10:31", שש דקות **לפני** שהחזרה הגיעה.
 *
 * חזרה שנקבעה לשעה עגולה נפלה בדיוק על תקתוק של השעון ויצאה נכון,
 * ולכן זה נראה אקראי: רק חזרות בדקה "לא עגולה" סבלו מזה.
 */

/**
 * חלון החסד. פער של פחות מדקה בין השליחה למועד החזרה הוא "עכשיו"
 * ולא איחור — הכרזת איחור על שלושים שניות היא רעש, לא מידע.
 */
const GRACE_MS = 60_000;

export interface ReminderTiming {
  /** מועד החזרה כבר עבר ברגע שההודעה יוצאת. */
  late: boolean;
  /** כמה דקות באמת נשארו עד החזרה. 0 כשהיא עכשיו או כבר עברה. */
  aheadMinutes: number;
}

/**
 * @param followUpAt מועד החזרה ללקוח.
 * @param sendsAt הרגע שבו ההודעה יוצאת בפועל — לא הרגע המתוכנן.
 */
export function reminderTiming(
  followUpAt: number,
  sendsAt: number,
): ReminderTiming {
  const diffMs = followUpAt - sendsAt;

  return {
    late: diffMs < -GRACE_MS,
    aheadMinutes: Math.max(0, Math.round(diffMs / 60_000)),
  };
}
