/**
 * שם משתמש → כתובת התחברות.
 *
 * ⚠️ **Supabase Auth מזהה משתמשים לפי מייל בלבד.** אין בו מושג של
 * "שם משתמש", ולכן כניסה עם `idan` לא יכולה לעבוד מולו ישירות. מה
 * שקורה כאן הוא הרחבה של הקלט: מי שמקליד שם בלבד מקבל אליו את דומיין
 * הארגון, ומה שנשמר בפועל — גם אצלנו וגם ב-Auth — הוא כתובת מלאה.
 *
 * המשמעות: `idan` ו-`idan@onestop.co.il` הם אותו חשבון בדיוק, וכל
 * המשתמשים הקיימים ממשיכים להתחבר עם המייל שלהם בלי שינוי.
 *
 * מודול נטול תלויות — נקרא גם מפעולת ההתחברות וגם מיצירת/עריכת
 * משתמש במסך הניהול, כדי ששני הצדדים ייצרו בדיוק את אותה מחרוזת.
 * אם הם יסטו זה מזה, משתמש ייווצר בכתובת אחת וינסה להתחבר באחרת.
 */

/**
 * הדומיין שמוצמד לשם משתמש בודד.
 *
 * ⚠️ שינוי הערך הזה **מנתק כל משתמש שנוצר עם שם בלבד** — הכתובת
 * שנשמרה לו לא תיווצר יותר מהשם שהוא מקליד. הוא לא נועד להשתנות
 * אחרי שקיימים חשבונות כאלה.
 */
export const LOGIN_DOMAIN = "onestop.co.il";

/**
 * מנרמל את מה שהוקלד בשדה ההתחברות לכתובת מייל מלאה.
 *
 * ⚠️ מחרוזת שכבר מכילה `@` מוחזרת כפי שהיא (למעט רווחים בקצוות)
 * ו**לא** מומרת לאותיות קטנות. זה מכוון: כתובות המשתמשים הקיימים
 * נשמרו כפי שהוקלדו, ו-`getByEmail` הוא חיפוש מדויק — הורדת רישיות
 * גורפת הייתה נועלת בחוץ כל מי שנרשם עם אות גדולה.
 *
 * שם בודד כן מומר לאותיות קטנות, כי הוא נתיב חדש: הכתובת נבנית ממנו
 * גם ביצירה וגם בכניסה, ולכן `Idan` ו-`idan` חייבים להוביל לאותו
 * מקום.
 */
export function toLoginEmail(input: string): string {
  const trimmed = input.trim();
  if (!trimmed) return "";
  if (trimmed.includes("@")) return trimmed;
  return `${trimmed.toLowerCase()}@${LOGIN_DOMAIN}`;
}

/**
 * האם המחרוזת תקפה כמזהה התחברות — שם משתמש או כתובת מלאה.
 *
 * לשם בודד: אותיות לועזיות, ספרות, נקודה, מקף וקו תחתון. עברית
 * חסומה בכוונה — היא תיצור כתובת מייל שמערכות אחרות (ובכללן
 * Supabase) לא בהכרח יקבלו, והתקלה תתגלה רק בניסיון ההתחברות.
 */
export function isValidLoginId(input: string): boolean {
  const trimmed = input.trim();
  if (trimmed.includes("@")) return /^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(trimmed);
  return /^[a-zA-Z0-9._-]{2,}$/.test(trimmed);
}
