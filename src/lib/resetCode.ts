/**
 * ── הקוד בן שש הספרות ─────────────────────────────────────────────────
 *
 * מודול טהור: אין בו מסד, אין בו `server-only`, ואפשר לבדוק אותו בלי
 * להרים כלום. כאן יושבים הכללים; המימוש שנוגע במסד יושב ב-
 * `server/auth/resetCode.ts`.
 *
 * ⚠️ **קוד בן 6 ספרות הוא סוד חלש — מיליון אפשרויות בלבד.** טוקן של
 * 256 ביט אפשר לשלוח בקישור ולשכוח ממנו; קוד קצר מחייב שלוש הגנות
 * שפועלות יחד, וכל אחת מהן לבדה לא מספיקה:
 *
 *   תפוגה קצרה   — 10 דקות, ולא 72 שעות כמו בקישור
 *   תקרת ניסיונות — 5, ואז הקוד מת ולא רק "נכשל"
 *   הגבלת בקשות  — אחרת אפשר לבקש קוד חדש בלי סוף ולנחש על כל אחד
 *
 * המספרים כאן הם התקן המקובל (RFC 6238 מדבר על חלונות של דקות, וכל
 * ספק OTP מסחרי נע בטווח 5-15 דקות). לא המצאנו כלום.
 */

/** אורך הקוד. שש ספרות — מה שאפשר להקריא בטלפון בלי טעויות. */
export const CODE_LENGTH = 6;

/** ⚠️ עשר דקות. ארוך מזה מגדיל את חלון הניחוש בלי להועיל למשתמש. */
export const CODE_TTL_MS = 10 * 60 * 1000;

/**
 * ⚠️ חמישה ניסיונות ואז הקוד **מת**, לא רק "נכשל".
 *
 * ההבדל מהותי: קוד שממשיך לחיות אחרי כישלון מאפשר לנחש עד התפוגה.
 * חמישה ניסיונות מתוך מיליון הם סיכוי של 1 ל-200,000 — ומי שנכשל
 * מבקש קוד חדש, וזה כבר נספר בהגבלת הבקשות.
 */
export const MAX_CODE_ATTEMPTS = 5;

/**
 * הקוד כפי שהמשתמש מקליד אותו — ספרות בלבד.
 *
 * ⚠️ מנקה רווחים ומקפים לפני הבדיקה. אנשים מדביקים קוד מהודעה
 * ולפעמים גוררים איתו רווח, וזו לא סיבה להיכשל.
 */
export function normalizeCode(raw: string): string {
  return raw.replace(/[\s-]/g, "");
}

/** האם המחרוזת נראית כמו קוד בכלל — לפני שנוגעים במסד. */
export function isCodeShape(raw: string): boolean {
  const code = normalizeCode(raw);
  return code.length === CODE_LENGTH && /^\d+$/.test(code);
}

/**
 * ⚠️ הקוד נבנה מ-`crypto.randomInt` ולא מ-`Math.random`.
 *
 * `Math.random` אינו קריפטוגרפי: הוא ניתן לחיזוי מתוך פלטים קודמים,
 * וכאן הפלט הזה הוא מפתח לחשבון. הפונקציה מקבלת את מחולל המספרים
 * מבחוץ כדי שהמודול יישאר טהור וניתן לבדיקה דטרמיניסטית.
 */
export function formatCode(value: number): string {
  return String(value % 10 ** CODE_LENGTH).padStart(CODE_LENGTH, "0");
}

/**
 * המספר כפי שמוצג למי שביקש קוד — ארבע ספרות אחרונות בלבד.
 *
 * ⚠️ **בלי זה המסך אומר "נשלח קוד" ולא לאן.** עובד שהטלפון שלו במערכת
 * לא מעודכן ממתין להודעה שלא תגיע, בלי שום דרך להבין למה — וזה נראה
 * כמו מערכת שבורה ולא כמו נתון שגוי בכרטיס שלו.
 *
 * ⚠️ ארבע ספרות ולא המספר המלא: מי שמגיע למסך הזה כבר עבר את שער
 * הזכאות, אבל אין סיבה להדפיס מספר טלפון מלא של עובד על מסך פתוח.
 */
export function maskPhone(phone: string): string {
  const digits = phone.replace(/\D/g, "");
  if (digits.length < 4) return "•".repeat(4);
  return `${"•".repeat(3)}${digits.slice(-4)}`;
}
