import "server-only";

import { createHash, randomBytes } from "node:crypto";

/**
 * הטוקן של עוגיית הסשן.
 *
 * ⚠️ הטוקן הוא הסוד היחיד — הוא **לא** נגזר משום דבר ולא מקודד שום
 * מידע. זו הנקודה: הערך בעוגייה חסר משמעות בפני עצמו, ולכן אי אפשר
 * לזייף אותו בעריכה (כמו שהיה אפשר כשהעוגייה הכילה מזהה משתמש).
 *
 * ב-DB נשמר רק ה-hash. מי שמשיג גישת קריאה למסד לא יכול להרכיב ממנו
 * עוגייה תקפה, כי SHA-256 חד-כיווני. זו הסיבה שאין כאן פונקציה
 * שמחזירה טוקן מתוך hash — היא לא אפשרית, וזה הרעיון.
 *
 * 32 בתים אקראיים = 256 ביט אנטרופיה. ניחוש הוא לא מודל תקיפה כאן.
 */

const TOKEN_BYTES = 32;

/** טוקן חדש, base64url — בטוח לעוגייה בלי קידוד נוסף. */
export function createSessionToken(): string {
  return randomBytes(TOKEN_BYTES).toString("base64url");
}

/**
 * ה-hash שנשמר במסד. הפונקציה היחידה שמחברת בין השניים.
 *
 * בלי salt ובלי KDF איטי בכוונה: אלה נחוצים לסיסמאות, שהן קצרות
 * ובעלות אנטרופיה נמוכה. טוקן אקראי של 256 ביט לא ניתן לתקיפת
 * מילון או קשת בענן, ו-hash איטי כאן היה עולה בכל בקשה ובקשה.
 */
export function hashSessionToken(token: string): string {
  return createHash("sha256").update(token).digest("hex");
}
