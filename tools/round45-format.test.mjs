import assert from "node:assert/strict";
import { test } from "node:test";

import { basePackages, byCategory, listable } from "../src/app/lp/catalog/catalog.ts";
import { routerDetail } from "../src/app/lp/catalog/format.ts";

/*
 * ⚠️ סבב 45 — "המחיר כולל נתב" בלי סכום.
 *
 * `ROUTER_INCLUDED_PRICE` דרשה סכום שצמוד להצהרה, בזמן שההערה שלה
 * מצהירה על הכלל במילים "הרשומה מסרה שהמחיר כולל את הנתב, ולא מסרה
 * מה הנתב שווה בנפרד" — נימוק שאינו תלוי בקיומו של מספר. שלוש
 * רשומות חיות מצהירות בלי סכום ולא קיבלו שורה כלל.
 *
 * ההוכחה החדה: ids 86 ו-98 הן אותה רשומה של Partner, עם אותה שורת
 * "*כולל נתב" — ו-98 נתפסה רק מפני שבמקרה היא כותבת גם "139 שח
 * כולל נתב". טבלת ההשוואה הציגה "נתב: — ‖ כלול במחיר" על שתי
 * רשומות שמסרו את אותה עובדה.
 */

const home = byCategory(listable(basePackages()), "home");
const byId = (id) => home.find((p) => String(p.id) === String(id));

test("סבב 45: הצהרת `כולל נתב` בלי סכום מדפיסה `כלול במחיר`", () => {
  // שלוש הרשומות שלא קיבלו שורה כלל לפני התיקון.
  for (const id of ["3", "99", "86"]) {
    assert.equal(routerDetail(byId(id)), "כלול במחיר", `id ${id}`);
  }
});

test("סבב 45: אותה רשומה בשני ניסוחים אינה סותרת את עצמה", () => {
  // 86 ו-98 הן אותו Partner DIRECT FIBER; הן חייבות להסכים.
  assert.equal(routerDetail(byId("86")), routerDetail(byId("98")));
});

test("סבב 45: ההצהרה השלילית נשארת שלילית", () => {
  /*
   * ⚠️ id 114 כותבת "199 ש״ח לא כולל נתב" לצד "220 שח כולל נתב".
   * בלי הלוויין השלילי על הצורה חסרת-הסכום היא הייתה מתהפכת
   * ל-"כלול במחיר" — ההפך ממה שהרשומה אומרת.
   */
  assert.equal(routerDetail(byId("114")), "המחיר אינו כולל נתב · ₪220 לחודש עם נתב");

  // ואותה הצהרה שלילית בלי סכום כלל אינה הופכת לחיובית.
  const bare = { ...byId("3"), id: "t", description: "המחיר אינו כולל נתב", benefits: null };
  assert.equal(routerDetail(bare), null);
});

test("סבב 45: סכום שאינו המחיר שבכותרת ממשיך לא להדפיס שורה", () => {
  /*
   * ⚠️ הענף שנוקב בסכום מכריע לבדו ואינו נופל לצורה חסרת-הסכום:
   * רשומה שמסרה "220 שח כולל נתב" על מחיר 199 אמרה משהו על חבילה
   * אחרת, וההכרעה הזו נשמרת.
   */
  const mismatch = {
    ...byId("3"),
    id: "t",
    price: 199,
    description: "220 שח כולל נתב",
    benefits: null,
  };
  assert.equal(routerDetail(mismatch), null);
});

test("סבב 45: שורות הנתב שכבר הודפסו לא זזו", () => {
  // ⚠️ נמדד לפני ואחרי: רק ids 3/99/86 נוספו, שאר הקבוצה זהה.
  const rows = home
    .map((p) => [String(p.id), routerDetail(p)])
    .filter(([, v]) => v != null)
    .sort(([a], [b]) => Number(a) - Number(b));
  assert.deepEqual(rows, [
    ["3", "כלול במחיר"],
    ["81", "ללא עלות"],
    ["82", "כלול במחיר"],
    // ⚠️ סבב 46: "לחודש" נוסף לשתי הרשומות שמוסרות את התקופה במילים
    // (85, 124) — ראה ההערה ב-`round41-format`. המספר לא זז.
    ["85", "₪25 לחודש בתוספת למחיר"],
    ["86", "כלול במחיר"],
    ["98", "כלול במחיר"],
    ["99", "כלול במחיר"],
    ["104", "₪20 בתוספת למחיר · ללא עלות למשך שנה"],
    ["112", "כלול במחיר"],
    ["113", "כלול במחיר"],
    ["114", "המחיר אינו כולל נתב · ₪220 לחודש עם נתב"],
    ["115", "כלול במחיר"],
    ["124", "₪20 לחודש בתוספת למחיר"],
    ["158", "₪20 בתוספת למחיר · ללא עלות למשך שנה"],
  ]);
});
