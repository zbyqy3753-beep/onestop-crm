import assert from "node:assert/strict";
import { test } from "node:test";

import { basePackages } from "../src/app/lp/catalog/catalog.ts";
import { compareRows, routerDetail } from "../src/app/lp/catalog/format.ts";

const pkgs = basePackages();
const byId = (id) => pkgs.find((p) => String(p.id) === id);
const tierRow = (ids) =>
  compareRows(ids.map(byId)).find((r) => r.label === "מחיר לפי מספר קווים");

/*
 * ⚠️ סבב 46 — מחיר מדרגה שהרשומה הגבילה בזמן הודפס כמחיר קבע.
 *
 * `tierLines` קורא מהפרוזה את מגדיר ה**כמות** בלבד ומתעלם ממגדיר הזמן
 * שיושב באותו משפט. זוג הבקרה 36/37 הוא ההוכחה: מבנה מדרגות זהה, שתי
 * שורות שנראו זהות לחלוטין בטבלה — בזמן ש-36 מגבילה את שתי המדרגות
 * ב-"למשך 13 מחזורי החיוב הראשונים" ומוסרת במפורש ₪64.90 לאותה מדרגה
 * אחרי שנה, ו-37 אינה מגבילה כלל.
 */
test("סבב 46: מחירי מדרגה מוגבלים בזמן מודפסים עם התקופה", () => {
  const row = tierRow(["36", "37"]);
  assert.equal(
    row.values[0],
    "עד 2 קווים ₪39.9 · 3 קווים ומעלה ₪34.9 (למשך 13 מחזורי החיוב הראשונים)",
  );
  // id 37 היא הבקרה — אותו מבנה, בלי הגבלת זמן בפרוזה, ולכן בלי סימן.
  assert.equal(row.values[1], "עד 2 קווים ₪59.9 · 3 קווים ומעלה ₪54.9");
  assert.notEqual(row.values[0], row.values[1]);
});

test("סבב 46: id 57 נושאת 'למשך שנה', ו-id 68 מצהירה קבע ולכן נקייה", () => {
  const row = tierRow(["57", "68"]);
  assert.equal(row.values[0], "2–3 קווים ₪33 · 4 קווים ומעלה ₪30 (למשך שנה)");
  // ⚠️ "המחיר קבוע – לכל החיים!" מנצח את המילה "למשך" אם היא מופיעה
  // במקום אחר ברשומה.
  assert.equal(row.values[1], "2 קווים ₪44.9 · 3 קווים ומעלה ₪39.9");
});

/*
 * ⚠️ "לחודש" נפל מתוספת הנתב.
 *
 * `routerDetail` בנה `₪25 בתוספת למחיר` בלי שום ציון תקופה גם כשהרשומה
 * אומרת "לחודש" במילים, בזמן שהענף התאום באותה שורה בטבלה
 * (`includedRouterSurcharge`) מדפיס "בתוספת ₪4.9 לחודש". הגולש שמשווה
 * id 85 מול id 92 ראה ₪25 שנקרא כחד-פעמי לצד ₪4.9 שמוצהר כחודשי —
 * דווקא התוספת היקרה נראתה הזולה, הפרש של ₪300 בשנה.
 */
test("סבב 46: תוספת נתב שהרשומה מצהירה כחודשית מודפסת 'לחודש'", () => {
  assert.equal(routerDetail(byId("85")), "₪25 לחודש בתוספת למחיר");
  assert.equal(routerDetail(byId("124")), "₪20 לחודש בתוספת למחיר");
  const row = compareRows([byId("85"), byId("92")]).find((r) => r.label === "נתב");
  assert.equal(row.values[0], "₪25 לחודש בתוספת למחיר");
  // הענף התאום, שממנו נלקחה הנורמליזציה.
  assert.equal(row.values[1], "כלול במחיר · בתוספת ₪4.9 לחודש");
});

test("סבב 46: סכום בלי תקופה צמודה נשאר בלי 'לחודש'", () => {
  /*
   * ⚠️ הבקרה בכיוון ההפוך: ids 158/104 נוקבות באותו סכום **בלי**
   * תקופה ("עלות נתב אינטרנט 20שח") וכותבות "למשך שנה" על ההטבה
   * במשפט שאחריו. הבדיקה היא על הטקסט הצמוד לסכום, ולכן הן אינן
   * מקבלות תקופה שהרשומה לא מסרה.
   */
  assert.equal(routerDetail(byId("158")), "₪20 בתוספת למחיר · ללא עלות למשך שנה");
  assert.equal(routerDetail(byId("104")), "₪20 בתוספת למחיר · ללא עלות למשך שנה");
});
