import assert from "node:assert/strict";
import { test } from "node:test";

import { basePackages } from "../src/app/lp/catalog/catalog.ts";
import { detailRows } from "../src/app/lp/catalog/format.ts";

/*
 * ⚠️ סבב 49 — שתי הצהרות שחצי מהן נקרא והחצי השני הומצא או הורחב.
 *
 *   • `housingQualifiers` קרא את הצד **החינמי** של המשפט ("מעל 4
 *     דירות ללא עלות") והרכיב את הצד המשלם בעצמו כ-"עד 4 דירות",
 *     בזמן שהרשומה אומרת "מתחת ל 4 דירות" באותו משפט. "עד 4" כולל
 *     ארבע, "מתחת ל-4" לא.
 *   • `tierPricesPeriod` לקח התאמה אחת והדפיס אותה כסיומת של כל
 *     השורה, ולכן הגביל בזמן גם את המדרגה היחידה שהרשומה מוסרת בלי
 *     הגבלה.
 */

const PKGS = basePackages();
const byId = (id) => PKGS.find((p) => p.id === id);
const rowValue = (id, label) =>
  detailRows(byId(id)).find((r) => r.label === label)?.value;

/** שש הרשומות שנושאות את המשפט הזה מילה במילה. */
const HOUSING = ["157", "92", "102", "107", "108", "109"];

test("סבב 49: הצד המשלם נקרא מהרשומה — `מתחת ל 4` ולא `עד 4`", () => {
  for (const id of HOUSING) {
    const value = rowValue(id, "עלות התקנה");
    assert.equal(
      value,
      "ללא עלות בבניין מעל 4 דירות · ₪499 לבית פרטי או מתחת ל 4 דירות",
      id,
    );
    /*
     * ⚠️ והנקודה החדה: בניין של **ארבע** דירות אינו בצד המשלם. זה
     * המצב שהרשומה מוסרת בו "ללא עלות", והשורה גבתה עליו ₪499.
     */
    assert.ok(!value.includes("עד 4 דירות"), id);
  }
  // id 157 היא הרשומה שהמחשבון מצטט בכל קלט במסלול הבית.
  assert.ok(rowValue("157", "עלות התקנה").includes("מתחת ל 4 דירות"));
});

test("סבב 49: בלי הצהרה על הצד המשלם, השורה אינה מבטיחה מספר דירות", () => {
  /*
   * ההשלמה הזהירה נשמרת: ids 3 ו-82 מצהירות על התניה בלי לנקוב
   * בכמות דירות, ולכן הן נשארות עם "בבניין" / "לבית פרטי" בלבד —
   * "לא יודעים, לא מבטיחים".
   */
  for (const id of ["3", "82"]) {
    const value = rowValue(id, "עלות התקנה");
    assert.equal(value, "ללא עלות בבניין · ₪499 לבית פרטי", id);
    assert.ok(!/\d+ דירות/.test(value), id);
  }
  // ו-ids 73/153/154/159 — "לבניין לזמן מוגבל" — לא זזו.
  for (const id of ["73", "153", "154", "159"]) {
    assert.equal(rowValue(id, "עלות התקנה"), "ללא עלות בבניין לזמן מוגבל · ₪125 לבית פרטי", id);
  }
  // ו-ids 158/104 — ההתניה על הסיב — לא זזו.
  for (const id of ["158", "104"]) {
    assert.equal(rowValue(id, "עלות התקנה"), "ללא עלות כשיש סיב מותקן · ₪499 כשאין", id);
  }
});

test("סבב 49: התקופה יושבת על המדרגה שהרשומה הגבילה, ולא על השורה", () => {
  /*
   * id 57 אומרת "למצרפים 2-3 מנויים – 33 ₪ **למשך שנה**, למצרפים 4
   * מנויים ויותר 30 ₪" — המדרגה השנייה בלי שום הגבלת זמן. הסיומת
   * הגורפת ייחסה לרשומה הגבלה שהיא לא אמרה, כלומר הבטיחה לגולש פחות
   * ממה שהרשומה נותנת.
   */
  assert.equal(
    rowValue("57", "מחיר לפי מספר קווים"),
    "2–3 קווים ₪33 (למשך שנה) · 4 קווים ומעלה ₪30",
  );
});

test("סבב 49: כששתי המדרגות חולקות תקופה, הסיומת נשארת אחת בסוף", () => {
  // id 36 מגבילה את **שתי** מדרגותיה לאותה תקופה, ולכן השורה שלו על
  // המסך אינה זזה — ושתי הצורות אינן נראות זהות.
  assert.equal(
    rowValue("36", "מחיר לפי מספר קווים"),
    "עד 2 קווים ₪39.9 · 3 קווים ומעלה ₪34.9 (למשך 13 מחזורי החיוב הראשונים)",
  );
  // ids 37 ו-68 הן הבקרה: 37 אינה מגבילה בזמן, 68 מצהירה קבע.
  assert.equal(rowValue("37", "מחיר לפי מספר קווים"), "עד 2 קווים ₪59.9 · 3 קווים ומעלה ₪54.9");
  assert.equal(rowValue("68", "מחיר לפי מספר קווים"), "2 קווים ₪44.9 · 3 קווים ומעלה ₪39.9");
  assert.notEqual(
    rowValue("36", "מחיר לפי מספר קווים"),
    rowValue("37", "מחיר לפי מספר קווים"),
  );
});

test("סבב 49: התקופה נקראת מהמדרגה ולא ממחיר הקו הבודד", () => {
  /*
   * ⚠️ ההתאמה הראשונה בפרוזה של id 57 היא "39.9 ₪ למנוי למשך שנה" —
   * מחיר הקו הבודד, מספר שהשורה הזו אפילו לא מדפיסה. כאן אותה פרוזה
   * בלי שום הצהרת זמן על מדרגה: השורה חייבת לצאת נקייה.
   */
  const p = structuredClone(byId("57"));
  p.description = "מחיר התוכנית – 39.9 ₪ למנוי למשך שנה. למצרפים 2-3 מנויים – 33 ₪, למצרפים 4 מנויים ויותר 30 ₪";
  p.benefits = "";
  const value = detailRows(p).find((r) => r.label === "מחיר לפי מספר קווים")?.value;
  assert.equal(value, "2–3 קווים ₪33 · 4 קווים ומעלה ₪30");
  assert.ok(!value.includes("למשך"));
});

test("סבב 49: אפס נגרר בפרוזה נספר — `34.90` היא המדרגה 34.9", () => {
  // הקטלוג כותב "34.90" במקום שהמדרגה מחזיקה 34.9, ולכן הסכום
  // מורכב מהמדרגה עם אפס אופציונלי ולא נקרא כמספר חופשי.
  assert.ok(rowValue("36", "מחיר לפי מספר קווים").includes("(למשך 13 מחזורי החיוב הראשונים)"));
});
