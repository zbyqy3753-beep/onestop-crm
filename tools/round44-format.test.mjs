import assert from "node:assert/strict";
import { test } from "node:test";

import { basePackages, listable } from "../src/app/lp/catalog/catalog.ts";
import { compareRows, detailRows } from "../src/app/lp/catalog/format.ts";

/*
 * ⚠️ סבב 44 — הצד **החיובי** של הצהרת הנתב, שנשאר פתוח אחרי שהשלילי
 * נסגר. אותה משפחה בדיוק: שער שמכיר הצהרה בצורה אחת ומפספס את השכנה.
 *
 * `ROUTER_EXCLUDED_PRICE` קורא "199 ש״ח לא כולל נתב … 220 שח כולל נתב"
 * (id 114), ואין קורא ל-"<מחיר> ש״ח כולל נתב" — הצורה שחמש רשומות
 * חיות משתמשות בה. התוצאה אינה חוסר-גילוי בלבד אלא השוואה מטעה:
 * בטבלה שורת `נתב` נתנה ל-112 את `"—"` ול-114 שורה מלאה, בזמן
 * שעלות ההתקנה והמגדיל זהות — כלומר הגולש קרא פער של ₪30 במקום ₪51.
 */

const live = listable(basePackages());
const byId = (id) => live.find((p) => String(p.id) === String(id));
const routerRow = (p) => detailRows(p).find((r) => r.label === "נתב")?.value ?? null;

test("format: '<מחיר> ש״ח כולל נתב' מודפס כ'כלול במחיר' בחמש הרשומות החיות", () => {
  for (const id of ["82", "98", "112", "113", "115"]) {
    assert.equal(routerRow(byId(id)), "כלול במחיר", `id ${id}`);
  }
});

test("format: הצורה השלילית לא זזה — id 114 ממשיך למסור את המחיר עם הנתב", () => {
  // ⚠️ 114 נושאת את שתי הצורות גם יחד ("כולל נתב" בשורת השירות,
  // ו-"199 ש״ח לא כולל נתב" אחריה). השלילית נבדקת ראשונה, ובנוסף
  // ה-220 שלה אינו המחיר שבכותרת — ולכן שני שערים מפרידים ביניהן.
  assert.equal(routerRow(byId("114")), "המחיר אינו כולל נתב · ₪220 לחודש עם נתב");
});

test("format: שורת הנתב בטבלת ההשוואה אינה מכחישה עובדה שהרשומה מסרה", () => {
  const row = compareRows([byId("112"), byId("114")]).find((r) => r.label === "נתב");
  assert.deepEqual(row.values, ["כלול במחיר", "המחיר אינו כולל נתב · ₪220 לחודש עם נתב"]);
  // ⚠️ זה הממצא עצמו: לפני התיקון הערך הראשון היה `"—"`.
  assert.ok(!row.values.includes("—"));
});

test("format: סכום שאינו המחיר שבכותרת אינו מייצר 'כלול במחיר'", () => {
  /*
   * ⚠️ השער שמונע את הטעות ההפוכה. בלי תנאי השוויון למחיר, id 114
   * הייתה מקבלת "כלול במחיר" על ₪220 — מחיר שאינו זה שהכרטיס מציג.
   * נמדד על עותק שה-`price` שלו הוזז: ההצהרה נשארת, השורה נעלמת.
   */
  const moved = { ...byId("112"), price: 171 };
  assert.equal(routerRow(moved), null);
});

test("format: התיקון רק מוסיף — חמש שורות חדשות ואף אחת לא נעלמה", () => {
  /*
   * ⚠️ נמדד לפני ואחרי על 106 הרשומות המוצגות. לפני התיקון שורת
   * `נתב` הודפסה ב-15 רשומות, ואחריו ב-20: נוספו בדיוק
   * 82, 98, 112, 113, 115 — חמש הרשומות שנושאות את הצורה החיובית —
   * ואף רשומה לא יצאה מהרשימה. זו המחצית שהקובץ הזה מקבע: תיקון
   * גילוי אינו אמור לכבות גילוי קיים.
   */
  const withRow = live.filter((p) => routerRow(p) != null).map((p) => String(p.id));
  const before = ["102", "104", "107", "108", "109", "114", "124", "157", "158", "70", "71", "72", "81", "85", "92"];
  const added = ["82", "98", "112", "113", "115"];
  assert.deepEqual([...withRow].sort(), [...before, ...added].sort());
  for (const id of before) assert.ok(withRow.includes(id), `id ${id} נעלם`);
});
